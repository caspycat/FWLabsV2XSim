function paths = schemaLeafPaths(node, prefix)
kind = string(node.Kind);
if kind == "table"
    paths = strings(0,1);
    names = string(fieldnames(node.Children));
    for name = names.'
        if prefix == ""
            childPrefix = name;
        else
            childPrefix = prefix + "." + name;
        end
        paths = [paths; schemaLeafPaths( ...
            node.Children.(name),childPrefix)]; %#ok<AGROW>
    end
elseif kind == "arrayOfTables"
    paths = schemaLeafPaths(node.Element,prefix + "[]");
else
    paths = prefix;
end
end

function values = schemaEnumValues(node)
kind = string(node.Kind);
values = strings(0,1);
if ~isempty(node.AllowedStrings)
    values = string(node.AllowedStrings(:));
end
if kind == "table"
    names = string(fieldnames(node.Children));
    for name = names.'
        values = [values; schemaEnumValues( ...
            node.Children.(name))]; %#ok<AGROW>
    end
elseif kind == "arrayOfTables"
    values = [values; schemaEnumValues(node.Element)];
end
values = unique(values(values ~= ""),"stable");
end

