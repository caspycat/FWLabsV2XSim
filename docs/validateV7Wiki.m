function report = validateV7Wiki(wikiDirectory, options)
%VALIDATEV7WIKI Check the V7 GitHub Wiki's local documentation contracts.
%   REPORT = VALIDATEV7WIKI(WIKIDIRECTORY) verifies that the complete
%   first-release page set exists, local Markdown links resolve, critical
%   public configuration/output tokens remain documented, and canonical
%   example files referenced by the wiki exist in this repository.

arguments (Input)
    wikiDirectory (1,1) string = defaultWikiDirectory()
    options.ThrowOnFailure (1,1) logical = true
end

arguments (Output)
    report (1,1) struct
end

if ~isfolder(wikiDirectory)
    error( ...
        "v2xsimdocs:wiki:DirectoryNotFound", ...
        "The wiki directory does not exist: %s",wikiDirectory);
end

projectRoot = fileparts(fileparts(mfilename("fullpath")));
requiredPages = wikiPageNames();
failureKind = strings(0,1);
source = strings(0,1);
detail = strings(0,1);

for page = requiredPages
    pageFile = fullfile(wikiDirectory,page + ".md");
    if ~isfile(pageFile)
        [failureKind,source,detail] = appendFailure( ...
            failureKind,source,detail, ...
            "MissingPage",page,pageFile);
    end
end

markdownFiles = dir(fullfile(wikiDirectory,"*.md"));
checkedLinkCount = 0;
wikiCorpus = "";
for fileIndex = 1:numel(markdownFiles)
    pageFile = fullfile( ...
        markdownFiles(fileIndex).folder,markdownFiles(fileIndex).name);
    pageText = string(fileread(pageFile));
    wikiCorpus = wikiCorpus + newline + pageText;
    linkTargets = markdownLinkTargets(pageText);
    for linkTarget = linkTargets
        if isExternalOrAnchor(linkTarget)
            continue
        end
        checkedLinkCount = checkedLinkCount + 1;
        localTarget = erase(extractBefore(linkTarget + "#","#"),".md");
        localTarget = replace(localTarget,"%20"," ");
        targetFile = fullfile(wikiDirectory,localTarget + ".md");
        if ~isfile(targetFile)
            [failureKind,source,detail] = appendFailure( ...
                failureKind,source,detail, ...
                "BrokenLink",string(markdownFiles(fileIndex).name), ...
                linkTarget);
        end
    end
end

criticalTokens = wikiCriticalTokens();
for tokenIndex = 1:height(criticalTokens)
    pageFile = fullfile( ...
        wikiDirectory,criticalTokens.Page(tokenIndex) + ".md");
    if ~isfile(pageFile)
        continue
    end
    pageText = string(fileread(pageFile));
    if ~contains(pageText,criticalTokens.Token(tokenIndex))
        [failureKind,source,detail] = appendFailure( ...
            failureKind,source,detail, ...
            "MissingToken",criticalTokens.Page(tokenIndex), ...
            criticalTokens.Token(tokenIndex));
    end
end

schemaPaths = schemaLeafPaths(v2xsim.config.schema(),"");
configurationIndex = string(fileread(fullfile( ...
    wikiDirectory,"Complete-Configuration-Key-Index.md")));
for schemaPath = schemaPaths.'
    if ~contains(configurationIndex,schemaPath)
        [failureKind,source,detail] = appendFailure( ...
            failureKind,source,detail, ...
            "MissingSchemaPath","Complete-Configuration-Key-Index", ...
            schemaPath);
    end
end

enumValues = schemaEnumValues(v2xsim.config.schema());
for enumValue = enumValues.'
    if ~contains(wikiCorpus,enumValue)
        [failureKind,source,detail] = appendFailure( ...
            failureKind,source,detail, ...
            "MissingEnumValue","wiki",enumValue);
    end
end

outputContracts = publicOutputContracts();
for contractIndex = 1:height(outputContracts)
    pageFile = fullfile( ...
        wikiDirectory,outputContracts.Page(contractIndex) + ".md");
    if ~isfile(pageFile)
        continue
    end
    pageText = string(fileread(pageFile));
    columns = outputContracts.Columns{contractIndex};
    for column = columns
        if ~contains(pageText,column)
            [failureKind,source,detail] = appendFailure( ...
                failureKind,source,detail, ...
                "MissingOutputColumn", ...
                outputContracts.Page(contractIndex),column);
        end
    end
end

canonicalExamples = [ ...
    "examples/v7/v7_04_apply_position_errors.m"; ...
    "examples/v7/v7_07_run_nr_mode1.m"; ...
    "examples/v7/v7_08_run_nr_mode1_etsi_campaign.m"; ...
    "examples/v7/v7_09_explore_traffic_scenarios.m"; ...
    "examples/v7/v7_10_run_nr_mode2.m"; ...
    "examples/v7/config/07_nr_mode1_quickstart.toml"; ...
    "examples/v7/config/08_nr_mode1_etsi_campaign.toml"; ...
    "examples/v7/config/09_traffic_scenario_gallery.toml"; ...
    "examples/v7/config/10_nr_mode2_all_options.toml"; ...
    "examples/v7/v7_11_compare_lte_modes.m"; ...
    "examples/v7/v7_12_compare_ieee80211p.m"; ...
    "examples/v7/v7_13_compare_coexistence_methods.m"; ...
    "examples/v7/v7_14_compare_channel_models.m"; ...
    "examples/v7/v7_15_compare_application_traffic.m"; ...
    "examples/v7/v7_16_run_roadside_unit.m"; ...
    "examples/v7/v7_17_reduce_packet_fates.m"; ...
    "examples/v7/config/11_lte_modes.toml"; ...
    "examples/v7/config/12_ieee80211p.toml"; ...
    "examples/v7/config/13_coexistence_methods.toml"; ...
    "examples/v7/config/14_channel_models.toml"; ...
    "examples/v7/config/15_application_traffic.toml"; ...
    "examples/v7/config/16_roadside_unit.toml"];
for relativePath = canonicalExamples.'
    exampleFile = fullfile( ...
        projectRoot,replace(relativePath,"/",filesep));
    if ~isfile(exampleFile)
        [failureKind,source,detail] = appendFailure( ...
            failureKind,source,detail, ...
            "MissingExample","v7-dev",relativePath);
    end
end

failures = table( ...
    failureKind,source,detail, ...
    VariableNames=["Kind","Source","Detail"]);
report = struct( ...
    WikiDirectory=wikiDirectory, ...
    RequiredPageCount=numel(requiredPages), ...
    MarkdownFileCount=numel(markdownFiles), ...
    CheckedLinkCount=checkedLinkCount, ...
    CriticalTokenCount=height(criticalTokens), ...
    SchemaPathCount=numel(schemaPaths), ...
    EnumValueCount=numel(enumValues), ...
    OutputColumnCount=sum(cellfun(@numel,outputContracts.Columns)), ...
    CanonicalExampleCount=numel(canonicalExamples), ...
    IsValid=isempty(failures), ...
    Failures=failures);

if options.ThrowOnFailure && ~report.IsValid
    firstFailure = failures(1,:);
    error( ...
        "v2xsimdocs:wiki:ValidationFailed", ...
        "Wiki validation found %d failure(s). First: %s in %s (%s).", ...
        height(failures),firstFailure.Kind, ...
        firstFailure.Source,firstFailure.Detail);
end
end

