function targets = markdownLinkTargets(pageText)
matches = regexp( ...
    char(pageText),"\[[^\]]*\]\(([^)]+)\)","tokens");
if isempty(matches)
    targets = strings(0,1);
    return
end
targets = string(cellfun(@(match) match{1},matches, ...
    UniformOutput=false)).';
end

function result = isExternalOrAnchor(target)
result = startsWith(target,[ ...
    "http://","https://","mailto:","#"]);
end

