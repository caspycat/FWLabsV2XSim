pressure = struct( ...
    TimeAvailabilityPercent=workItem.AvailabilityPercent, ...
    FrequencyAvailabilityPercent=workItem.AvailabilityPercent);
patchData = struct( ...
    Simulation=struct( ...
        RandomSeed=workItem.RandomSeed, ...
        DurationSeconds=workItem.SimulationTimeSeconds), ...
    Scenario=struct( ...
        Type="BidirectionalHighway", ...
        BidirectionalHighway=struct( ...
            RandomSeed=workItem.RandomSeed, ...
            VehicleCount=126, ...
            NLanes=3, ...
            LaneWidth=4, ...
            RoadLength=2100, ...
            CentralDividerWidth=0, ...
            MeanVehicleSpeed=140 ./ 3.6, ...
            VehicleSpeedStandardDeviation=0, ...
            RerollSpeedOnWrapAround=false)), ...
    Application=struct( ...
        ResourceReservationIntervalSeconds=0.1, ...
        PacketGeneration=struct( ...
            IntervalVariationSeconds=0, ...
            IntervalSeconds=0.1, ...
            RandomComponentMeanSeconds=0)), ...
    Radio=struct( ...
        Type="NrV2X", ...
        NrV2X=struct( ...
            Mcs=7, ...
            SubcarrierSpacingKilohertz=15, ...
            DmrsResourceElementCountPerSlot=24), ...
        Sidelink=struct(ResourcePool=struct( ...
            SubchannelSizeResourceBlocks=10, ...
            PartialFrequencyOverlapEnabled=false, ...
            ResourcePressure=pressure))), ...
    Awareness=struct(RangesMeters=300), ...
    ResourceAllocation=struct( ...
        Type=workItem.Allocator, ...
        RandomSeed=workItem.RandomSeed), ...
    Outputs=struct( ...
        PacketReceptionRatio=struct( ...
            Enabled=true,DistanceBinWidthMeters=25), ...
        UpdateDelay=struct(Enabled=false), ...
        PacketDelay=struct(Enabled=false), ...
        DataAge=struct(Enabled=false), ...
        WirelessBlindSpot=struct(Enabled=false), ...
        AverageNeighborCount=struct(Enabled=false), ...
        ChannelBusyRatio=struct(Enabled=false)));
end

function [normalizedPrrAuc,counts] = scorePrrFile( ...
        prrFile,maximumScoreDistanceMeters)
if ~isfile(prrFile)
    error( ...
        "v2xsimregression:resourcepressure:MissingPrrOutput", ...
        "Expected packet-reception output was not created: %s",prrFile);
end
prrData = readmatrix(prrFile);
if size(prrData,2) ~= 6 || isempty(prrData)
    error( ...
        "v2xsimregression:resourcepressure:InvalidPrrOutput", ...
        "Packet-reception output must contain six numeric columns: %s", ...
        prrFile);
end
if any(~isfinite(prrData(:,1:5)),"all") || ...
        any(prrData(:,1:5) < 0,"all") || ...
        any(prrData(:,2:5) ~= fix(prrData(:,2:5)),"all")
    error( ...
        "v2xsimregression:resourcepressure:InvalidPrrOutput", ...
        "Packet-reception distances and counts must be finite, " + ...
        "nonnegative integers.");
end
if any(prrData(:,5) ~= sum(prrData(:,2:4),2))
    error( ...
        "v2xsimregression:resourcepressure:InconsistentPrrCounts", ...
        "Every PRR row must satisfy total = correct + error + blocked.");
end

isScored = prrData(:,1) > 0 & ...
    prrData(:,1) <= maximumScoreDistanceMeters;
scored = prrData(isScored,:);
expectedDistances = (25:25:maximumScoreDistanceMeters).';
if isempty(scored) || ~isequal(scored(:,1),expectedDistances) || ...
        any(scored(:,5) == 0)
    error( ...
        "v2xsimregression:resourcepressure:IncompletePrrCurve", ...
        "Every 25 m distance bin through %g m must contain samples.", ...
        maximumScoreDistanceMeters);
end

packetReceptionRatios = scored(:,2) ./ scored(:,5);
normalizedPrrAuc = trapz( ...
    [0;scored(:,1)],[1;packetReceptionRatios]) ./ ...
    maximumScoreDistanceMeters;
counts = sum(scored(:,2:4),1);
end

function comparisons = comparePressureLevels( ...
        seedResults,allocators,randomSeeds, ...
        availabilityPercents,bootstrapSampleCount)
comparisonCells = cell(1,numel(allocators));
for allocatorIndex = 1:numel(allocators)
    allocator = allocators(allocatorIndex);
    scores = pairedScores( ...
        seedResults,allocator,randomSeeds,availabilityPercents);
    pairedDifferences = scores(:,1) - scores(:,2);
    confidenceInterval = pairedBootstrapMeanInterval( ...
        pairedDifferences,bootstrapSampleCount,92000 + allocatorIndex);
    comparisonCells{allocatorIndex} = table( ...
        allocator,numel(randomSeeds),mean(scores(:,1)),mean(scores(:,2)), ...
        mean(pairedDifferences),confidenceInterval(1),confidenceInterval(2), ...
        VariableNames=[ ...
            "Allocator", "SeedCount", "UnpressuredMeanAuc", ...
            "PressuredMeanAuc", "MeanUnpressuredMinusPressuredAuc", ...
            "Lower95ConfidenceBound", "Upper95ConfidenceBound"]);
end
comparisons = vertcat(comparisonCells{:});
end

function scores = pairedScores( ...
        seedResults,allocator,randomSeeds,availabilityPercents)
scores = zeros(numel(randomSeeds),numel(availabilityPercents));
for availabilityIndex = 1:numel(availabilityPercents)
    selected = seedResults( ...
        seedResults.Allocator == allocator & ...
        seedResults.AvailabilityPercent == ...
            availabilityPercents(availabilityIndex),:);
    [isPresent,rowOrder] = ismember(randomSeeds(:),selected.RandomSeed);
    if ~all(isPresent) || height(selected) ~= numel(randomSeeds)
        error( ...
            "v2xsimregression:resourcepressure:UnpairedSeeds", ...
            "Allocator %s does not contain every manifest seed at " + ...
            "%d%% availability.",allocator, ...
            availabilityPercents(availabilityIndex));
    end
    scores(:,availabilityIndex) = selected.NormalizedPrrAuc(rowOrder);
end
end

function confidenceInterval = pairedBootstrapMeanInterval( ...
        pairedDifferences,bootstrapSampleCount,randomSeed)
stream = RandStream("mt19937ar",Seed=randomSeed);
seedCount = numel(pairedDifferences);
sampleRows = randi( ...
    stream,seedCount,seedCount,bootstrapSampleCount);
bootstrapMeans = sort(mean(pairedDifferences(sampleRows),1));
lowerIndex = max(1,ceil(0.025 .* bootstrapSampleCount));
upperIndex = min( ...
    bootstrapSampleCount,floor(0.975 .* bootstrapSampleCount));
confidenceInterval = [ ...
    bootstrapMeans(lowerIndex),bootstrapMeans(upperIndex)];
end

function validateSimulator(simulatorRoot,configurationFile)
if ~isfolder(simulatorRoot) || ...
        ~isfile(fullfile(simulatorRoot,"src","+v2xsim","runSimulation.m"))
    error( ...
        "v2xsimregression:resourcepressure:MissingSimulator", ...
        "v2xsim.runSimulation was not found below %s.",simulatorRoot);
end
if ~isfile(configurationFile)
    error( ...
        "v2xsimregression:resourcepressure:MissingConfiguration", ...
        "Baseline configuration was not found: %s.",configurationFile);
end
end

function restoreEnvironment( ...
        originalPath,originalStream,originalStreamState,originalWarningState)
path(originalPath);
RandStream.setGlobalStream(originalStream);
originalStream.State = originalStreamState;
warning(originalWarningState);
end

function pathValue = absolutePath(pathValue,baseDirectory)
if ~isAbsolutePath(pathValue)
    pathValue = fullfile(baseDirectory,pathValue);
end
end

function tf = isAbsolutePath(pathValue)
if ispc
    tf = ~isempty(regexp(pathValue,"^[A-Za-z]:[\\/]|^\\\\","once"));
else
    tf = startsWith(pathValue,"/");
end
end
