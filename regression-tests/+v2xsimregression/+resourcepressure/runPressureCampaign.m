function [seedResults, comparisons] = runPressureCampaign( ...
        simulatorRoot, outputDirectory, options)
%RUNPRESSURECAMPAIGN Estimate the per-allocator capacity-pressure effect.
%   The campaign holds scenario, traffic, PHY, and allocator parameters
%   fixed.  It changes only the static time and frequency availability of the
%   ResourcePressure policy, pairing each pressure level by random seed.

arguments (Input)
    simulatorRoot (1, 1) string {mustBeNonzeroLengthText}
    outputDirectory (1, 1) string {mustBeNonzeroLengthText}
    options.Allocators (1, :) string {mustBeMember( ...
        options.Allocators, ["ReuseDistance", "MaximumReuseDistance", ...
        "MinimumReusePower", "SensingBased", "Random", "Ordered"])} = ...
        ["ReuseDistance", "MaximumReuseDistance", ...
        "MinimumReusePower", "SensingBased", "Random", "Ordered"]
    options.RandomSeeds (1, :) double {mustBeInteger,mustBePositive} = 10:19
    options.SimulationTimeSeconds (1, 1) double { ...
        mustBeReal,mustBeFinite,mustBePositive} = 2
    options.ExecutionMode (1, 1) string {mustBeMember( ...
        options.ExecutionMode, ["auto", "serial", "parallel"])} = "auto"
    options.MaxWorkers (1, 1) double { ...
        v2xsimregression.execution.mustBeWorkerLimit} = Inf
    options.BootstrapSampleCount (1, 1) double { ...
        mustBeInteger,mustBePositive} = 10000
end

arguments (Output)
    seedResults table
    comparisons table
end

availabilityPercents = [100, 25];
validateOptions(options);

callerWorkingDirectory = string(pwd);
simulatorRoot = absolutePath(simulatorRoot, callerWorkingDirectory);
outputDirectory = absolutePath(outputDirectory, callerWorkingDirectory);
configurationFile = fullfile( ...
    simulatorRoot, "tests", "+v2xsimtest", "+fixtures", ...
    "config", "EtsiHighwayMediumMode1.toml");
validateSimulator(simulatorRoot,configurationFile);

originalPath = path;
originalStream = RandStream.getGlobalStream();
originalStreamState = originalStream.State;
originalWarningState = warning;
environmentCleanup = onCleanup(@() restoreEnvironment( ...
    originalPath,originalStream,originalStreamState,originalWarningState));

addpath(fullfile(simulatorRoot,"src"));
addpath(fullfile(simulatorRoot,"lib","matlab-toml"));
if ~isfolder(outputDirectory)
    [created,message] = mkdir(outputDirectory);
    if ~created
        error( ...
            "v2xsimregression:resourcepressure:OutputDirectoryCreationFailed", ...
            "Could not create output directory ""%s"": %s", ...
            outputDirectory,message);
    end
end

manifest = createManifest( ...
    configurationFile,outputDirectory,options.Allocators,options.RandomSeeds, ...
    availabilityPercents,options.SimulationTimeSeconds);
workItems = arrayfun(@(workItem) {workItem},manifest);
labels = string({manifest.Label});
additionalPaths = [ ...
    fullfile(simulatorRoot,"regression-tests"), ...
    fullfile(simulatorRoot,"src"), ...
    fullfile(simulatorRoot,"lib","matlab-toml")];
resultCells = v2xsimregression.execution.runWorkItems( ...
    workItems,@runWorkItem,Labels=labels, ...
    ExecutionMode=options.ExecutionMode,MaxWorkers=options.MaxWorkers, ...
    AdditionalPaths=additionalPaths,CollectAllFailures=true);
seedResults = vertcat(resultCells{:});
comparisons = comparePressureLevels( ...
    seedResults,options.Allocators,options.RandomSeeds, ...
    availabilityPercents,options.BootstrapSampleCount);

environmentCleanup; %#ok<VUNUS>
end

function validateOptions(options)
if isempty(options.Allocators) || isempty(options.RandomSeeds)
    error( ...
        "v2xsimregression:resourcepressure:EmptyManifest", ...
        "Allocators and RandomSeeds must both be nonempty.");
end
if numel(unique(options.Allocators)) ~= numel(options.Allocators)
    error( ...
        "v2xsimregression:resourcepressure:DuplicateAllocator", ...
        "Allocators must not contain duplicates.");
end
if numel(unique(options.RandomSeeds)) ~= numel(options.RandomSeeds)
    error( ...
        "v2xsimregression:resourcepressure:DuplicateRandomSeed", ...
        "RandomSeeds must not contain duplicates.");
end
if options.BootstrapSampleCount < 40
    error( ...
        "v2xsimregression:resourcepressure:InsufficientBootstrapSamples", ...
        "BootstrapSampleCount must be at least 40.");
end
end

function manifest = createManifest( ...
        configurationFile,outputDirectory,allocators,randomSeeds, ...
        availabilityPercents,simulationTimeSeconds)
manifest = repmat(struct( ...
    "ConfigurationFile",configurationFile, ...
    "OutputDirectory","", ...
    "Allocator","", ...
    "RandomSeed",0, ...
    "AvailabilityPercent",0, ...
    "SimulationTimeSeconds",simulationTimeSeconds, ...
    "Label",""), ...
    1,numel(allocators) .* numel(randomSeeds) .* ...
    numel(availabilityPercents));

workIndex = 0;
for allocator = allocators
    for availabilityPercent = availabilityPercents
        for randomSeed = randomSeeds
            workIndex = workIndex + 1;
            label = compose( ...
                "%s/availability-%d/seed-%d", ...
                allocator,availabilityPercent,randomSeed);
            manifest(workIndex).OutputDirectory = fullfile( ...
                outputDirectory,lower(allocator), ...
                compose("availability-%d",availabilityPercent), ...
                compose("seed-%d",randomSeed));
            manifest(workIndex).Allocator = allocator;
            manifest(workIndex).RandomSeed = randomSeed;
            manifest(workIndex).AvailabilityPercent = availabilityPercent;
            manifest(workIndex).Label = label;
        end
    end
end
end

function result = runWorkItem(workItem)
template = v2xsim.config.load(workItem.ConfigurationFile);
configuration = template.resolve(Patch=v2xsim.config.patch( ...
    configurationPatch(workItem))); %#ok<NASGU>
evalc("v2xsim.runSimulation(configuration," + ...
    "OutputDirectory=workItem.OutputDirectory," + ...
    "RunLabel=workItem.Label);");

summaryFile = fullfile(workItem.OutputDirectory,"simulation_summary.json");
if ~isfile(summaryFile)
    error( ...
        "v2xsimregression:resourcepressure:MissingSimulationSummary", ...
        "Simulation did not publish a summary for %s.",workItem.Label);
end

prrFile = fullfile(workItem.OutputDirectory,"packet_reception_ratio_5G.csv");
[normalizedPrrAuc,counts] = scorePrrFile(prrFile,300);
result = table( ...
    workItem.Allocator,workItem.RandomSeed,workItem.AvailabilityPercent, ...
    workItem.SimulationTimeSeconds,normalizedPrrAuc, ...
    counts(1),counts(2),counts(3),sum(counts),workItem.OutputDirectory, ...
    VariableNames=[ ...
        "Allocator", "RandomSeed", "AvailabilityPercent", ...
        "SimulationTimeSeconds", "NormalizedPrrAuc", ...
        "CorrectCount", "ErrorCount", "BlockedCount", "TotalCount", ...
        "OutputDirectory"]);
end

