        reuseCandidates, runDirectory, maximumDistanceMeters, ...
        options);
writetable( ...
    shadowManifest, ...
    fullfile( ...
        runDirectory, ...
        "exposed_reuse_shadow_manifest.csv"));

[realizedMean, realizedRms, realizedQ95, activeSampleCount, ...
        moduleSampleCount, activeSampleFraction, ...
        overallMeanMagnitude, selectedVehicleCount, episodeCount, ...
        selectedVehicleCohortKey] = ...
    summarizePositionTrace(positionTrace);
[transmitterActive, receiverActive] = ...
    activeEndpointMasks(errorFates, positionState);
