function [meanMagnitude, rmsMagnitude, q95Magnitude, sampleCount, ...
        moduleSampleCount, activeSampleFraction, ...
        overallMeanMagnitude, selectedVehicleCount, episodeCount, ...
        selectedVehicleCohortKey] = ...
        summarizePositionTrace(positionTrace)
if isempty(positionTrace)
    [meanMagnitude, rmsMagnitude, q95Magnitude] = deal(NaN);
    [sampleCount, moduleSampleCount, selectedVehicleCount, ...
        episodeCount] = deal(0);
    activeSampleFraction = 0;
    overallMeanMagnitude = 0;
    selectedVehicleCohortKey = "";
    return
end
requiredNames = [ ...
    "VehicleId", "ModuleIndex", "DisplacementMagnitudeMeters", ...
    "StatusEffectType", "IsSelected", "IsActive", "EpisodeId"];
if any(~ismember( ...
        requiredNames, ...
        string(positionTrace.Properties.VariableNames)))
    error( ...
        "v2xsimregression:positionerror:InvalidPositionTrace", ...
        "Position-error trace is missing required columns.");
end

moduleRows = positionTrace.ModuleIndex > 0 & ...
    strlength(string(positionTrace.StatusEffectType)) > 0;
active = logical(positionTrace.IsActive) & moduleRows;
magnitudes = double( ...
    positionTrace.DisplacementMagnitudeMeters(active));
sampleCount = numel(magnitudes);
moduleSampleCount = nnz(moduleRows);
if moduleSampleCount == 0
    activeSampleFraction = 0;
    overallMeanMagnitude = 0;
else
    activeSampleFraction = sampleCount ./ moduleSampleCount;
    overallMeanMagnitude = mean(double( ...
        positionTrace. ...
            DisplacementMagnitudeMeters(moduleRows)));
end
if isempty(magnitudes)
    meanMagnitude = 0;
    rmsMagnitude = 0;
    q95Magnitude = 0;
else
    meanMagnitude = mean(magnitudes);
    rmsMagnitude = sqrt(mean(magnitudes .^ 2));
    q95Magnitude = linearQuantile(magnitudes, 0.95);
end
selectedVehicleIds = sort(unique(string( ...
    positionTrace.VehicleId( ...
        logical(positionTrace.IsSelected) & ...
        moduleRows))));
selectedVehicleCount = numel(selectedVehicleIds);
selectedVehicleCohortKey = strjoin(selectedVehicleIds, "|");
episodeRows = isfinite(double(positionTrace.EpisodeId)) & ...
    moduleRows;
if ~any(episodeRows)
    episodeCount = 0;
else
    episodeKeys = table( ...
        string(positionTrace.VehicleId(episodeRows)), ...
        double(positionTrace.ModuleIndex(episodeRows)), ...
        string(positionTrace.StatusEffectType(episodeRows)), ...
        double(positionTrace.EpisodeId(episodeRows)), ...
        VariableNames=[ ...
            "VehicleId", "ModuleIndex", ...
            "StatusEffectType", "EpisodeId"]);
    episodeCount = height(unique(episodeKeys));
end
end

