function metrics = finalizePerVehicleMetrics( ...
        accumulator, positionTrace, distanceGrid)
rowCount = numel(accumulator.Keys);
binCount = numel(distanceGrid);
correctByBin = accumulator.BinOutcomeCounts(:, 1:binCount);
errorByBin = accumulator.BinOutcomeCounts( ...
    :, binCount + (1:binCount));
blockedByBin = accumulator.BinOutcomeCounts( ...
    :, 2 .* binCount + (1:binCount));
correctCount = sum(correctByBin, 2);
errorCount = sum(errorByBin, 2);
blockedCount = sum(blockedByBin, 2);
totalCount = correctCount + errorCount + blockedCount;
radioAttemptCount = correctCount + errorCount;
deliveryPrr = divideOrNaN(correctCount, totalCount);
radioPrr = divideOrNaN(correctCount, radioAttemptCount);
blockingRate = divideOrNaN(blockedCount, totalCount);
deliveryPrrAuc = nan(rowCount, 1);
radioPrrAuc = nan(rowCount, 1);
deliveryStatus = repmat("NoTerminalFates", rowCount, 1);
radioStatus = deliveryStatus;
nonemptyDeliveryBinCount = nnzByRow( ...
    correctByBin + errorByBin + blockedByBin > 0);
nonemptyRadioBinCount = nnzByRow( ...
    correctByBin + errorByBin > 0);
for rowIndex = 1:rowCount
    if accumulator.FateCount(rowIndex) == 0
        continue
    elseif totalCount(rowIndex) == 0
        deliveryStatus(rowIndex) = ...
            "NoFatesWithinDistanceGrid";
        radioStatus(rowIndex) = ...
            "NoFatesWithinDistanceGrid";
        continue
    end
    [deliveryPrrAuc(rowIndex), deliveryStatus(rowIndex)] = ...
        scoreBinnedCounts( ...
            correctByBin(rowIndex, :), ...
            correctByBin(rowIndex, :) + ...
                errorByBin(rowIndex, :) + ...
                blockedByBin(rowIndex, :), ...
            distanceGrid);
    if radioAttemptCount(rowIndex) == 0
        radioStatus(rowIndex) = "NoRadioAttempts";
    else
        [radioPrrAuc(rowIndex), radioStatus(rowIndex)] = ...
            scoreBinnedCounts( ...
                correctByBin(rowIndex, :), ...
                correctByBin(rowIndex, :) + ...
                    errorByBin(rowIndex, :), ...
                distanceGrid);
    end
end

metrics = table( ...
    accumulator.Technology, accumulator.VehicleUeId, ...
    accumulator.Perspective, accumulator.ExposureState, ...
    repmat(distanceGrid(end), rowCount, 1), ...
    repmat(binCount, rowCount, 1), ...
    nonemptyDeliveryBinCount, nonemptyRadioBinCount, ...
    correctCount, errorCount, blockedCount, totalCount, ...
    radioAttemptCount, deliveryPrr, radioPrr, blockingRate, ...
    deliveryPrrAuc, radioPrrAuc, deliveryStatus, radioStatus, ...
    VariableNames=[ ...
        "Technology", "VehicleUeId", "Perspective", ...
        "ExposureState", "MaximumDistanceMeters", ...
        "DistanceBinCount", "NonemptyDeliveryBinCount", ...
        "NonemptyRadioBinCount", "CorrectCount", ...
        "ErrorCount", "BlockedCount", "TotalCount", ...
        "RadioAttemptCount", "DeliveryPrr", "RadioPrr", ...
        "BlockingRate", "DeliveryPrrAuc", "RadioPrrAuc", ...
        "DeliveryPrrAucStatus", "RadioPrrAucStatus"]);

vehicleLifecycle = summarizeVehicleLifecycle(positionTrace);
[hasLifecycle, lifecycleRows] = ismember( ...
    metrics.VehicleUeId, vehicleLifecycle.VehicleUeId);
metrics.EverSelectedForPositionError = false(height(metrics), 1);
metrics.ActivePositionSampleCount = zeros(height(metrics), 1);
metrics.StatusEffectEpisodeCount = zeros(height(metrics), 1);
metrics.FirstActiveTimeSeconds = nan(height(metrics), 1);
metrics.LastActiveTimeSeconds = nan(height(metrics), 1);
metrics.EverSelectedForPositionError(hasLifecycle) = ...
    vehicleLifecycle.EverSelectedForPositionError( ...
        lifecycleRows(hasLifecycle));
metrics.ActivePositionSampleCount(hasLifecycle) = ...
    vehicleLifecycle.ActivePositionSampleCount( ...
        lifecycleRows(hasLifecycle));
metrics.StatusEffectEpisodeCount(hasLifecycle) = ...
    vehicleLifecycle.StatusEffectEpisodeCount( ...
        lifecycleRows(hasLifecycle));
metrics.FirstActiveTimeSeconds(hasLifecycle) = ...
    vehicleLifecycle.FirstActiveTimeSeconds( ...
        lifecycleRows(hasLifecycle));
metrics.LastActiveTimeSeconds(hasLifecycle) = ...
    vehicleLifecycle.LastActiveTimeSeconds( ...
        lifecycleRows(hasLifecycle));
metrics = sortrows( ...
    metrics, ["Technology", "VehicleUeId", ...
        "Perspective", "ExposureState"]);
end

function counts = nnzByRow(values)
counts = sum(values, 2);
end

function values = divideOrNaN(numerator, denominator)
values = nan(size(numerator));
hasDenominator = denominator > 0;
values(hasDenominator) = ...
    numerator(hasDenominator) ./ denominator(hasDenominator);
end

function [auc, status] = scoreBinnedCounts( ...
        correctCounts, denominatorCounts, distanceGrid)
auc = NaN;
if any(denominatorCounts <= 0)
    status = "IncompleteDistanceGrid";
    return
end
ratios = correctCounts ./ denominatorCounts;
auc = trapz( ...
    [0; distanceGrid], [1; ratios(:)]) ./ distanceGrid(end);
status = "Complete";
end

function lifecycle = summarizeVehicleLifecycle(positionTrace)
lifecycle = table( ...
    strings(0, 1), false(0, 1), zeros(0, 1), ...
    zeros(0, 1), nan(0, 1), nan(0, 1), ...
    VariableNames=[ ...
        "VehicleUeId", "EverSelectedForPositionError", ...
        "ActivePositionSampleCount", "StatusEffectEpisodeCount", ...
        "FirstActiveTimeSeconds", "LastActiveTimeSeconds"]);
requiredNames = [ ...
    "VehicleId", "ModuleIndex", "SimulationTimeSeconds", ...
    "StatusEffectType", "IsSelected", "IsActive", "EpisodeId"];
if isempty(positionTrace) || ...
        any(~ismember( ...
            requiredNames, ...
            string(positionTrace.Properties.VariableNames)))
    return
end

moduleRows = positionTrace.ModuleIndex > 0 & ...
    strlength(string(positionTrace.StatusEffectType)) > 0;
moduleTrace = positionTrace(moduleRows, :);
if isempty(moduleTrace)
    return
end
[vehicleGroups, vehicleIds] = findgroups( ...
    string(moduleTrace.VehicleId));
lifecycle = table( ...
    vehicleIds, ...
    splitapply( ...
        @any, logical(moduleTrace.IsSelected), vehicleGroups), ...
    splitapply( ...
        @sum, logical(moduleTrace.IsActive), vehicleGroups), ...
    splitapply( ...
        @countFiniteModuleEpisodes, ...
        double(moduleTrace.ModuleIndex), ...
        double(moduleTrace.EpisodeId), vehicleGroups), ...
    splitapply( ...
        @minimumActiveTime, ...
        double(moduleTrace.SimulationTimeSeconds), ...
        logical(moduleTrace.IsActive), vehicleGroups), ...
    splitapply( ...
        @maximumActiveTime, ...
        double(moduleTrace.SimulationTimeSeconds), ...
        logical(moduleTrace.IsActive), vehicleGroups), ...
    VariableNames=lifecycle.Properties.VariableNames);
end

