function values = logicalColumn(values, variableName)
if islogical(values)
    return
end
if isnumeric(values)
    if any(~ismember(values, [0, 1]))
        error( ...
            "v2xsimregression:positionerror:" + ...
            "InvalidInterferenceEvidenceTrace", ...
            "%s must contain logical values.", variableName);
    end
    values = logical(values);
    return
end
values = lower(string(values));
if any(~ismember(values, ["true", "false", "1", "0"]))
    error( ...
        "v2xsimregression:positionerror:" + ...
        "InvalidInterferenceEvidenceTrace", ...
        "%s must contain logical values.", variableName);
end
values = values == "true" | values == "1";
end

