    "Status", status, ...
    "AllocatorEvidenceAvailable", ...
        allocatorEvidenceAvailable, ...
    "InterferenceEvidenceComplete", ...
        interferenceEvidenceComplete, ...
    "CompositionDenominatorErrorCount", errorCount, ...
    "IncidenceDenominatorRadioFateCount", ...
        terminalRadioFateCount, ...
    "ModeCompositionRateStatus", ...
        modeValue( ...
            modeSummary, generalMode, ...
            "CompositionRateStatus"), ...
    "ModeIncidenceRateStatus", ...
        modeValue( ...
            modeSummary, generalMode, ...
            "IncidenceRateStatus"), ...
    "HiddenTerminalCountStatus", ...
        modeValue( ...
            modeSummary, "hidden_terminal", "CountStatus"), ...
    "HiddenTerminalCompositionRateStatus", ...
        modeValue( ...
            modeSummary, "hidden_terminal", ...
            "CompositionRateStatus"), ...
    "HiddenTerminalIncidenceRateStatus", ...
        modeValue( ...
            modeSummary, "hidden_terminal", ...
            "IncidenceRateStatus"), ...
    "ClassifiedErrorCount", nnz(~unclassified), ...
    "UnclassifiedErrorCount", nnz(unclassified), ...
    "EvidenceCoveredErrorCount", coveredCount, ...
    "EvidenceExhaustiveErrorCount", exhaustiveCount, ...
    "EvidenceCoverageRate", ratioOrNaN(coveredCount, errorCount), ...
    "EvidenceExhaustiveRate", ...
        ratioOrNaN(exhaustiveCount, errorCount), ...
    "DetectedHiddenTerminalCount", hiddenDetectedCount, ...
    "HiddenTerminalCount", hiddenCount, ...
    "DetectedHiddenTerminalCompositionRate", ...
        ratioOrNaN(nnz(hidden), errorCount), ...
    "HiddenTerminalCompositionRate", ...
        hiddenCompositionRate, ...
    "HiddenTerminalRateAmongErrors", ...
        hiddenCompositionRate, ...
    "HiddenTerminalIncidenceRate", ...
        hiddenIncidenceRate, ...
    "StatusEffectActiveTransmitterHiddenTerminalCount", ...
        gateValue( ...
            nnz(hidden & ...
                events.TransmitterPositionErrorActive), ...
            hiddenIsAnalyzable), ...
    "StatusEffectActiveReceiverHiddenTerminalCount", ...
        gateValue( ...
            nnz(hidden & events.ReceiverPositionErrorActive), ...
            hiddenIsAnalyzable), ...
    "EitherEndpointStatusEffectActiveErrorCount", ...
        nnz(eitherEndpointStatusEffectActive), ...
    "EitherEndpointStatusEffectActiveHiddenTerminalCount", ...
        gateValue( ...
            nnz(hidden & eitherEndpointStatusEffectActive), ...
            hiddenIsAnalyzable), ...
    "EitherEndpointStatusEffectActiveHiddenTerminalRateAmongErrors", ...
        gateValue( ...
            ratioOrNaN( ...
                nnz(hidden & eitherEndpointStatusEffectActive), ...
                nnz(eitherEndpointStatusEffectActive)), ...
            hiddenIsAnalyzable));
metrics = addPrimaryModeMetrics( ...
    metrics, modeSummary, "HalfDuplexFailure", ...
