function state = buildTemporalState(rows, valueName, defaultValue)
state = emptyTemporalState(defaultValue);
if isempty(rows)
    return
end
vehicleIds = string(rows.VehicleId);
[sortedVehicleIds, order] = sort(vehicleIds);
sortedTimes = double(rows.SimulationTimeSeconds(order));
sortedValues = rows.(valueName)(order);
if isstring(defaultValue)
    sortedValues = string(sortedValues);
else
    sortedValues = logical(sortedValues);
end
groupStart = [ ...
    1; find(sortedVehicleIds(2:end) ~= ...
        sortedVehicleIds(1:end - 1)) + 1];
groupEnd = [groupStart(2:end) - 1; numel(order)];
state.VehicleIds = sortedVehicleIds(groupStart);
state.Times = cell(numel(groupStart), 1);
state.Values = cell(numel(groupStart), 1);
for groupIndex = 1:numel(groupStart)
    groupRows = groupStart(groupIndex):groupEnd(groupIndex);
    times = sortedTimes(groupRows);
    values = sortedValues(groupRows);
    [times, retainedRows] = unique(times, "last");
    values = values(retainedRows);
    [times, timeOrder] = sort(times);
    state.Times{groupIndex} = times;
    state.Values{groupIndex} = values(timeOrder);
end
end

function [reduction, errorFates] = reducePacketFateChunks( ...
        runDirectory, distanceGrid, positionState)
parquetFiles = dir(fullfile( ...
    runDirectory, "packet_fates_*.parquet"));
csvFiles = dir(fullfile(runDirectory, "packet_fates_*.csv"));
if ~isempty(parquetFiles) && ~isempty(csvFiles)
    error( ...
        "v2xsimregression:positionerror:MixedPacketTraceFormats", ...
        "A run cannot mix packet-fate CSV and Parquet chunks.");
end

files = parquetFiles;
isParquet = true;
if isempty(files)
    files = csvFiles;
    isParquet = false;
end
files = sortTraceFiles(files);
reduction = initializePacketReduction(numel(distanceGrid));
errorParts = cell(numel(files), 1);
errorPartCount = 0;
for fileIndex = 1:numel(files)
    filename = fullfile( ...
        files(fileIndex).folder, files(fileIndex).name);
    if isParquet
        chunk = parquetread(filename);
    else
        chunk = readtable(filename, TextType="string");
    end
    chunk = coercePacketFateTypes(chunk);
    chunk = ...
        v2xsim.analysis.aggregateTerminalPacketFates(chunk);
    if isempty(chunk)
        continue
    end
    transmitterActive = previousStateAtTimes( ...
        chunk.TransmitterUeId, chunk.FateTimeSeconds, ...
        positionState.Active);
    receiverActive = previousStateAtTimes( ...
        chunk.ReceiverUeId, chunk.FateTimeSeconds, ...
        positionState.Active);
    transmitterRoutes = previousStateAtTimes( ...
        chunk.TransmitterUeId, chunk.FateTimeSeconds, ...
        positionState.Route);
    reduction = accumulatePacketChunk( ...
        reduction, chunk, transmitterActive, receiverActive, ...
        transmitterRoutes, distanceGrid);
    errorRows = chunk.Outcome == "error";
    if any(errorRows)
        errorPartCount = errorPartCount + 1;
        errorParts{errorPartCount} = chunk(errorRows, :);
    end
end

if errorPartCount == 0
    errorFates = ...
        v2xsim.analysis.emptyTerminalPacketFateTable();
else
    errorFates = vertcat(errorParts{1:errorPartCount});
    errorFates = ...
        v2xsim.analysis.aggregateTerminalPacketFates(errorFates);
end
end

function files = sortTraceFiles(files)
if isempty(files)
    return
end
[~, order] = sort(string({files.name}));
files = files(order);
end

function reduction = initializePacketReduction(binCount)
categoryNames = [ ...
    "all"; "status_effect_active_transmitter"; ...
    "status_effect_active_receiver"; ...
    "either_endpoint_status_effect_active"; ...
    "mainline_transmitter"; ...
    "ramp_transmitter"];
categoryCount = numel(categoryNames);
reduction = struct( ...
    "CategoryNames", categoryNames, ...
    "CategoryFateCounts", zeros(categoryCount, 1), ...
    "CategoryOutcomeCounts", zeros(categoryCount, 3), ...
    "CategoryBinOutcomeCounts", ...
        zeros(categoryCount, binCount .* 3), ...
    "TerminalPacketFateCount", 0, ...
    "PerVehicle", initializePerVehicleReduction(binCount));
end

function accumulator = initializePerVehicleReduction(binCount)
accumulator = struct( ...
    "Keys", strings(0, 1), ...
    "Technology", strings(0, 1), ...
    "VehicleUeId", strings(0, 1), ...
    "Perspective", strings(0, 1), ...
    "ExposureState", strings(0, 1), ...
    "FateCount", zeros(0, 1), ...
    "BinOutcomeCounts", zeros(0, binCount .* 3));
end

function reduction = accumulatePacketChunk( ...
        reduction, chunk, transmitterActive, receiverActive, ...
        transmitterRoutes, distanceGrid)
outcomeIndex = packetOutcomeIndex(chunk.Outcome);
binCount = numel(distanceGrid);
binIndex = discretize( ...
    double(chunk.TrueDistanceMeters), ...
    [-Inf; distanceGrid; Inf]);
withinGrid = binIndex <= binCount;
categoryMasks = [ ...
    true(height(chunk), 1), ...
    transmitterActive, receiverActive, ...
    transmitterActive | receiverActive, ...
    ismember(transmitterRoutes, ["Merge", "Adjacent"]), ...
    transmitterRoutes == "Ramp"];
for categoryIndex = 1:width(categoryMasks)
    categoryRows = categoryMasks(:, categoryIndex);
    reduction.CategoryFateCounts(categoryIndex) = ...
        reduction.CategoryFateCounts(categoryIndex) + ...
        nnz(categoryRows);
    if any(categoryRows)
        reduction.CategoryOutcomeCounts(categoryIndex, :) = ...
            reduction.CategoryOutcomeCounts(categoryIndex, :) + ...
            accumarray( ...
                outcomeIndex(categoryRows), 1, [3, 1]).';
    end
    gridRows = categoryRows & withinGrid;
    if any(gridRows)
        binOutcomeColumn = ...
            (outcomeIndex(gridRows) - 1) .* binCount + ...
            binIndex(gridRows);
        reduction.CategoryBinOutcomeCounts( ...
            categoryIndex, :) = ...
            reduction.CategoryBinOutcomeCounts( ...
                categoryIndex, :) + ...
            accumarray( ...
                binOutcomeColumn, 1, ...
                [binCount .* 3, 1]).';
    end
end
reduction.TerminalPacketFateCount = ...
    reduction.TerminalPacketFateCount + height(chunk);
reduction.PerVehicle = accumulatePerVehicleChunk( ...
    reduction.PerVehicle, chunk, transmitterActive, ...
    receiverActive, binIndex, withinGrid, outcomeIndex);
end

function indices = packetOutcomeIndex(outcomes)
outcomes = string(outcomes);
indices = zeros(numel(outcomes), 1);
indices(outcomes == "correct") = 1;
indices(outcomes == "error") = 2;
indices(outcomes == "blocked") = 3;
if any(indices == 0)
    error( ...
        "v2xsimregression:positionerror:InvalidPacketTrace", ...
        "Reduced packet-fate chunks must contain terminal outcomes.");
end
end

function accumulator = accumulatePerVehicleChunk( ...
        accumulator, chunk, transmitterActive, receiverActive, ...
        binIndex, withinGrid, outcomeIndex)
technologies = string(chunk.Technology);
transmitters = string(chunk.TransmitterUeId);
receivers = string(chunk.ReceiverUeId);
seenVehicles = unique( ...
    table( ...
        [technologies; technologies], ...
        [transmitters; receivers], ...
        VariableNames=["Technology", "VehicleUeId"]), ...
    "rows", "stable");
for perspective = ["transmitter", "receiver"]
    [accumulator, ~] = ensurePerVehicleRows( ...
        accumulator, seenVehicles.Technology, ...
        seenVehicles.VehicleUeId, ...
        repmat(perspective, height(seenVehicles), 1), ...
        repmat("all", height(seenVehicles), 1));
end

[accumulator, transmitterRows] = ensurePerVehicleRows( ...
    accumulator, technologies, transmitters, ...
    repmat("transmitter", height(chunk), 1), ...
    repmat("all", height(chunk), 1));
[accumulator, receiverRows] = ensurePerVehicleRows( ...
    accumulator, technologies, receivers, ...
    repmat("receiver", height(chunk), 1), ...
    repmat("all", height(chunk), 1));
accumulator.FateCount = accumulator.FateCount + ...
    accumarray( ...
        [transmitterRows; receiverRows], 1, ...
        [numel(accumulator.Keys), 1]);

if ~any(withinGrid)
    return
end
within = find(withinGrid);
transmitterState = repmat("inactive", numel(within), 1);
transmitterState(transmitterActive(within)) = "active";
receiverState = repmat("inactive", numel(within), 1);
receiverState(receiverActive(within)) = "active";
contributions = table( ...
    [technologies(within); technologies(within); ...
        technologies(within); technologies(within)], ...
    [transmitters(within); receivers(within); ...
        transmitters(within); receivers(within)], ...
    [repmat("transmitter", numel(within), 1); ...
        repmat("receiver", numel(within), 1); ...
        repmat("transmitter", numel(within), 1); ...
        repmat("receiver", numel(within), 1)], ...
    [repmat("all", numel(within), 1); ...
        repmat("all", numel(within), 1); ...
        transmitterState; receiverState], ...
    repmat(binIndex(within), 4, 1), ...
    repmat(outcomeIndex(within), 4, 1), ...
    VariableNames=[ ...
        "Technology", "VehicleUeId", "Perspective", ...
        "ExposureState", "BinIndex", "OutcomeIndex"]);
[groups, groupRows] = findgroups(contributions);
groupCounts = accumarray(groups, 1);
[accumulator, metricRows] = ensurePerVehicleRows( ...
    accumulator, groupRows.Technology, ...
    groupRows.VehicleUeId, groupRows.Perspective, ...
    groupRows.ExposureState);
columnCount = size(accumulator.BinOutcomeCounts, 2);
binCount = columnCount ./ 3;
countColumns = ...
    (groupRows.OutcomeIndex - 1) .* binCount + ...
    groupRows.BinIndex;
linearIndices = sub2ind( ...
    size(accumulator.BinOutcomeCounts), ...
    metricRows, countColumns);
accumulator.BinOutcomeCounts(linearIndices) = ...
    accumulator.BinOutcomeCounts(linearIndices) + ...
    groupCounts;
stateRows = groupRows.ExposureState ~= "all";
if any(stateRows)
    accumulator.FateCount = accumulator.FateCount + ...
        accumarray( ...
            metricRows(stateRows), groupCounts(stateRows), ...
            [numel(accumulator.Keys), 1]);
end
end

function [accumulator, rowIndices] = ensurePerVehicleRows( ...
        accumulator, technology, vehicleUeId, perspective, ...
        exposureState)
technology = string(technology);
vehicleUeId = string(vehicleUeId);
perspective = string(perspective);
exposureState = string(exposureState);
keys = vehicleMetricKeys( ...
    technology, vehicleUeId, perspective, exposureState);
[known, rowIndices] = ismember(keys, accumulator.Keys);
if any(~known)
    newRows = unique( ...
        table( ...
            keys(~known), technology(~known), ...
            vehicleUeId(~known), perspective(~known), ...
            exposureState(~known), ...
            VariableNames=[ ...
                "Key", "Technology", "VehicleUeId", ...
                "Perspective", "ExposureState"]), ...
        "rows", "stable");
    oldCount = numel(accumulator.Keys);
    newCount = height(newRows);
    accumulator.Keys = [accumulator.Keys; newRows.Key];
    accumulator.Technology = [ ...
        accumulator.Technology; newRows.Technology];
    accumulator.VehicleUeId = [ ...
