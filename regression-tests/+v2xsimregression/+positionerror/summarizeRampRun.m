function metrics = packetMetricsFromReduction( ...
        reduction, categoryName, distanceGrid)
categoryRow = find( ...
    reduction.CategoryNames == categoryName, 1);
if isempty(categoryRow)
    error( ...
        "v2xsimregression:positionerror:" + ...
        "UnknownPacketMetricCategory", ...
        "Unknown packet reduction category: %s.", categoryName);
end
outcomeCounts = ...
    reduction.CategoryOutcomeCounts(categoryRow, :);
metrics = struct( ...
    "CorrectCount", outcomeCounts(1), ...
    "ErrorCount", outcomeCounts(2), ...
    "BlockedCount", outcomeCounts(3), ...
    "DeliveryPrrAuc", NaN, ...
    "RadioPrrAuc", NaN, ...
    "Status", "Incomplete");
if reduction.CategoryFateCounts(categoryRow) == 0
    metrics.Status = "NoTerminalFates";
    return
end

binCount = numel(distanceGrid);
counts = reduction.CategoryBinOutcomeCounts(categoryRow, :);
correctCounts = counts(1:binCount);
errorCounts = counts(binCount + (1:binCount));
blockedCounts = counts(2 .* binCount + (1:binCount));
[metrics.DeliveryPrrAuc, deliveryStatus] = ...
    scoreBinnedCounts( ...
        correctCounts, ...
        correctCounts + errorCounts + blockedCounts, ...
        distanceGrid);
if deliveryStatus == "Complete"
    metrics.Status = "Complete";
end
[metrics.RadioPrrAuc, ~] = scoreBinnedCounts( ...
    correctCounts, correctCounts + errorCounts, distanceGrid);
end

function value = meanVariable(rows, variableName)
if isempty(rows) || ...
        ~ismember(variableName, ...
            string(rows.Properties.VariableNames))
    value = NaN;
    return
end
values = double(rows.(variableName));
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = linearQuantile(values, probability)
values = sort(values(:));
if isscalar(values)
    value = values;
    return
end
position = 1 + (numel(values) - 1) .* probability;
lowerIndex = floor(position);
upperIndex = ceil(position);
weight = position - lowerIndex;
value = values(lowerIndex) .* (1 - weight) + ...
    values(upperIndex) .* weight;
end
