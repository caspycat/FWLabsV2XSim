function values = previousStateAtTimes( ...
        vehicleIds, queryTimes, temporalState)
rowCount = numel(vehicleIds);
if isstring(temporalState.DefaultValue)
    values = repmat(temporalState.DefaultValue, rowCount, 1);
else
    values = repmat( ...
        logical(temporalState.DefaultValue), rowCount, 1);
end
if rowCount == 0 || isempty(temporalState.VehicleIds)
    return
end
[knownVehicles, stateRows] = ismember( ...
    string(vehicleIds), temporalState.VehicleIds);
for stateRow = unique(stateRows(knownVehicles)).'
    queryRows = stateRows == stateRow;
    times = temporalState.Times{stateRow};
    stateValues = temporalState.Values{stateRow};
    bins = discretize( ...
        double(queryTimes(queryRows)), ...
        [-Inf; times; Inf]);
    previousRows = bins - 1;
    matched = previousRows >= 1 & ...
        previousRows <= numel(times);
    queryValues = repmat( ...
        temporalState.DefaultValue, nnz(queryRows), 1);
    queryValues(matched) = stateValues(previousRows(matched));
    values(queryRows) = queryValues;
end
end

