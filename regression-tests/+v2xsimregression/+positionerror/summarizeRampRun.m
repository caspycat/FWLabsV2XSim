function summary = summarizeRampRun( ...
        runDirectory, maximumDistanceMeters, ...
        distanceBinWidthMeters, options)
%SUMMARIZERAMPRUN Reduce one completed ramp-error run to study metrics.
%   Raw trace files remain the source of truth. This reducer pools packet
%   counts before ratios, scores a fixed distance grid, stratifies packet
%   delivery by whether either endpoint is actively affected, and
%   summarizes controller-visible topology and allocation differences.

arguments (Input)
    runDirectory (1, 1) string {mustBeNonzeroLengthText}
    maximumDistanceMeters (1, 1) double ...
        {mustBeReal, mustBeFinite, mustBePositive}
    distanceBinWidthMeters (1, 1) double ...
        {mustBeReal, mustBeFinite, mustBePositive}
    options.MaximumExposedShadowCases (1, 1) double ...
        {mustBeReal, mustBePositive} = 1000
    options.ExposedShadowEvaluationHorizonSeconds (1, 1) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = 0.1
    options.MinimumShadowReceiverObservationCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 10
    options.ExposedShadowSelectionSeed (1, 1) double ...
        {mustBeInteger, mustBeNonnegative} = 0
end

arguments (Output)
    summary (1, 1) struct
end

if ~isfolder(runDirectory)
    error( ...
        "v2xsimregression:positionerror:MissingRunDirectory", ...
        "Run directory does not exist: %s", runDirectory);
end
if mod(maximumDistanceMeters, distanceBinWidthMeters) ~= 0
    error( ...
        "v2xsimregression:positionerror:MisalignedPrrGrid", ...
        "Maximum distance must be an integer multiple of bin width.");
end
