function [candidates, evidenceAvailable] = ...
        validClassifierReuseCandidates(candidates)
requiredNames = [ ...
    "AllocationEpoch", "NetworkSliceId", ...
    "FirstUeId", "SecondUeId", "CandidateType", ...
    "LiveResourceRelation", "OracleResourceRelation", ...
    "IsHarmfulInterferenceOverlap", ...
    "IsMissedInterferenceOverlap"];
evidenceAvailable = all(ismember( ...
        requiredNames, ...
        string(candidates.Properties.VariableNames)));
if ~evidenceAvailable
    candidates = table();
    return
end
candidates = candidates(:, requiredNames);
for variableName = [ ...
        "NetworkSliceId", "FirstUeId", "SecondUeId", ...
        "CandidateType", "LiveResourceRelation", ...
        "OracleResourceRelation"]
    candidates.(variableName) = ...
        string(candidates.(variableName));
end
for variableName = [ ...
        "IsHarmfulInterferenceOverlap", ...
        "IsMissedInterferenceOverlap"]
    candidates.(variableName) = logicalColumn( ...
        candidates.(variableName), variableName);
end
end

function events = buildFailureEvents( ...
        classified, coverage, transmitterActive, receiverActive, ...
        transmitterRoutes, receiverRoutes, ...
        allocatorEvidenceAvailable)
if height(classified) ~= height(coverage) || ...
        height(classified) ~= numel(transmitterActive) || ...
        height(classified) ~= numel(receiverActive) || ...
        height(classified) ~= numel(transmitterRoutes) || ...
        height(classified) ~= numel(receiverRoutes)
    error( ...
        "v2xsimregression:positionerror:" + ...
        "FailureEvidenceAlignmentMismatch", ...
        "Failure classification, coverage, route, and status-effect " + ...
        "activity " + ...
        "rows must remain aligned.");
end

errorRows = classified.Outcome == "error";
events = classified(errorRows, :);
events.HasAttemptEvidence = ...
    coverage.HasAttemptEvidence(errorRows);
events.EvidenceIsExhaustive = ...
    coverage.EvidenceIsExhaustive(errorRows);
events.CounterfactualCount = ...
    coverage.CounterfactualCount(errorRows);
events.AllocatorEvidenceAvailable = repmat( ...
    allocatorEvidenceAvailable, height(events), 1);
events.TransmitterPositionErrorActive = ...
    transmitterActive(errorRows);
events.ReceiverPositionErrorActive = ...
    receiverActive(errorRows);
events.EitherEndpointPositionErrorActive = ...
    transmitterActive(errorRows) | receiverActive(errorRows);
events.TransmitterTrueRoute = transmitterRoutes(errorRows);
events.ReceiverTrueRoute = receiverRoutes(errorRows);
end

function evidence = sparseFailureEvidence(evidence)
% Raw interference chunks remain authoritative for joint mechanisms.
% This joined convenience artifact retains only rows that are individually
% sufficient to change decoding or are linked to harmful interference
% overlap.
if isempty(evidence)
    return
end
retain = ...
    evidence.SinrWithoutInterfererDb >= ...
        evidence.DecodeThresholdDb | ...
    evidence.IsHarmfulReuseCandidate;
evidence = evidence(retain, :);
end

function count = overallTerminalRadioFateCount(reduction)
allRow = reduction.CategoryNames == "all";
if nnz(allRow) ~= 1
    error( ...
        "v2xsimregression:positionerror:" + ...
        "InvalidPacketReduction", ...
        "Packet reduction must contain one all-fates category.");
end
count = sum( ...
    reduction.CategoryOutcomeCounts(allRow, 1:2));
end

function summary = summarizeFailureModes( ...
        events, allocatorEvidenceAvailable, ...
        terminalRadioFateCount)
modeOrder = [ ...
    "hidden_terminal", "half_duplex", ...
    "cochannel_interference", ...
    "adjacent_channel_interference", ...
    "cross_technology_interference", ...
    "multiple_sufficient_interferers", ...
    "joint_interference", "other_interference", ...
    "noise_or_propagation", ...
    "unclassified_missing_counterfactual", ...
    "unclassified_incomplete_counterfactual"];
primaryModeCount = 9;
errorCount = height(events);
interferenceEvidenceComplete = errorCount == 0 || ...
    all(events.HasAttemptEvidence & ...
        events.EvidenceIsExhaustive);
detectedCount = zeros(numel(modeOrder), 1);
statusEffectActiveTransmitterCount = zeros(numel(modeOrder), 1);
statusEffectActiveReceiverCount = zeros(numel(modeOrder), 1);
eitherEndpointStatusEffectActiveCount = ...
    zeros(numel(modeOrder), 1);
for modeIndex = 1:numel(modeOrder)
    if modeOrder(modeIndex) == "hidden_terminal"
        modeRows = events.IsHiddenTerminal;
    else
        modeRows = events.FailureMode == modeOrder(modeIndex);
    end
    detectedCount(modeIndex) = nnz(modeRows);
    statusEffectActiveTransmitterCount(modeIndex) = nnz( ...
        modeRows & events.TransmitterPositionErrorActive);
    statusEffectActiveReceiverCount(modeIndex) = nnz( ...
        modeRows & events.ReceiverPositionErrorActive);
    eitherEndpointStatusEffectActiveCount(modeIndex) = nnz( ...
        modeRows & events.EitherEndpointPositionErrorActive);
end

observedCompositionRate = divideOrNaN( ...
    detectedCount, repmat(errorCount, numel(modeOrder), 1));
observedIncidenceRate = divideOrNaN( ...
    detectedCount, ...
    repmat(terminalRadioFateCount, numel(modeOrder), 1));
count = detectedCount;
compositionRate = observedCompositionRate;
incidenceRate = observedIncidenceRate;
countStatus = repmat("Descriptive", numel(modeOrder), 1);
compositionRateStatus = countStatus;
incidenceRateStatus = countStatus;
for modeIndex = 1:primaryModeCount
    modeIsHidden = modeOrder(modeIndex) == "hidden_terminal";
    [modeComplete, incompleteStatus] = ...
        modeEvidenceStatus( ...
            modeIsHidden, interferenceEvidenceComplete, ...
            allocatorEvidenceAvailable);
    if ~modeComplete
        count(modeIndex) = NaN;
        compositionRate(modeIndex) = NaN;
        incidenceRate(modeIndex) = NaN;
        countStatus(modeIndex) = incompleteStatus;
        compositionRateStatus(modeIndex) = incompleteStatus;
        incidenceRateStatus(modeIndex) = incompleteStatus;
        continue
    end
    countStatus(modeIndex) = "Analyzable";
    if errorCount == 0
        compositionRate(modeIndex) = NaN;
        compositionRateStatus(modeIndex) = ...
            "NotAnalyzableNoTerminalErrors";
    else
        compositionRateStatus(modeIndex) = "Analyzable";
    end
    if terminalRadioFateCount == 0
        incidenceRate(modeIndex) = NaN;
        incidenceRateStatus(modeIndex) = ...
            "NotAnalyzableNoTerminalRadioFates";
    else
        incidenceRateStatus(modeIndex) = "Analyzable";
    end
end

compositionDenominator = repmat( ...
    errorCount, numel(modeOrder), 1);
incidenceDenominator = repmat( ...
    terminalRadioFateCount, numel(modeOrder), 1);
summary = table( ...
    modeOrder.', detectedCount, count, ...
    observedCompositionRate, compositionRate, ...
    compositionRate, observedIncidenceRate, incidenceRate, ...
    incidenceRate, compositionDenominator, ...
    incidenceDenominator, countStatus, ...
    compositionRateStatus, incidenceRateStatus, ...
    statusEffectActiveTransmitterCount, ...
    statusEffectActiveReceiverCount, ...
    eitherEndpointStatusEffectActiveCount, ...
    repmat(allocatorEvidenceAvailable, numel(modeOrder), 1), ...
    repmat( ...
        interferenceEvidenceComplete, numel(modeOrder), 1), ...
    VariableNames=[ ...
        "FailureMode", "DetectedCount", "Count", ...
        "ObservedCompositionRate", "CompositionRate", ...
        "RateAmongErrors", "ObservedIncidenceRate", ...
        "IncidenceRate", "RateAmongTerminalRadioFates", ...
        "CompositionDenominator", "IncidenceDenominator", ...
        "CountStatus", "CompositionRateStatus", ...
        "IncidenceRateStatus", ...
        "StatusEffectActiveTransmitterCount", ...
        "StatusEffectActiveReceiverCount", ...
        "EitherEndpointStatusEffectActiveCount", ...
        "AllocatorEvidenceAvailable", ...
        "InterferenceEvidenceComplete"]);
end

function [complete, status] = modeEvidenceStatus( ...
        isHidden, interferenceEvidenceComplete, ...
        allocatorEvidenceAvailable)
if isHidden && ~allocatorEvidenceAvailable
    complete = false;
    status = "NotAnalyzableMissingAllocatorEvidence";
elseif ~interferenceEvidenceComplete
    complete = false;
    status = ...
        "NotAnalyzableIncompleteInterferenceEvidence";
else
    complete = true;
    status = "Analyzable";
end
end

function metrics = failureSummaryMetrics( ...
        events, modeSummary, allocatorEvidenceAvailable, ...
        terminalRadioFateCount)
errorCount = height(events);
unclassified = startsWith( ...
    events.FailureMode, "unclassified_");
coveredCount = nnz(events.HasAttemptEvidence);
exhaustiveCount = nnz(events.EvidenceIsExhaustive);
hidden = events.IsHiddenTerminal;
eitherEndpointStatusEffectActive = ...
    events.EitherEndpointPositionErrorActive;
interferenceEvidenceComplete = errorCount == 0 || ...
    all(events.HasAttemptEvidence & ...
        events.EvidenceIsExhaustive);

if errorCount == 0
    status = "NoErrors";
elseif ~allocatorEvidenceAvailable
    status = "IncompleteAllocatorEvidence";
elseif coveredCount == 0
    status = "NoInterferenceEvidence";
elseif exhaustiveCount == errorCount
    status = "Complete";
else
    status = "IncompleteInterferenceEvidence";
end

hiddenCount = modeValue( ...
    modeSummary, "hidden_terminal", "Count");
hiddenDetectedCount = modeValue( ...
    modeSummary, "hidden_terminal", "DetectedCount");
hiddenCompositionRate = modeValue( ...
    modeSummary, "hidden_terminal", "CompositionRate");
hiddenIncidenceRate = modeValue( ...
    modeSummary, "hidden_terminal", "IncidenceRate");
hiddenIsAnalyzable = isfinite(hiddenCount);
generalMode = "half_duplex";
