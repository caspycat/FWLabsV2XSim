    errorFates.TransmitterUeId, ...
    errorFates.FateTimeSeconds, positionState);
receiverRoutes = endpointRoutes( ...
    errorFates.ReceiverUeId, ...
    errorFates.FateTimeSeconds, positionState);
[classifierCandidates, allocatorEvidenceAvailable] = ...
    validClassifierReuseCandidates(reuseCandidates);
[classifiedFates, failureEvidence, failureCoverage] = ...
    v2xsim.analysis.classifyRecordedFailureModes( ...
        errorFates, interferenceAttempts, ...
        interferenceCounterfactuals, ...
        classifierCandidates);
failureEvidence = sparseFailureEvidence(failureEvidence);
failureEvents = buildFailureEvents( ...
    classifiedFates, failureCoverage, ...
    transmitterActive, receiverActive, ...
    transmitterRoutes, receiverRoutes, ...
    allocatorEvidenceAvailable);
terminalRadioFateCount = overallTerminalRadioFateCount( ...
    packetReduction);
failureModeSummary = summarizeFailureModes( ...
    failureEvents, allocatorEvidenceAvailable, ...
    terminalRadioFateCount);
writetable( ...
    failureEvents, ...
    fullfile(runDirectory, "failure_mode_events.csv"));
writetable( ...
    failureEvidence, ...
    fullfile(runDirectory, "failure_mode_evidence.csv"));
writetable( ...
    failureModeSummary, ...
    fullfile(runDirectory, "failure_mode_summary.csv"));
failureMetrics = failureSummaryMetrics( ...
    failureEvents, failureModeSummary, ...
    allocatorEvidenceAvailable, terminalRadioFateCount);

perVehicleMetrics = finalizePerVehicleMetrics( ...
    packetReduction.PerVehicle, positionTrace, distanceGrid);
writetable( ...
    perVehicleMetrics, ...
    fullfile(runDirectory, "per_vehicle_prr.csv"));
allPacketMetrics = packetMetricsFromReduction( ...
    packetReduction, "all", distanceGrid);
statusEffectActiveTransmitterMetrics = packetMetricsFromReduction( ...
    packetReduction, "status_effect_active_transmitter", distanceGrid);
statusEffectActiveReceiverMetrics = packetMetricsFromReduction( ...
    packetReduction, "status_effect_active_receiver", distanceGrid);
eitherEndpointStatusEffectActiveMetrics = packetMetricsFromReduction( ...
    packetReduction, ...
    "either_endpoint_status_effect_active", distanceGrid);
mainlineMetrics = packetMetricsFromReduction( ...
    packetReduction, "mainline_transmitter", distanceGrid);
rampMetrics = packetMetricsFromReduction( ...
    packetReduction, "ramp_transmitter", distanceGrid);
[harmfulCandidateCount, missedCandidateCount, ...
        meanHarmfulCandidateRate, meanMissedCandidateRate, ...
        harmfulInterferenceOverlapCandidateCount, ...
        missedInterferenceOverlapCandidateCount, ...
        meanHarmfulInterferenceOverlapCandidateRate, ...
        meanMissedInterferenceOverlapCandidateRate] = ...
    summarizeReuseCandidates( ...
        reuseCandidates, allocationSummary);

