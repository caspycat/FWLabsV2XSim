function events = compactLifecycleEvents(positionTrace)
canonical = v2xsim.positioning.diagnostics.emptyTable();
traceOutputNames = [ ...
    "SimulationTimeSeconds", "VehicleId", "ModuleIndex", ...
    "ModuleType", "StatusEffectType", "TrueRoute", "EpisodeId", ...
    "IsSelected", "IsActive", "IsEvaluated", ...
    "EvaluationOccurred", "SelectionOccurred", ...
    "ActiveSegmentEntered", "ActiveSegmentExited", ...
    "ResetOccurred", "LeftCensoredAtStart", ...
    "LifecycleEvent"];
outputNames = [ ...
    traceOutputNames(1:end - 1), ...
    "RightCensoredAtEnd", "LifecycleEvent"];
if isempty(positionTrace) && width(positionTrace) == 0
    events = canonical(:, traceOutputNames);
    events.RightCensoredAtEnd = false(0, 1);
    events = events(:, outputNames);
    return
end
actualNames = string(positionTrace.Properties.VariableNames);
if any(~ismember(traceOutputNames, actualNames))
    error( ...
        "v2xsimregression:positionerror:InvalidPositionTrace", ...
        "Position-error trace is missing lifecycle-event columns.");
end
eventRows = ...
    logical(positionTrace.EvaluationOccurred) | ...
    logical(positionTrace.SelectionOccurred) | ...
    logical(positionTrace.ActiveSegmentEntered) | ...
    logical(positionTrace.ActiveSegmentExited) | ...
    logical(positionTrace.ResetOccurred) | ...
    logical(positionTrace.LeftCensoredAtStart);
events = positionTrace(eventRows, traceOutputNames);
events.RightCensoredAtEnd = false(height(events), 1);
events = events(:, outputNames);

rightCensoredEvents = rightCensoredLifecycleEvents( ...
    positionTrace, traceOutputNames, outputNames);
events = [events; rightCensoredEvents];
events.VehicleId = string(events.VehicleId);
events.ModuleType = string(events.ModuleType);
events.StatusEffectType = string(events.StatusEffectType);
events.TrueRoute = string(events.TrueRoute);
events.LifecycleEvent = string(events.LifecycleEvent);
events = sortrows( ...
    events, ["SimulationTimeSeconds", "VehicleId", ...
        "ModuleIndex", "RightCensoredAtEnd"]);
end

function events = rightCensoredLifecycleEvents( ...
        positionTrace, traceOutputNames, outputNames)
events = positionTrace([], traceOutputNames);
events.RightCensoredAtEnd = false(0, 1);
events = events(:, outputNames);

moduleRows = double(positionTrace.ModuleIndex) > 0 & ...
    strlength(string(positionTrace.StatusEffectType)) > 0;
moduleTrace = positionTrace(moduleRows, :);
if isempty(moduleTrace)
    return
end
vehicleIds = string(moduleTrace.VehicleId);
moduleTypes = string(moduleTrace.ModuleType);
statusEffectTypes = string(moduleTrace.StatusEffectType);
[groups, ~, ~, ~, ~] = findgroups( ...
    vehicleIds, double(moduleTrace.ModuleIndex), ...
    moduleTypes, statusEffectTypes);
traceRows = (1:height(moduleTrace)).';
finalRows = splitapply( ...
    @lastObservedRow, traceRows, ...
    double(moduleTrace.SimulationTimeSeconds), groups);
activeAtEnd = logical(moduleTrace.IsActive(finalRows));
hasEpisode = isfinite(double( ...
    moduleTrace.EpisodeId(finalRows)));
finalRows = finalRows(activeAtEnd & hasEpisode);
if isempty(finalRows)
    return
end

events = moduleTrace(finalRows, traceOutputNames);
events.EvaluationOccurred(:) = false;
events.SelectionOccurred(:) = false;
events.ActiveSegmentEntered(:) = false;
events.ActiveSegmentExited(:) = false;
events.ResetOccurred(:) = false;
events.LeftCensoredAtStart(:) = false;
events.LifecycleEvent(:) = "RightCensoredAtEnd";
events.RightCensoredAtEnd = true(height(events), 1);
events = events(:, outputNames);
end

