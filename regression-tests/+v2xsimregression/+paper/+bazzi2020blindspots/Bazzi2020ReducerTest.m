    "durations = (0.1:0.1:15).';", ...
    "wbsTotal = repmat(100000, numel(durations), 1);", ...
    "greaterOrEqual = round(wbsTotal .* 10 .^ (-durations ./ 3));", ...
    "shorter = wbsTotal - greaterOrEqual;", ...
    "probability = greaterOrEqual ./ wbsTotal;", ...
    "wirelessBlindSpot = [durations, greaterOrEqual, shorter, " + ...
        "probability, greaterOrEqual, shorter, probability];", ...
    "writematrix(wirelessBlindSpot, fullfile(outputDirectory, " + ...
