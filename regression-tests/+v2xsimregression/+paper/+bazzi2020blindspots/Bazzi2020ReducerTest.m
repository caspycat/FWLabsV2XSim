function verifyConfigurationSetting( ...
        testCase, configuration, key, expectedValue)
lines = strtrim(splitlines(configuration));
prefix = "[" + key + "]";
matchingLines = lines(startsWith(lines, prefix));
testCase.assertNumElements( ...
    matchingLines, 1, ...
    "Expected exactly one configuration entry for " + key + ".");
actualValue = strtrim(extractAfter(matchingLines, strlength(prefix)));
testCase.verifyEqual(actualValue, expectedValue);
end

