    Path=path, ...
    Stream=stream, ...
    StreamState=stream.State, ...
    WarningState=warning);
end

function verifyEnvironment(testCase, environment)
testCase.verifyEqual(path, environment.Path);
testCase.verifyTrue(isequal( ...
    RandStream.getGlobalStream(), environment.Stream));
testCase.verifyEqual( ...
    environment.Stream.State, environment.StreamState);
testCase.verifyEqual(warning, environment.WarningState);
end

function restoreEnvironment(environment)
path(environment.Path);
RandStream.setGlobalStream(environment.Stream);
environment.Stream.State = environment.StreamState;
warning(environment.WarningState);
end

function [first, second] = syntheticPrrOutputs()
distances = (10:10:300).';
firstTotal = repmat(100, numel(distances), 1);
secondTotal = repmat(300, numel(distances), 1);
firstCorrect = round(firstTotal .* linspace(0.99, 0.55, ...
    numel(distances)).');
secondCorrect = round(secondTotal .* linspace(0.98, 0.65, ...
    numel(distances)).');
firstError = firstTotal - firstCorrect;
secondError = secondTotal - secondCorrect;
first = [ ...
    distances, firstCorrect, firstError, ...
    zeros(size(distances)), firstTotal, ...
    firstCorrect ./ firstTotal];
second = [ ...
    distances, secondCorrect, secondError, ...
    zeros(size(distances)), secondTotal, ...
    secondCorrect ./ secondTotal];
end

function [first, second] = syntheticWbsOutputs()
durations = (0.1:0.1:15).';
firstTotal = 100000;
secondTotal = 300000;
probabilities = 10 .^ (-durations);
firstGreaterOrEqual = round(firstTotal .* probabilities);
secondGreaterOrEqual = round(secondTotal .* probabilities);
firstShorter = firstTotal - firstGreaterOrEqual;
secondShorter = secondTotal - secondGreaterOrEqual;
firstProbability = firstGreaterOrEqual ./ firstTotal;
secondProbability = secondGreaterOrEqual ./ secondTotal;
first = [ ...
    durations, firstGreaterOrEqual, firstShorter, firstProbability, ...
    firstGreaterOrEqual, firstShorter, firstProbability];
second = [ ...
    durations, secondGreaterOrEqual, secondShorter, secondProbability, ...
    secondGreaterOrEqual, secondShorter, secondProbability];
end

function seedResults = syntheticSeedSummary(manifest)
seedResults = manifest(:, [ ...
    "Profile", "Scenario", "DensityVehiclesPerKilometer", ...
    "SpeedKilometersPerHour", "Scheme", "SimulationSeed"]);
seedResults.Properties.VariableNames(end) = "RandomSeed";
seedOffset = 0.0001 .* seedResults.RandomSeed;
scenarioOffset = 0.01 .* ...
    double(seedResults.Scenario == "congested");

prrSchemeEffect = zeros(height(seedResults), 1);
wbsSchemeEffect = zeros(height(seedResults), 1);
rangeSchemeEffect = zeros(height(seedResults), 1);
for scheme = unique(seedResults.Scheme, "stable").'
    selected = seedResults.Scheme == scheme;
    if scheme == "legacy-p0"
        prrSchemeEffect(selected) = 0;
        rangeSchemeEffect(selected) = 0;
        wbsSchemeEffect(selected) = 0.01;
    elseif scheme == "legacy-p08"
        prrSchemeEffect(selected) = 0.08;
        rangeSchemeEffect(selected) = 20;
        wbsSchemeEffect(selected) = 0.02;
    elseif scheme == "capped-m2"
        prrSchemeEffect(selected) = 0.04;
        rangeSchemeEffect(selected) = 10;
        wbsSchemeEffect(selected) = 0.004;
    else
        prrSchemeEffect(selected) = 0.07;
        rangeSchemeEffect(selected) = 18;
        wbsSchemeEffect(selected) = 0.008;
    end
end

seedResults.PrrAuc0To300 = ...
    0.7 + scenarioOffset + seedOffset + prrSchemeEffect;
seedResults.PrrRangeAt90Meters = ...
    100 + 100 .* scenarioOffset + rangeSchemeEffect;
seedResults.WbsTailProbabilityAuc2To10Seconds = ...
    wbsSchemeEffect + seedOffset;
end

