        function testCrossingInterpolationAndCensoring(testCase)
            crossingFunction = @(x, y) ...
                v2xsimregression.paper.bazzi2020blindspots. ...
                firstDownwardCrossing(x, y, 1e-4);

            [crossedValue, crossedStatus] = crossingFunction( ...
                [1; 2; 3], [2e-4; 1.5e-4; 0.5e-4]);
            testCase.verifyEqual(crossedValue, 2.5, AbsTol=1e-14);
            testCase.verifyEqual(crossedStatus, "crossed");

            [leftValue, leftStatus] = crossingFunction( ...
                [0.1; 0.2], [0.5e-4; 0.25e-4]);
            testCase.verifyEqual(leftValue, 0.1);
            testCase.verifyEqual(leftStatus, "left_censored");

            [rightValue, rightStatus] = crossingFunction( ...
                [10; 20], [3e-4; 2e-4]);
            testCase.verifyEqual(rightValue, 20);
            testCase.verifyEqual(rightStatus, "right_censored");
        end

        function testPoolsRawCountsBeforeCalculatingMetrics(testCase)
            [firstPrr, secondPrr] = syntheticPrrOutputs();
            [firstWbs, secondWbs] = syntheticWbsOutputs();

            [metrics, pooledPrr, pooledWbs] = ...
                v2xsimregression.paper.bazzi2020blindspots. ...
                reduceCountOutputs( ...
                    {firstPrr, secondPrr}, ...
                    {firstWbs, secondWbs}, ...
                    WirelessBlindSpotMaximumDelaySeconds=15);

            expectedCorrect = ...
                firstPrr(:, 2) + secondPrr(:, 2);
            expectedTotal = ...
                firstPrr(:, 5) + secondPrr(:, 5);
            expectedPrr = expectedCorrect ./ expectedTotal;
            expectedAuc = trapz( ...
                [0; (10:10:300).'], ...
                [expectedPrr(1); expectedPrr]) ./ 300;
            testCase.verifyEqual( ...
                pooledPrr.CorrectCount, expectedCorrect);
            testCase.verifyEqual( ...
                pooledPrr.TotalCount, expectedTotal);
            testCase.verifyEqual( ...
                pooledPrr.PacketReceptionRatio, expectedPrr, ...
                AbsTol=1e-14);
            testCase.verifyEqual( ...
                metrics.PrrAuc0To300, expectedAuc, ...
                AbsTol=1e-14);
            testCase.verifyEqual( ...
                metrics.PrrCorrectCount0To300, ...
                sum(expectedCorrect));
            testCase.verifyEqual( ...
                metrics.PrrTotalCount0To300, sum(expectedTotal));

            expectedWbsGreaterOrEqual = ...
                firstWbs(:, 2) + secondWbs(:, 2);
            expectedWbsTotal = ...
                sum(firstWbs(:, 2:3), 2) + ...
                sum(secondWbs(:, 2:3), 2);
            expectedWbsProbability = ...
                expectedWbsGreaterOrEqual ./ expectedWbsTotal;
            tailRows = ...
                pooledWbs.DurationSeconds >= 2 & ...
                pooledWbs.DurationSeconds <= 10;
            expectedWbsAuc = trapz( ...
                pooledWbs.DurationSeconds(tailRows), ...
                expectedWbsProbability(tailRows));
            testCase.verifyEqual( ...
                pooledWbs.GreaterOrEqualCount, ...
                expectedWbsGreaterOrEqual);
            testCase.verifyEqual( ...
                pooledWbs.Probability, expectedWbsProbability, ...
                AbsTol=1e-14);
            testCase.verifyEqual( ...
                metrics.WbsTailProbabilityAuc2To10Seconds, ...
                expectedWbsAuc, AbsTol=1e-14);
            testCase.verifyEqual( ...
                metrics.WbsThresholdCrossingStatus, "crossed");
        end

