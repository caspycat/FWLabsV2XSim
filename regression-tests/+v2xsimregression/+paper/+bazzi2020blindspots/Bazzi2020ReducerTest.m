        function testPairedBootstrapIsDeterministicAndStreamLocal( ...
                testCase)
            manifest = ...
                v2xsimregression.paper.bazzi2020blindspots. ...
                createCampaignManifest( ...
                    "shortened", "campaign-output", 10:14);
            seedResults = syntheticSeedSummary(manifest);

            originalStream = RandStream.getGlobalStream();
            originalState = originalStream.State;
            cleanup = onCleanup(@() restoreGlobalStream( ...
                originalStream, originalState));

            first = ...
                v2xsimregression.paper.bazzi2020blindspots. ...
                buildPairedComparisons( ...
                    seedResults, "shortened", 10:14, 200);
            second = ...
                v2xsimregression.paper.bazzi2020blindspots. ...
                buildPairedComparisons( ...
                    seedResults, "shortened", 10:14, 200);

            testCase.verifyEqual(first, second);
            testCase.verifyEqual(height(first), 8);
            testCase.verifyEqual( ...
                originalStream.State, originalState, ...
                "Bootstrap resampling must not consume the global stream.");
            legacyTradeoff = first( ...
                first.Scenario == "light" & ...
                first.ReferenceScheme == "legacy-p0" & ...
                first.CandidateScheme == "legacy-p08", :);
            testCase.verifyGreaterThan( ...
                legacyTradeoff.PrrAucDifferenceLower95Percentile, 0);
            testCase.verifyGreaterThan( ...
                legacyTradeoff. ...
                WbsTailAucDifferenceLower95Percentile, 0);
        end

