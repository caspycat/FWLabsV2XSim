row = table( ...
    manifestRow.Profile, manifestRow.Scenario, ...
    manifestRow.DensityVehiclesPerKilometer, ...
    manifestRow.SpeedKilometersPerHour, ...
    manifestRow.RoadLengthMeters, manifestRow.VehicleCount, ...
    manifestRow.Scheme, manifestRow.KeepResourceProbability, ...
    manifestRow.MaximumConsecutiveReservationIntervals, ...
    manifestRow.SimulationSeed, manifestRow.ScenarioSeed, ...
    manifestRow.AllocatorSeed, manifestRow.SimulationTimeSeconds, ...
    manifestRow.WirelessBlindSpotMaximumDelaySeconds, ...
    metrics.PrrAuc0To300, metrics.PrrRangeAt90Meters, ...
    metrics.PrrCorrectCount0To300, ...
    metrics.PrrErrorCount0To300, ...
    metrics.PrrBlockedCount0To300, ...
    metrics.PrrTotalCount0To300, ...
    metrics.WbsTailProbabilityAuc2To10Seconds, ...
    metrics.WbsProbabilityThreshold, ...
    metrics.WbsThresholdCrossingSeconds, ...
    metrics.WbsThresholdCrossingStatus, ...
    metrics.WbsAt10GreaterOrEqualCount, ...
    metrics.WbsAt10ShorterCount, ...
    metrics.WbsAt10Probability, ...
    manifestRow.OutputDirectory, ...
    VariableNames=summaryVariableNames("seed"));
row.RandomSeed = row.SimulationSeed;
row = movevars(row, "RandomSeed", Before="SimulationSeed");
end

function row = aggregateSummaryRow( ...
        selectedManifest, metrics, outputDirectory)
metadata = selectedManifest(1, :);
row = table( ...
    metadata.Profile, metadata.Scenario, ...
