function [aggregateResults, comparisons] = runPublishedCampaigns( ...
        simulatorRoot, outputDirectory, options)
%RUNPUBLISHEDCAMPAIGNS Run the Bazzi et al. 2020 blind-spot campaign.
%   AGGREGATERESULTS contains one row per scenario and allocation scheme.
%   Raw PRR and WBS counts are pooled across seeds before metrics are
%   derived. COMPARISONS contains deterministic paired-seed percentile
%   bootstrap intervals, expressed as candidate minus reference.

arguments (Input)
    simulatorRoot (1, 1) string {mustBeNonzeroLengthText}
    outputDirectory (1, 1) string {mustBeNonzeroLengthText}
    options.Profile (1, 1) string {mustBeMember( ...
        options.Profile, ["shortened", "publication"])} = "shortened"
    options.RandomSeeds (1, :) double ...
        {mustBeInteger, mustBeNonnegative, ...
        v2xsimregression.paper.bazzi2020blindspots. ...
        mustBeRandomSeeds} = zeros(1, 0)
    options.ExecutionMode (1, 1) string {mustBeMember( ...
        options.ExecutionMode, ["auto", "serial", "parallel"])} = "auto"
    options.MaxWorkers (1, 1) double { ...
        v2xsimregression.execution.mustBeWorkerLimit} = Inf
    options.BootstrapSampleCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 10000
end

arguments (Output)
    aggregateResults table
    comparisons table
end

definition = ...
    v2xsimregression.paper.bazzi2020blindspots. ...
    campaignDefinition(options.Profile);
randomSeeds = options.RandomSeeds;
if isempty(randomSeeds)
    randomSeeds = definition.DefaultRandomSeeds;
end
if numel(unique(randomSeeds)) ~= numel(randomSeeds)
    error( ...
        "v2xsimregression:bazzi2020blindspots:" + ...
        "DuplicateRandomSeed", ...
        "RandomSeeds must not contain duplicates.");
end
if options.BootstrapSampleCount < 40
    error( ...
        "v2xsimregression:bazzi2020blindspots:" + ...
        "InsufficientBootstrapSamples", ...
        "BootstrapSampleCount must be at least 40.");
end

callerWorkingDirectory = string(pwd);
simulatorRoot = absolutePath( ...
    simulatorRoot, callerWorkingDirectory);
outputDirectory = absolutePath( ...
    outputDirectory, callerWorkingDirectory);
simulatorDirectory = fullfile(simulatorRoot, "old_src");
configurationFile = fullfile( ...
    fileparts(mfilename("fullpath")), ...
    "config", "bazzi2020.cfg");
validateSimulator( ...
    simulatorRoot, simulatorDirectory, configurationFile);
prepareOutputDirectory(outputDirectory);

originalPath = path;
originalStream = RandStream.getGlobalStream();
originalStreamState = originalStream.State;
originalWarningState = warning;
environmentCleanup = onCleanup(@() restoreEnvironment( ...
    originalPath, originalStream, originalStreamState, ...
    originalWarningState));

addpath(fullfile(simulatorRoot, "src"));
addpath(simulatorDirectory);

manifest = ...
    v2xsimregression.paper.bazzi2020blindspots. ...
    createCampaignManifest( ...
        options.Profile, outputDirectory, randomSeeds);
manifestStructures = table2struct(manifest);
workItems = cell(1, numel(manifestStructures));
for workIndex = 1:numel(manifestStructures)
    workItem = manifestStructures(workIndex);
    workItem.ConfigurationFile = configurationFile;
    workItem.SimulatorDirectory = simulatorDirectory;
    workItems{workIndex} = workItem;
end

effectiveMaxWorkers = options.MaxWorkers;
if options.Profile == "publication" && isinf(effectiveMaxWorkers)
    % Default conservatively for the 400-1600 vehicle work items. An
    % explicit finite MaxWorkers value remains a caller-owned choice.
    effectiveMaxWorkers = 4;
end
additionalPaths = [ ...
    fullfile(simulatorRoot, "regression-tests"), ...
    fullfile(simulatorRoot, "src"), ...
    simulatorDirectory];
seedDirectoryOutputs = ...
    v2xsimregression.execution.runWorkItems( ...
        workItems, @runSeedWorkItem, ...
        Labels=manifest.Label.', ...
        ExecutionMode=options.ExecutionMode, ...
        MaxWorkers=effectiveMaxWorkers, ...
        AdditionalPaths=additionalPaths, ...
        CollectAllFailures=true);
seedDirectories = string(seedDirectoryOutputs).';
if ~isequal(seedDirectories, manifest.OutputDirectory)
    error( ...
        "v2xsimregression:bazzi2020blindspots:" + ...
        "WorkItemOrderChanged", ...
        "The work scheduler did not preserve manifest result order.");
end

seedResults = summarizeSeeds(manifest, definition);
aggregateResults = summarizeConfigurations( ...
    manifest, definition, outputDirectory);
comparisons = ...
    v2xsimregression.paper.bazzi2020blindspots. ...
    buildPairedComparisons( ...
        seedResults, options.Profile, randomSeeds, ...
        options.BootstrapSampleCount);

writetable( ...
    seedResults, ...
    fullfile(outputDirectory, "campaign-seed-summary.csv"));
writetable( ...
    aggregateResults, ...
    fullfile(outputDirectory, "campaign-summary.csv"));
writetable( ...
    comparisons, ...
    fullfile(outputDirectory, "campaign-comparisons.csv"));

environmentCleanup; %#ok<VUNUS>
end

