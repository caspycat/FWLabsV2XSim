function seedResults = summarizeSeeds(manifest, definition)
rowCells = cell(height(manifest), 1);
for rowIndex = 1:height(manifest)
    directory = manifest.OutputDirectory(rowIndex);
    [prrData, wbsData] = readCountOutputs(directory);
    metrics = ...
        v2xsimregression.paper.bazzi2020blindspots. ...
        reduceCountOutputs( ...
            {prrData}, {wbsData}, ...
            WirelessBlindSpotMaximumDelaySeconds= ...
                definition.WirelessBlindSpotMaximumDelaySeconds);
    rowCells{rowIndex} = seedSummaryRow( ...
        manifest(rowIndex, :), metrics);
end
seedResults = vertcat(rowCells{:});
end

function aggregateResults = summarizeConfigurations( ...
        manifest, definition, outputDirectory)
configurationCount = ...
    numel(definition.ScenarioNames) .* numel(definition.Schemes);
rowCells = cell(configurationCount, 1);
configurationIndex = 0;
for scenario = definition.ScenarioNames
    for scheme = definition.Schemes
        configurationIndex = configurationIndex + 1;
        selected = manifest( ...
            manifest.Scenario == scenario & ...
            manifest.Scheme == scheme, :);
        prrOutputs = cell(1, height(selected));
        wbsOutputs = cell(1, height(selected));
        for seedIndex = 1:height(selected)
            [prrOutputs{seedIndex}, wbsOutputs{seedIndex}] = ...
                readCountOutputs( ...
                    selected.OutputDirectory(seedIndex));
        end
        metrics = ...
            v2xsimregression.paper.bazzi2020blindspots. ...
            reduceCountOutputs( ...
                prrOutputs, wbsOutputs, ...
                WirelessBlindSpotMaximumDelaySeconds= ...
                    definition. ...
                    WirelessBlindSpotMaximumDelaySeconds);
        configurationDirectory = fullfile( ...
            outputDirectory, "scenario-" + scenario, ...
            "scheme-" + scheme);
        rowCells{configurationIndex} = aggregateSummaryRow( ...
            selected, metrics, configurationDirectory);
    end
end
aggregateResults = vertcat(rowCells{:});
end

