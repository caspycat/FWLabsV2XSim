    metadata.RoadLengthMeters, metadata.VehicleCount, ...
    metadata.Scheme, metadata.KeepResourceProbability, ...
    metadata.MaximumConsecutiveReservationIntervals, ...
    height(selectedManifest), metadata.SimulationTimeSeconds, ...
    metadata.WirelessBlindSpotMaximumDelaySeconds, ...
    metrics.PrrAuc0To300, metrics.PrrRangeAt90Meters, ...
    metrics.PrrCorrectCount0To300, ...
    metrics.PrrErrorCount0To300, ...
    metrics.PrrBlockedCount0To300, ...
    metrics.PrrTotalCount0To300, ...
    metrics.WbsTailProbabilityAuc2To10Seconds, ...
    metrics.WbsProbabilityThreshold, ...
    metrics.WbsThresholdCrossingSeconds, ...
    metrics.WbsThresholdCrossingStatus, ...
    metrics.WbsAt10GreaterOrEqualCount, ...
    metrics.WbsAt10ShorterCount, ...
    metrics.WbsAt10Probability, outputDirectory, ...
    VariableNames=summaryVariableNames("aggregate"));
end

function variableNames = summaryVariableNames(kind)
metadataNames = [ ...
    "Profile", "Scenario", "DensityVehiclesPerKilometer", ...
    "SpeedKilometersPerHour", "RoadLengthMeters", "VehicleCount", ...
    "Scheme", "KeepResourceProbability", ...
    "MaximumConsecutiveReservationIntervals"];
if kind == "seed"
    runNames = [ ...
        "SimulationSeed", "ScenarioSeed", "AllocatorSeed", ...
        "SimulationTimeSeconds", ...
        "WirelessBlindSpotMaximumDelaySeconds"];
else
    runNames = [ ...
        "SeedCount", "SimulationTimeSeconds", ...
        "WirelessBlindSpotMaximumDelaySeconds"];
end
metricNames = [ ...
    "PrrAuc0To300", "PrrRangeAt90Meters", ...
    "PrrCorrectCount0To300", "PrrErrorCount0To300", ...
    "PrrBlockedCount0To300", "PrrTotalCount0To300", ...
    "WbsTailProbabilityAuc2To10Seconds", ...
    "WbsProbabilityThreshold", ...
    "WbsThresholdCrossingSeconds", ...
    "WbsThresholdCrossingStatus", ...
    "WbsAt10GreaterOrEqualCount", ...
    "WbsAt10ShorterCount", "WbsAt10Probability", ...
    "OutputDirectory"];
variableNames = [metadataNames, runNames, metricNames];
end

function [prrData, wbsData] = readCountOutputs(directory)
validateSeedOutputs(directory);
prrData = readmatrix( ...
    fullfile(directory, "packet_reception_ratio_LTE.csv"), ...
    FileType="text", Delimiter=",");
wbsData = readmatrix( ...
    fullfile(directory, "wireless_blind_spot_LTE.csv"), ...
    FileType="text", Delimiter=",");
end

function validateSeedOutputs(directory)
expectedFiles = [ ...
    "simulation_summary.json", ...
    "packet_reception_ratio_LTE.csv", ...
    "wireless_blind_spot_LTE.csv"];
for expectedFile = expectedFiles
    expectedPath = fullfile(directory, expectedFile);
    if ~isfile(expectedPath)
        error( ...
            "v2xsimregression:bazzi2020blindspots:MissingOutput", ...
            "The simulator did not create the expected file: %s", ...
            expectedPath);
    end
end
end

function validateSimulator( ...
        simulatorRoot, simulatorDirectory, configurationFile)
if ~isfolder(simulatorRoot)
    error( ...
        "v2xsimregression:bazzi2020blindspots:" + ...
        "MissingSimulatorRoot", ...
        "SimulatorRoot is not a directory: %s", simulatorRoot);
end
if ~isfile(fullfile( ...
        simulatorRoot, "src", "+v2xsim", "runSimulation.m"))
    error( ...
        "v2xsimregression:bazzi2020blindspots:MissingSimulator", ...
        "v2xsim.runSimulation was not found under: %s", ...
        simulatorRoot);
end
if ~isfolder(simulatorDirectory)
    error( ...
        "v2xsimregression:bazzi2020blindspots:" + ...
        "MissingSimulatorSupport", ...
        "The simulator support directory was not found: %s", ...
        simulatorDirectory);
end
if ~isfile(configurationFile)
    error( ...
        "v2xsimregression:bazzi2020blindspots:" + ...
        "MissingConfiguration", ...
        "The Bazzi 2020 configuration was not found: %s", ...
        configurationFile);
end
end

function prepareOutputDirectory(outputDirectory)
if isfolder(outputDirectory)
    directoryEntries = dir(outputDirectory);
    entryNames = string({directoryEntries.name});
    isContent = ~ismember(entryNames, [".", ".."]);
    if any(isContent)
        error( ...
            "v2xsimregression:bazzi2020blindspots:OutputNotEmpty", ...
            "Refusing to append results in nonempty folder: %s", ...
            outputDirectory);
    end
else
    [wasCreated, message] = mkdir(outputDirectory);
    if ~wasCreated
        error( ...
            "v2xsimregression:bazzi2020blindspots:" + ...
            "OutputCreationFailed", ...
            "Could not create output folder %s: %s", ...
            outputDirectory, message);
    end
end
end

function restoreEnvironment( ...
        originalPath, originalStream, originalStreamState, ...
        originalWarningState)
path(originalPath);
RandStream.setGlobalStream(originalStream);
originalStream.State = originalStreamState;
warning(originalWarningState);
end

function pathValue = absolutePath(pathValue, baseDirectory)
if ~isAbsolutePath(pathValue)
    pathValue = fullfile(baseDirectory, pathValue);
end
end

function result = isAbsolutePath(pathValue)
if ispc
    result = ~isempty(regexp( ...
        pathValue, "^[A-Za-z]:[\\/]|^\\\\", "once"));
else
    result = startsWith(pathValue, "/");
end
end
