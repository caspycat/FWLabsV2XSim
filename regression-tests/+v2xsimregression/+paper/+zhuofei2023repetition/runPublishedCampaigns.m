function results = runPublishedCampaigns( ...
        simulatorRoot, outputDirectory, options)
%RUNPUBLISHEDCAMPAIGNS Run the Zhuofei et al. repetition campaigns.
%   RESULTS contains one row per pooled configuration. The runner samples
%   the conclusions behind Figures 3-5 instead of reproducing every point
%   in the paper's full Monte Carlo sweep.

arguments (Input)
    simulatorRoot (1, 1) string {mustBeNonzeroLengthText}
    outputDirectory (1, 1) string {mustBeNonzeroLengthText}
    options.Figures (1, :) double ...
        {mustBeInteger, mustBeMember(options.Figures, [3, 4, 5])} = ...
        [3, 4, 5]
    options.RandomSeeds (1, :) double ...
        {mustBeInteger, mustBePositive} = 10:11
    options.SimulationTimeSeconds (1, 1) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = ...
        defaultSimulationTimeSeconds()
    options.Figure3PreambleSensitivitiesDbm (1, :) double ...
        {mustBeReal, mustBeFinite} = [-100, -103, -120]
    options.Figure3TransmissionCounts (1, :) double ...
        {mustBeInteger, ...
        mustBeMember(options.Figure3TransmissionCounts, 1:4)} = [1, 4]
    options.LoadDensitiesVehiclesPerKilometer (1, :) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = [5, 40, 80]
    options.StaticTransmissionCounts (1, :) double ...
        {mustBeInteger, ...
        mustBeMember(options.StaticTransmissionCounts, 1:4)} = 1:4
    options.AdaptiveStrategies (1, :) string = ...
        ["deterministic", "probabilistic"]
    options.IncludeEccPropagation (1, 1) logical = true
    options.EccDensitiesVehiclesPerKilometer (1, :) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = [5, 80]
    options.EccTransmissionCounts (1, :) double ...
        {mustBeInteger, ...
        mustBeMember(options.EccTransmissionCounts, 1:4)} = [1, 4]
end

arguments (Output)
    results table
end

validateCampaignOptions(options);
[simulatorDirectory, fixtureDirectory, packetErrorRateDirectory] = ...
    resolveSimulatorDirectories(simulatorRoot);
validateSimulatorRoot( ...
    simulatorRoot, simulatorDirectory, fixtureDirectory, ...
    packetErrorRateDirectory);
prepareOutputDirectory(outputDirectory);

originalPath = path;
randomStream = RandStream.getGlobalStream();
originalRandomState = randomStream.State;
environmentCleanup = onCleanup( ...
    @() restoreEnvironment( ...
        originalPath, randomStream, originalRandomState));

addpath(fullfile(simulatorRoot, "src"));
addpath(simulatorDirectory);

results = createEmptyResults(0);
if ismember(3, options.Figures)
    figure3Results = runFigure3( ...
        simulatorDirectory, fixtureDirectory, packetErrorRateDirectory, ...
        outputDirectory, options);
    results = [results; figure3Results];
end

if any(ismember(options.Figures, [4, 5]))
    loadResults = runFigures4And5( ...
        simulatorDirectory, fixtureDirectory, packetErrorRateDirectory, ...
        outputDirectory, options);
    results = [results; loadResults];
end

writetable(results, fullfile(outputDirectory, "campaign-summary.csv"));
end

function validateCampaignOptions(options)
if isempty(options.Figures) || isempty(options.RandomSeeds)
    error( ...
        "v2xsimregression:zhuofei2023repetition:EmptyCampaign", ...
        "Figures and RandomSeeds must both be nonempty.");
end

uniqueOptions = { ...
    options.Figures, ...
    options.RandomSeeds, ...
    options.Figure3PreambleSensitivitiesDbm, ...
    options.Figure3TransmissionCounts, ...
    options.LoadDensitiesVehiclesPerKilometer, ...
    options.StaticTransmissionCounts, ...
    options.AdaptiveStrategies, ...
    options.EccDensitiesVehiclesPerKilometer, ...
    options.EccTransmissionCounts};
optionNames = [ ...
    "Figures", ...
    "RandomSeeds", ...
    "Figure3PreambleSensitivitiesDbm", ...
    "Figure3TransmissionCounts", ...
    "LoadDensitiesVehiclesPerKilometer", ...
    "StaticTransmissionCounts", ...
    "AdaptiveStrategies", ...
    "EccDensitiesVehiclesPerKilometer", ...
    "EccTransmissionCounts"];
for optionIndex = 1:numel(uniqueOptions)
    values = uniqueOptions{optionIndex};
    if numel(unique(values)) ~= numel(values)
        error( ...
            "v2xsimregression:zhuofei2023repetition:DuplicateOption", ...
            "%s must not contain duplicates.", ...
            optionNames(optionIndex));
    end
end

if any(options.Figure3PreambleSensitivitiesDbm >= 0)
    error( ...
        "v2xsimregression:zhuofei2023repetition:InvalidSensitivity", ...
        "Preamble sensitivities must be negative values in dBm.");
end

supportedStrategies = ["deterministic", "probabilistic"];
if any(~ismember(options.AdaptiveStrategies, supportedStrategies))
    unsupportedStrategies = options.AdaptiveStrategies( ...
        ~ismember(options.AdaptiveStrategies, supportedStrategies));
    error( ...
        "v2xsimregression:zhuofei2023repetition:UnsupportedStrategy", ...
        "Unsupported repetition strategy or strategies: %s.", ...
        join(unsupportedStrategies, ", "));
end
if ismember(5, options.Figures) && isempty(options.AdaptiveStrategies)
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingStrategy", ...
        "Figure 5 requires at least one adaptive strategy.");
end
end

function results = runFigure3( ...
        simulatorDirectory, fixtureDirectory, packetErrorRateDirectory, ...
        outputDirectory, options)
results = createEmptyResults(0);
configurationFile = fullfile(fixtureDirectory, "figure3.cfg");
density = 5;
channelModel = "WINNER+ B1";

for sensitivityDbm = options.Figure3PreambleSensitivitiesDbm
    for transmissionCount = options.Figure3TransmissionCounts
        caseName = compose( ...
            "preamble-%d-static-transmissions-%d", ...
            abs(sensitivityDbm), transmissionCount);
        caseOutputDirectory = fullfile( ...
            outputDirectory, "figure-3", caseName);
        seedDirectories = runConfigurationSeeds( ...
            simulatorDirectory, configurationFile, ...
            packetErrorRateDirectory, caseOutputDirectory, ...
            density, channelModel, sensitivityDbm, "static", ...
            transmissionCount, options.RandomSeeds, ...
            options.SimulationTimeSeconds);
        summary = summarizeConfiguration( ...
            "3", caseName, density, channelModel, ...
            sensitivityDbm, "static", transmissionCount, ...
            options.RandomSeeds, options.SimulationTimeSeconds, ...
            caseOutputDirectory, seedDirectories);
        results = [results; summary]; %#ok<AGROW>
    end
end
end

function results = runFigures4And5( ...
        simulatorDirectory, fixtureDirectory, packetErrorRateDirectory, ...
        outputDirectory, options)
results = createEmptyResults(0);
configurationFile = fullfile(fixtureDirectory, "figures4and5.cfg");
hasFigure4 = ismember(4, options.Figures);
hasFigure5 = ismember(5, options.Figures);

if hasFigure4 && hasFigure5
    staticPaperFigures = "4,5";
elseif hasFigure4
    staticPaperFigures = "4";
else
    staticPaperFigures = "5";
end

for density = options.LoadDensitiesVehiclesPerKilometer
    for transmissionCount = options.StaticTransmissionCounts
        summary = runAndSummarizeLoadCase( ...
            simulatorDirectory, configurationFile, ...
            packetErrorRateDirectory, outputDirectory, ...
            staticPaperFigures, density, "WINNER+ B1", -100, ...
            "static", transmissionCount, options.RandomSeeds, ...
            options.SimulationTimeSeconds);
        results = [results; summary]; %#ok<AGROW>
    end
end

if hasFigure4 && options.IncludeEccPropagation
    for density = options.EccDensitiesVehiclesPerKilometer
        for transmissionCount = options.EccTransmissionCounts
            summary = runAndSummarizeLoadCase( ...
                simulatorDirectory, configurationFile, ...
                packetErrorRateDirectory, outputDirectory, ...
                "4", density, "ECC rural", -100, ...
                "static", transmissionCount, options.RandomSeeds, ...
                options.SimulationTimeSeconds);
            results = [results; summary]; %#ok<AGROW>
        end
    end
end

if hasFigure5
    for density = options.LoadDensitiesVehiclesPerKilometer
        for strategy = options.AdaptiveStrategies
            summary = runAndSummarizeLoadCase( ...
                simulatorDirectory, configurationFile, ...
                packetErrorRateDirectory, outputDirectory, ...
                "5", density, "WINNER+ B1", -100, ...
                strategy, 4, options.RandomSeeds, ...
                options.SimulationTimeSeconds);
            results = [results; summary]; %#ok<AGROW>
        end
    end
end
end

function summary = runAndSummarizeLoadCase( ...
        simulatorDirectory, configurationFile, ...
        packetErrorRateDirectory, outputDirectory, paperFigures, ...
        density, channelModel, sensitivityDbm, strategy, ...
        transmissionCount, randomSeeds, simulationTimeSeconds)
caseName = compose( ...
    "%s-density-%g-%s-transmissions-%d", ...
    channelSlug(channelModel), density, strategy, transmissionCount);
caseOutputDirectory = fullfile( ...
    outputDirectory, "figures-4-5", caseName);
seedDirectories = runConfigurationSeeds( ...
    simulatorDirectory, configurationFile, ...
    packetErrorRateDirectory, caseOutputDirectory, ...
    density, channelModel, sensitivityDbm, strategy, ...
    transmissionCount, randomSeeds, simulationTimeSeconds);
summary = summarizeConfiguration( ...
    paperFigures, caseName, density, channelModel, ...
    sensitivityDbm, strategy, transmissionCount, ...
    randomSeeds, simulationTimeSeconds, ...
    caseOutputDirectory, seedDirectories);
end

function seedDirectories = runConfigurationSeeds( ...
        simulatorDirectory, configurationFile, ...
        packetErrorRateDirectory, caseOutputDirectory, ...
        paperDensity, channelModel, sensitivityDbm, strategy, ...
        transmissionCount, randomSeeds, simulationTimeSeconds)
seedDirectories = strings(numel(randomSeeds), 1);
for seedIndex = 1:numel(randomSeeds)
    randomSeed = randomSeeds(seedIndex);
    seedDirectory = fullfile( ...
        caseOutputDirectory, compose("seed-%d", randomSeed));
    runSimulation( ...
        simulatorDirectory, configurationFile, ...
        packetErrorRateDirectory, seedDirectory, ...
        paperDensity, channelModel, sensitivityDbm, strategy, ...
        transmissionCount, randomSeed, simulationTimeSeconds);
    seedDirectories(seedIndex) = seedDirectory;
end
end

function runSimulation( ...
        simulatorDirectory, configurationFile, ...
        packetErrorRateDirectory, outputDirectory, ...
        paperDensity, channelModel, sensitivityDbm, strategy, ...
        transmissionCount, randomSeed, simulationTimeSeconds)
prepareOutputDirectory(outputDirectory);
[roadLengthMeters, simulatedDensity, pathLossModel] = ...
    channelDefinition(paperDensity, channelModel);
vehicleCount = round( ...
    simulatedDensity .* roadLengthMeters ./ 1000);

simulationArguments = { ...
    configurationFile, ...
    "simulation.RequiredVersion", "V7", ...
    "simulation.RandomSeed", randomSeed, ...
    "scenarioOptions.RandomSeed", randomSeed, ...
    "simulation.DurationSeconds", simulationTimeSeconds, ...
    "simulation.RadioAccessMode", "80211p", ...
    "scenario.Type", "BidirectionalHighwayScenario", ...
    "scenarioOptions.VehicleCount", vehicleCount, ...
    "scenarioOptions.NLanes", 3, ...
    "scenarioOptions.LaneWidth", 4, ...
    "scenarioOptions.RoadLength", roadLengthMeters, ...
    "scenarioOptions.CentralDividerWidth", 0, ...
    "scenarioOptions.MeanVehicleSpeed", 120 ./ 3.6, ...
    "scenarioOptions.VehicleSpeedStandardDeviation", 12 ./ 3.6, ...
    "scenarioOptions.RerollSpeedOnWrapAround", false, ...
    "application.PacketSizeBytes", 350, ...
    "application.ResourceReservationIntervalSeconds", 0.1, ...
    "application.PacketGeneration.IntervalSeconds", 0.1, ...
    "application.PacketGeneration.IntervalVariationSeconds", 0, ...
    "channelLoad.Enabled", true, ...
    "channelLoad.MeasurementWindowSeconds", 0.1, ...
    "channelLoad.UpdateStepsPerWindow", 100, ...
    "congestionControl.Enabled", false, ...
    "radio.ReceiverNoiseFigureDb", 6, ...
    "ieee80211p.PreambleSensitivityDbm", sensitivityDbm, ...
    "ieee80211p.RelativeInterferenceLevelModelEnabled", true, ...
    "ieee80211p.Mcs", 2, ...
    "channel.PacketErrorRateCurveDirectory", ...
        packetErrorRateDirectory, ...
    "channel.PathLoss.Model", pathLossModel, ...
    "itsG5.Repetition.Mode", strategyCode(strategy), ...
    "itsG5.Repetition.MaximumTransmissionCount", transmissionCount, ...
    "itsG5.Repetition.BackoffMicroseconds", 32, ...
    "itsG5.Repetition.LowCbrThreshold", 0.03, ...
    "itsG5.Repetition.MediumCbrThreshold", 0.05, ...
    "itsG5.Repetition.HighCbrThreshold", 0.09, ...
    "awareness.RangesMeters", 300, ...
    "output.PacketReceptionRatio.Enabled", true, ...
    "output.PacketReceptionRatio.DistanceBinWidthMeters", 10, ...
    "output.ChannelBusyRatio.Enabled", true, ...
    "output.AverageNeighborCount.Enabled", false, ...
    "output.UpdateDelay.Enabled", false, ...
    "output.PacketDelay.Enabled", false, ...
    "output.DataAge.Enabled", false, ...
    "simulation.RunLabel", compose( ...
        "Zhuofei2023 repetition: density=%g, channel=%s, " + ...
        "sensitivity=%g, strategy=%s, transmissions=%d, seed=%d", ...
        paperDensity, channelModel, sensitivityDbm, strategy, ...
        transmissionCount, randomSeed), ...
    "output.Directory", outputDirectory};

if channelModel == "ECC rural"
    eccArguments = { ...
        "channel.PathLoss.ReferenceLossAtOneMeterDb", 47.85, ...
        "channel.PathLoss.Exponent1", 2, ...
        "channel.PathLoss.BreakpointDistance1Meters", 128, ...
        "channel.PathLoss.Exponent2", 2.8, ...
        "channel.PathLoss.BreakpointDistance2Meters", 512, ...
        "channel.PathLoss.Exponent3", 3.3};
    simulationArguments = [simulationArguments, eccArguments]; %#ok<NASGU>
end

evalc("WiLabV2Xsim(simulationArguments{:});");
validateSimulationOutputs(outputDirectory);

if ~contains(which("WiLabV2Xsim"), simulatorDirectory)
    error( ...
        "v2xsimregression:zhuofei2023repetition:WrongSimulator", ...
        "WiLabV2Xsim resolved outside the requested simulator: %s", ...
        which("WiLabV2Xsim"));
end
end

function validateSimulationOutputs(outputDirectory)
expectedFiles = [ ...
    "MainOut.xls", ...
    "packet_reception_ratio_1_11p.csv", ...
    "CBRstatistic_1_11p.csv"];
for expectedFile = expectedFiles
    expectedPath = fullfile(outputDirectory, expectedFile);
    if ~isfile(expectedPath)
        error( ...
            "v2xsimregression:zhuofei2023repetition:MissingOutput", ...
            "The simulator did not create the expected file: %s", ...
            expectedPath);
    end
end
end

function summary = summarizeConfiguration( ...
        paperFigures, caseName, paperDensity, channelModel, ...
        sensitivityDbm, strategy, transmissionCount, ...
        randomSeeds, simulationTimeSeconds, ...
        caseOutputDirectory, seedDirectories)
[roadLengthMeters, simulatedDensity, ~, maximumScoreDistanceMeters] = ...
    channelDefinition(paperDensity, channelModel);
vehicleCount = round( ...
    simulatedDensity .* roadLengthMeters ./ 1000);
prrFiles = fullfile( ...
    seedDirectories, "packet_reception_ratio_1_11p.csv");
cbrFiles = fullfile(seedDirectories, "CBRstatistic_1_11p.csv");
[normalizedPrrScore, rangeAt90Meters] = summarizePrr( ...
    prrFiles, maximumScoreDistanceMeters);
meanNetCbr = summarizeCbr(cbrFiles);

if strategy == "static"
    repetitionCount = transmissionCount - 1;
else
    repetitionCount = NaN;
end

seedCount = numel(randomSeeds);
summary = table( ...
    paperFigures, caseName, channelModel, ...
    paperDensity, simulatedDensity, roadLengthMeters, vehicleCount, ...
    sensitivityDbm, strategy, transmissionCount, repetitionCount, ...
    seedCount, simulationTimeSeconds, maximumScoreDistanceMeters, ...
    normalizedPrrScore, rangeAt90Meters, meanNetCbr, ...
    caseOutputDirectory, ...
    VariableNames=[ ...
        "PaperFigures", "CaseName", "ChannelModel", ...
        "PaperDensityVehiclesPerKilometer", ...
        "SimulatedDensityVehiclesPerKilometer", ...
        "RoadLengthMeters", "VehicleCount", ...
        "PreambleSensitivityDbm", "Strategy", ...
        "MaximumTransmissionCount", "RepetitionCount", ...
        "SeedCount", "SimulationTimeSeconds", ...
        "MaximumScoreDistanceMeters", ...
        "NormalizedPrrScore", "RangeAt90Meters", "MeanNetCbr", ...
        "OutputDirectory"]);
end

function [normalizedPrrScore, rangeAt90Meters] = ...
        summarizePrr(prrFiles, maximumScoreDistanceMeters)
distanceBinWidthMeters = 50;
allDistancesMeters = zeros(0, 1);
fileData = cell(numel(prrFiles), 1);
for fileIndex = 1:numel(prrFiles)
    prrData = readmatrix( ...
        prrFiles(fileIndex), FileType="text", Delimiter=",");
    fileData{fileIndex} = prrData;
    allDistancesMeters = [ ...
        allDistancesMeters; prrData(:, 1)]; %#ok<AGROW>
end

allDistancesMeters = unique(allDistancesMeters);
correctPackets = zeros(size(allDistancesMeters));
totalPackets = zeros(size(allDistancesMeters));
for fileIndex = 1:numel(fileData)
    prrData = fileData{fileIndex};
    [hasDistance, pooledRow] = ismember( ...
        prrData(:, 1), allDistancesMeters);
    correctPackets(pooledRow(hasDistance)) = ...
        correctPackets(pooledRow(hasDistance)) + ...
        prrData(hasDistance, 2);
    totalPackets(pooledRow(hasDistance)) = ...
        totalPackets(pooledRow(hasDistance)) + ...
        prrData(hasDistance, 5);
end

isScoredDistance = ...
    allDistancesMeters > 0 & ...
    allDistancesMeters <= maximumScoreDistanceMeters;
scoredDistancesMeters = allDistancesMeters(isScoredDistance);
scoredCorrectPackets = correctPackets(isScoredDistance);
scoredTotalPackets = totalPackets(isScoredDistance);
distanceGroup = ceil( ...
    scoredDistancesMeters ./ distanceBinWidthMeters);
groupCount = floor( ...
    maximumScoreDistanceMeters ./ distanceBinWidthMeters);
groupCorrectPackets = accumarray( ...
    distanceGroup, scoredCorrectPackets, [groupCount, 1]);
groupTotalPackets = accumarray( ...
    distanceGroup, scoredTotalPackets, [groupCount, 1]);
groupDistancesMeters = ...
    (distanceBinWidthMeters: ...
    distanceBinWidthMeters:maximumScoreDistanceMeters).';
hasSamples = groupTotalPackets > 0;
groupDistancesMeters = groupDistancesMeters(hasSamples);
packetReceptionRatios = ...
    groupCorrectPackets(hasSamples) ./ groupTotalPackets(hasSamples);

if isempty(groupDistancesMeters)
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingPrrSamples", ...
        "No pooled PRR samples were available within the score range.");
end

normalizedPrrScore = trapz( ...
    [0; groupDistancesMeters], ...
    [1; packetReceptionRatios]) ./ maximumScoreDistanceMeters;
rangeAt90Meters = firstThresholdCrossing( ...
    groupDistancesMeters, packetReceptionRatios, 0.9);
end

function crossingDistance = firstThresholdCrossing( ...
        distances, values, threshold)
firstBelowThreshold = find(values < threshold, 1);
if isempty(firstBelowThreshold)
    crossingDistance = distances(end);
elseif firstBelowThreshold == 1
    crossingDistance = 0;
else
    leftIndex = firstBelowThreshold - 1;
    rightIndex = firstBelowThreshold;
    crossingDistance = interp1( ...
        values([leftIndex, rightIndex]), ...
        distances([leftIndex, rightIndex]), threshold);
end
end

function meanNetCbr = summarizeCbr(cbrFiles)
seedMeans = zeros(numel(cbrFiles), 1);
for fileIndex = 1:numel(cbrFiles)
    cbrData = readmatrix( ...
        cbrFiles(fileIndex), FileType="text", Delimiter=",");
    isFiniteRow = all(isfinite(cbrData(:, 1:2)), 2);
    cbrValues = cbrData(isFiniteRow, 1);
    empiricalCdf = cbrData(isFiniteRow, 2);
    if isempty(cbrValues) || empiricalCdf(end) < 0.999
        error( ...
            "v2xsimregression:zhuofei2023repetition:InvalidCbrOutput", ...
            "The CBR empirical distribution is empty or incomplete: %s", ...
            cbrFiles(fileIndex));
    end
    probabilityMass = diff([0; empiricalCdf]);
    seedMeans(fileIndex) = sum(cbrValues .* probabilityMass);
end
meanNetCbr = mean(seedMeans);
end

