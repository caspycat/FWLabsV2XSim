function results = runPublishedCampaigns( ...
        simulatorRoot, outputDirectory, options)
%RUNPUBLISHEDCAMPAIGNS Run the Zhuofei et al. repetition campaigns.
%   RESULTS contains one row per pooled configuration. The runner samples
%   the conclusions behind Figures 3-5 instead of reproducing every point
%   in the paper's full Monte Carlo sweep.

arguments (Input)
    simulatorRoot (1, 1) string {mustBeNonzeroLengthText}
    outputDirectory (1, 1) string {mustBeNonzeroLengthText}
    options.Figures (1, :) double ...
        {mustBeInteger, mustBeMember(options.Figures, [3, 4, 5])} = ...
        [3, 4, 5]
    options.RandomSeeds (1, :) double ...
        {mustBeInteger, mustBePositive} = 10:11
    options.SimulationTimeSeconds (1, 1) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = ...
        defaultSimulationTimeSeconds()
    options.Figure3PreambleSensitivitiesDbm (1, :) double ...
        {mustBeReal, mustBeFinite} = [-100, -103, -120]
    options.Figure3TransmissionCounts (1, :) double ...
        {mustBeInteger, ...
        mustBeMember(options.Figure3TransmissionCounts, 1:4)} = [1, 4]
    options.LoadDensitiesVehiclesPerKilometer (1, :) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = [5, 40, 80]
    options.StaticTransmissionCounts (1, :) double ...
        {mustBeInteger, ...
        mustBeMember(options.StaticTransmissionCounts, 1:4)} = 1:4
    options.AdaptiveStrategies (1, :) string = ...
        ["deterministic", "probabilistic"]
    options.IncludeEccPropagation (1, 1) logical = true
    options.EccDensitiesVehiclesPerKilometer (1, :) double ...
        {mustBeReal, mustBeFinite, mustBePositive} = [5, 80]
    options.EccTransmissionCounts (1, :) double ...
        {mustBeInteger, ...
        mustBeMember(options.EccTransmissionCounts, 1:4)} = [1, 4]
    options.ExecutionMode (1, 1) string {mustBeMember( ...
        options.ExecutionMode, ["auto", "serial", "parallel"])} = "auto"
    options.MaxWorkers (1, 1) double { ...
        v2xsimregression.execution.mustBeWorkerLimit} = Inf
end

arguments (Output)
    results table
end

validateCampaignOptions(options);
[sourceDirectory, fixtureDirectory, packetErrorRateDirectory, ...
    tomlDirectory] = ...
    resolveSimulatorDirectories(simulatorRoot);
validateSimulatorRoot( ...
    simulatorRoot, fixtureDirectory, ...
    packetErrorRateDirectory);
prepareOutputDirectory(outputDirectory);

originalPath = path;
randomStream = RandStream.getGlobalStream();
originalRandomState = randomStream.State;
environmentCleanup = onCleanup( ...
    @() restoreEnvironment( ...
        originalPath, randomStream, originalRandomState));

addpath(sourceDirectory);
addpath(tomlDirectory);

configurations = createConfigurations( ...
    fixtureDirectory, outputDirectory, options);
assertUniqueConfigurationDirectories(configurations);
workItems = cell(1, 0);
workLabels = strings(1, 0);
for configurationIndex = 1:numel(configurations)
    configuration = configurations{configurationIndex};
    for randomSeed = options.RandomSeeds
        seedDirectory = fullfile( ...
            configuration.OutputDirectory, ...
            compose("seed-%d", randomSeed));
        workItem = struct( ...
            SourceDirectory=sourceDirectory, ...
            PacketErrorRateDirectory=packetErrorRateDirectory, ...
            Configuration=configuration, ...
            OutputDirectory=seedDirectory, ...
            RandomSeed=randomSeed, ...
            SimulationTimeSeconds=options.SimulationTimeSeconds);
        workItems{end + 1} = workItem; %#ok<AGROW>
        workLabels(end + 1) = compose( ...
            "case=%s,seed=%d", configuration.CaseName, ...
            randomSeed); %#ok<AGROW>
    end
end

additionalPaths = [ ...
    fullfile(simulatorRoot, "regression-tests"), ...
    sourceDirectory, ...
    tomlDirectory];
seedDirectoryOutputs = ...
    v2xsimregression.execution.runWorkItems( ...
        workItems, @runSeedWorkItem, ...
        Labels=workLabels, ...
        ExecutionMode=options.ExecutionMode, ...
        MaxWorkers=options.MaxWorkers, ...
        AdditionalPaths=additionalPaths);

results = createEmptyResults(0);
workIndex = 0;
for configurationIndex = 1:numel(configurations)
    configuration = configurations{configurationIndex};
    seedRange = workIndex + (1:numel(options.RandomSeeds));
    seedDirectories = string(seedDirectoryOutputs(seedRange)).';
    workIndex = workIndex + numel(options.RandomSeeds);
    summary = summarizeConfiguration( ...
        configuration.PaperFigures, configuration.CaseName, ...
        configuration.Density, configuration.ChannelModel, ...
        configuration.SensitivityDbm, configuration.Strategy, ...
        configuration.TransmissionCount, options.RandomSeeds, ...
        options.SimulationTimeSeconds, ...
        configuration.OutputDirectory, seedDirectories);
    results = [results; summary]; %#ok<AGROW>
end

writetable(results, fullfile(outputDirectory, "campaign-summary.csv"));
end

function validateCampaignOptions(options)
if isempty(options.Figures) || isempty(options.RandomSeeds)
    error( ...
        "v2xsimregression:zhuofei2023repetition:EmptyCampaign", ...
        "Figures and RandomSeeds must both be nonempty.");
end

uniqueOptions = { ...
    options.Figures, ...
    options.RandomSeeds, ...
    options.Figure3PreambleSensitivitiesDbm, ...
    options.Figure3TransmissionCounts, ...
    options.LoadDensitiesVehiclesPerKilometer, ...
    options.StaticTransmissionCounts, ...
    options.AdaptiveStrategies, ...
    options.EccDensitiesVehiclesPerKilometer, ...
    options.EccTransmissionCounts};
optionNames = [ ...
    "Figures", ...
    "RandomSeeds", ...
    "Figure3PreambleSensitivitiesDbm", ...
    "Figure3TransmissionCounts", ...
    "LoadDensitiesVehiclesPerKilometer", ...
    "StaticTransmissionCounts", ...
    "AdaptiveStrategies", ...
    "EccDensitiesVehiclesPerKilometer", ...
    "EccTransmissionCounts"];
for optionIndex = 1:numel(uniqueOptions)
    values = uniqueOptions{optionIndex};
    if numel(unique(values)) ~= numel(values)
        error( ...
            "v2xsimregression:zhuofei2023repetition:DuplicateOption", ...
            "%s must not contain duplicates.", ...
            optionNames(optionIndex));
    end
end

if any(options.Figure3PreambleSensitivitiesDbm >= 0)
    error( ...
        "v2xsimregression:zhuofei2023repetition:InvalidSensitivity", ...
        "Preamble sensitivities must be negative values in dBm.");
end

supportedStrategies = ["deterministic", "probabilistic"];
if any(~ismember(options.AdaptiveStrategies, supportedStrategies))
    unsupportedStrategies = options.AdaptiveStrategies( ...
        ~ismember(options.AdaptiveStrategies, supportedStrategies));
    error( ...
        "v2xsimregression:zhuofei2023repetition:UnsupportedStrategy", ...
        "Unsupported repetition strategy or strategies: %s.", ...
        join(unsupportedStrategies, ", "));
end
if ismember(5, options.Figures) && isempty(options.AdaptiveStrategies)
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingStrategy", ...
        "Figure 5 requires at least one adaptive strategy.");
end
end

function configurations = createConfigurations( ...
        fixtureDirectory, outputDirectory, options)
configurations = cell(1, 0);
configurationFile = fullfile(fixtureDirectory, "figure3.toml");

if ismember(3, options.Figures)
    for sensitivityDbm = options.Figure3PreambleSensitivitiesDbm
        for transmissionCount = options.Figure3TransmissionCounts
            caseName = compose( ...
                "preamble-%d-static-transmissions-%d", ...
                abs(sensitivityDbm), transmissionCount);
            caseOutputDirectory = fullfile( ...
                outputDirectory, "figure-3", caseName);
            configuration = createConfiguration( ...
                "3", caseName, 5, "WINNER+ B1", sensitivityDbm, ...
                "static", transmissionCount, configurationFile, ...
                caseOutputDirectory);
            configurations{end + 1} = configuration; %#ok<AGROW>
        end
    end
end

if ~any(ismember(options.Figures, [4, 5]))
    return
end

configurationFile = fullfile(fixtureDirectory, "figures4and5.toml");
hasFigure4 = ismember(4, options.Figures);
hasFigure5 = ismember(5, options.Figures);

if hasFigure4 && hasFigure5
    staticPaperFigures = "4,5";
elseif hasFigure4
    staticPaperFigures = "4";
else
    staticPaperFigures = "5";
end

for density = options.LoadDensitiesVehiclesPerKilometer
    for transmissionCount = options.StaticTransmissionCounts
        configuration = createLoadConfiguration( ...
            configurationFile, outputDirectory, ...
            staticPaperFigures, density, "WINNER+ B1", -100, ...
            "static", transmissionCount);
        configurations{end + 1} = configuration; %#ok<AGROW>
    end
end

if hasFigure4 && options.IncludeEccPropagation
    for density = options.EccDensitiesVehiclesPerKilometer
        for transmissionCount = options.EccTransmissionCounts
            configuration = createLoadConfiguration( ...
                configurationFile, outputDirectory, ...
                "4", density, "ECC rural", -100, ...
                "static", transmissionCount);
            configurations{end + 1} = configuration; %#ok<AGROW>
        end
    end
end

if hasFigure5
    for density = options.LoadDensitiesVehiclesPerKilometer
        for strategy = options.AdaptiveStrategies
            configuration = createLoadConfiguration( ...
                configurationFile, outputDirectory, ...
                "5", density, "WINNER+ B1", -100, ...
                strategy, 4);
            configurations{end + 1} = configuration; %#ok<AGROW>
        end
    end
end
end

function configuration = createLoadConfiguration( ...
        configurationFile, outputDirectory, paperFigures, ...
        density, channelModel, sensitivityDbm, strategy, ...
        transmissionCount)
caseName = compose( ...
    "%s-density-%s-%s-transmissions-%d", ...
    channelSlug(channelModel), numericPathToken(density), ...
    strategy, transmissionCount);
caseOutputDirectory = fullfile( ...
    outputDirectory, "figures-4-5", caseName);
configuration = createConfiguration( ...
    paperFigures, caseName, density, channelModel, ...
    sensitivityDbm, strategy, transmissionCount, configurationFile, ...
    caseOutputDirectory);
end

function configuration = createConfiguration( ...
        paperFigures, caseName, density, channelModel, ...
        sensitivityDbm, strategy, transmissionCount, ...
        configurationFile, outputDirectory)
configuration = struct( ...
    PaperFigures=paperFigures, ...
    CaseName=caseName, ...
    Density=density, ...
    ChannelModel=channelModel, ...
    SensitivityDbm=sensitivityDbm, ...
    Strategy=strategy, ...
    TransmissionCount=transmissionCount, ...
    ConfigurationFile=configurationFile, ...
    OutputDirectory=outputDirectory);
end

function token = numericPathToken(value)
token = compose("%.17g",value);
token = replace(token,["-", "+", "."],["m", "p", "d"]);
end

function assertUniqueConfigurationDirectories(configurations)
outputDirectories = strings(1, numel(configurations));
for configurationIndex = 1:numel(configurations)
    outputDirectories(configurationIndex) = ...
        string(configurations{configurationIndex}.OutputDirectory);
end
if numel(unique(outputDirectories)) ~= numel(outputDirectories)
    error( ...
        "v2xsimregression:zhuofei2023repetition:" + ...
        "OutputDirectoryCollision", ...
        "Campaign options generated duplicate run output directories.");
end
end

function seedDirectory = runSeedWorkItem(workItem)
configuration = workItem.Configuration;
seedDirectory = workItem.OutputDirectory;
    runSimulation( ...
        workItem.SourceDirectory, ...
        configuration.ConfigurationFile, ...
        workItem.PacketErrorRateDirectory, seedDirectory, ...
        configuration.Density, configuration.ChannelModel, ...
        configuration.SensitivityDbm, configuration.Strategy, ...
        configuration.TransmissionCount, workItem.RandomSeed, ...
        workItem.SimulationTimeSeconds);
end

function runSimulation( ...
        sourceDirectory, configurationFile, ...
        packetErrorRateDirectory, outputDirectory, ...
        paperDensity, channelModel, sensitivityDbm, strategy, ...
        transmissionCount, randomSeed, simulationTimeSeconds)
[roadLengthMeters, simulatedDensity, pathLossModel] = ...
    channelDefinition(paperDensity, channelModel);
vehicleCount = round( ...
    simulatedDensity .* roadLengthMeters ./ 1000);

pathLoss = struct(Model=pathLossModel);
if channelModel == "ECC rural"
    pathLoss.ReferenceLossAtOneMeterDb = 47.85;
    pathLoss.Exponent1 = 2;
    pathLoss.BreakpointDistance1Meters = 128;
    pathLoss.Exponent2 = 2.8;
    pathLoss.BreakpointDistance2Meters = 512;
    pathLoss.Exponent3 = 3.3;
end

patchData = struct( ...
    Simulation=struct( ...
        RandomSeed=randomSeed, ...
        DurationSeconds=simulationTimeSeconds), ...
    Scenario=struct( ...
        Type="BidirectionalHighway", ...
        BidirectionalHighway=struct( ...
            RandomSeed=randomSeed, ...
            VehicleCount=vehicleCount, ...
            NLanes=3, ...
            LaneWidth=4, ...
            RoadLength=roadLengthMeters, ...
            CentralDividerWidth=0, ...
            MeanVehicleSpeed=120 ./ 3.6, ...
            VehicleSpeedStandardDeviation=12 ./ 3.6, ...
            RerollSpeedOnWrapAround=false)), ...
    Application=struct( ...
        PacketSizeBytes=350, ...
        ResourceReservationIntervalSeconds=0.1, ...
        PacketGeneration=struct( ...
            IntervalSeconds=0.1, ...
            IntervalVariationSeconds=0), ...
        ChannelLoad=struct( ...
            Enabled=true, ...
            MeasurementWindowSeconds=0.1, ...
            UpdateStepsPerWindow=100), ...
        CongestionControl=struct(Enabled=false)), ...
    Radio=struct( ...
        Type="Ieee80211p", ...
        ReceiverNoiseFigureDb=6, ...
        Ieee80211p=struct( ...
            PreambleSensitivityDbm=sensitivityDbm, ...
            RelativeInterferenceLevelModelEnabled=true, ...
            Mcs=2, ...
            Repetition=struct( ...
                Mode=strategyType(strategy), ...
                MaximumTransmissionCount=transmissionCount, ...
                BackoffMicroseconds=32, ...
                CbrThresholds=[0.03, 0.05, 0.09]))), ...
    Channel=struct( ...
        PacketError=struct( ...
            Model="Curves", ...
            CurveDirectory=packetErrorRateDirectory), ...
        PathLoss=pathLoss), ...
    Awareness=struct(RangesMeters=300), ...
    Outputs=struct( ...
        PacketReceptionRatio=struct( ...
            Enabled=true, ...
            DistanceBinWidthMeters=10), ...
        ChannelBusyRatio=struct(Enabled=true), ...
        AverageNeighborCount=struct(Enabled=false), ...
        UpdateDelay=struct(Enabled=false), ...
        PacketDelay=struct(Enabled=false), ...
        DataAge=struct(Enabled=false)));
template = v2xsim.config.load(configurationFile);
configuration = template.resolve( ...
    Patch=v2xsim.config.patch(patchData)); %#ok<NASGU>
runLabel = compose( ...
    "Zhuofei2023 repetition: density=%g, channel=%s, " + ...
    "sensitivity=%g, strategy=%s, transmissions=%d, seed=%d", ...
    paperDensity, channelModel, sensitivityDbm, strategy, ...
    transmissionCount, randomSeed); %#ok<NASGU>
evalc("v2xsim.runSimulation(configuration," + ...
    "OutputDirectory=outputDirectory,RunLabel=runLabel);");
validateSimulationOutputs(outputDirectory);

resolvedEntrypoint = string(which("v2xsim.runSimulation"));
if ~startsWith(resolvedEntrypoint, sourceDirectory)
    error( ...
        "v2xsimregression:zhuofei2023repetition:WrongSimulator", ...
        "v2xsim.runSimulation resolved outside the requested simulator: %s", ...
        resolvedEntrypoint);
end
end

