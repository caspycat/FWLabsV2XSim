    end
end
end

function summary = summarizeConfiguration( ...
        paperFigures, caseName, paperDensity, channelModel, ...
        sensitivityDbm, strategy, transmissionCount, ...
        randomSeeds, simulationTimeSeconds, ...
        caseOutputDirectory, seedDirectories)
[roadLengthMeters, simulatedDensity, ~, maximumScoreDistanceMeters] = ...
    channelDefinition(paperDensity, channelModel);
vehicleCount = round( ...
    simulatedDensity .* roadLengthMeters ./ 1000);
prrFiles = fullfile( ...
    seedDirectories, "packet_reception_ratio_11p.csv");
cbrFiles = fullfile(seedDirectories, "CBRstatistic_11p.csv");
[normalizedPrrScore, rangeAt90Meters] = summarizePrr( ...
    prrFiles, maximumScoreDistanceMeters);
meanNetCbr = summarizeCbr(cbrFiles);

if strategy == "static"
    repetitionCount = transmissionCount - 1;
else
    repetitionCount = NaN;
end

seedCount = numel(randomSeeds);
summary = table( ...
    paperFigures, caseName, channelModel, ...
    paperDensity, simulatedDensity, roadLengthMeters, vehicleCount, ...
    sensitivityDbm, strategy, transmissionCount, repetitionCount, ...
    seedCount, simulationTimeSeconds, maximumScoreDistanceMeters, ...
    normalizedPrrScore, rangeAt90Meters, meanNetCbr, ...
    caseOutputDirectory, ...
    VariableNames=[ ...
        "PaperFigures", "CaseName", "ChannelModel", ...
        "PaperDensityVehiclesPerKilometer", ...
        "SimulatedDensityVehiclesPerKilometer", ...
        "RoadLengthMeters", "VehicleCount", ...
        "PreambleSensitivityDbm", "Strategy", ...
        "MaximumTransmissionCount", "RepetitionCount", ...
        "SeedCount", "SimulationTimeSeconds", ...
        "MaximumScoreDistanceMeters", ...
        "NormalizedPrrScore", "RangeAt90Meters", "MeanNetCbr", ...
        "OutputDirectory"]);
end

function [normalizedPrrScore, rangeAt90Meters] = ...
        summarizePrr(prrFiles, maximumScoreDistanceMeters)
distanceBinWidthMeters = 50;
allDistancesMeters = zeros(0, 1);
fileData = cell(numel(prrFiles), 1);
for fileIndex = 1:numel(prrFiles)
    prrData = readmatrix( ...
        prrFiles(fileIndex), FileType="text", Delimiter=",");
    fileData{fileIndex} = prrData;
    allDistancesMeters = [ ...
        allDistancesMeters; prrData(:, 1)]; %#ok<AGROW>
end

allDistancesMeters = unique(allDistancesMeters);
correctPackets = zeros(size(allDistancesMeters));
totalPackets = zeros(size(allDistancesMeters));
for fileIndex = 1:numel(fileData)
    prrData = fileData{fileIndex};
    [hasDistance, pooledRow] = ismember( ...
        prrData(:, 1), allDistancesMeters);
    correctPackets(pooledRow(hasDistance)) = ...
        correctPackets(pooledRow(hasDistance)) + ...
        prrData(hasDistance, 2);
    totalPackets(pooledRow(hasDistance)) = ...
        totalPackets(pooledRow(hasDistance)) + ...
        prrData(hasDistance, 5);
end

isScoredDistance = ...
    allDistancesMeters > 0 & ...
    allDistancesMeters <= maximumScoreDistanceMeters;
scoredDistancesMeters = allDistancesMeters(isScoredDistance);
scoredCorrectPackets = correctPackets(isScoredDistance);
scoredTotalPackets = totalPackets(isScoredDistance);
distanceGroup = ceil( ...
    scoredDistancesMeters ./ distanceBinWidthMeters);
groupCount = floor( ...
    maximumScoreDistanceMeters ./ distanceBinWidthMeters);
groupCorrectPackets = accumarray( ...
    distanceGroup, scoredCorrectPackets, [groupCount, 1]);
groupTotalPackets = accumarray( ...
    distanceGroup, scoredTotalPackets, [groupCount, 1]);
groupDistancesMeters = ...
    (distanceBinWidthMeters: ...
    distanceBinWidthMeters:maximumScoreDistanceMeters).';
hasSamples = groupTotalPackets > 0;
groupDistancesMeters = groupDistancesMeters(hasSamples);
packetReceptionRatios = ...
    groupCorrectPackets(hasSamples) ./ groupTotalPackets(hasSamples);

if isempty(groupDistancesMeters)
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingPrrSamples", ...
        "No pooled PRR samples were available within the score range.");
end

normalizedPrrScore = trapz( ...
    [0; groupDistancesMeters], ...
    [1; packetReceptionRatios]) ./ maximumScoreDistanceMeters;
rangeAt90Meters = firstThresholdCrossing( ...
    groupDistancesMeters, packetReceptionRatios, 0.9);
end

function crossingDistance = firstThresholdCrossing( ...
        distances, values, threshold)
firstBelowThreshold = find(values < threshold, 1);
if isempty(firstBelowThreshold)
    crossingDistance = distances(end);
elseif firstBelowThreshold == 1
    crossingDistance = 0;
else
    leftIndex = firstBelowThreshold - 1;
    rightIndex = firstBelowThreshold;
    crossingDistance = interp1( ...
        values([leftIndex, rightIndex]), ...
        distances([leftIndex, rightIndex]), threshold);
end
end

function meanNetCbr = summarizeCbr(cbrFiles)
seedMeans = zeros(numel(cbrFiles), 1);
for fileIndex = 1:numel(cbrFiles)
    cbrData = readmatrix( ...
        cbrFiles(fileIndex), FileType="text", Delimiter=",");
    isFiniteRow = all(isfinite(cbrData(:, 1:2)), 2);
    cbrValues = cbrData(isFiniteRow, 1);
    empiricalCdf = cbrData(isFiniteRow, 2);
    if isempty(cbrValues) || empiricalCdf(end) < 0.999
        error( ...
            "v2xsimregression:zhuofei2023repetition:InvalidCbrOutput", ...
            "The CBR empirical distribution is empty or incomplete: %s", ...
            cbrFiles(fileIndex));
    end
    probabilityMass = diff([0; empiricalCdf]);
    seedMeans(fileIndex) = sum(cbrValues .* probabilityMass);
end
meanNetCbr = mean(seedMeans);
end

