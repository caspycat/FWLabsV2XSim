function code = strategyCode(strategy)
if strategy == "static"
    code = 0;
elseif strategy == "deterministic"
    code = 1;
elseif strategy == "probabilistic"
    code = 2;
else
    error( ...
        "v2xsimregression:zhuofei2023repetition:UnsupportedStrategy", ...
        "Unsupported repetition strategy: %s.", strategy);
end
end

function slug = channelSlug(channelModel)
if channelModel == "WINNER+ B1"
    slug = "winner-b1";
elseif channelModel == "ECC rural"
    slug = "ecc-rural";
else
    error( ...
        "v2xsimregression:zhuofei2023repetition:UnsupportedChannel", ...
        "Unsupported channel model: %s.", channelModel);
end
end

function [roadLengthMeters, simulatedDensity, pathLossModel, ...
        maximumScoreDistanceMeters] = ...
        channelDefinition(paperDensity, channelModel)
if channelModel == "WINNER+ B1"
    roadLengthMeters = 2000;
    simulatedDensity = paperDensity;
    pathLossModel = 0;
    maximumScoreDistanceMeters = 650;
elseif channelModel == "ECC rural"
    roadLengthMeters = 8000;
    simulatedDensity = paperDensity ./ 4;
    pathLossModel = 3;
    maximumScoreDistanceMeters = 2000;
else
    error( ...
        "v2xsimregression:zhuofei2023repetition:UnsupportedChannel", ...
        "Unsupported channel model: %s.", channelModel);
end
end

function [simulatorDirectory, fixtureDirectory, ...
        packetErrorRateDirectory] = ...
        resolveSimulatorDirectories(simulatorRoot)
simulatorDirectory = fullfile(simulatorRoot, "old_src");
fixtureDirectory = fullfile(fileparts(mfilename("fullpath")), "config");
packetErrorRateDirectory = fullfile( ...
    simulatorDirectory, "PERcurves", "G5-HighwayLOS");
end

function validateSimulatorRoot( ...
        simulatorRoot, simulatorDirectory, fixtureDirectory, ...
        packetErrorRateDirectory)
if ~isfolder(simulatorRoot)
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingSimulatorRoot", ...
        "SimulatorRoot is not a directory: %s", simulatorRoot);
end
if ~isfile(fullfile(simulatorDirectory, "WiLabV2Xsim.m"))
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingSimulator", ...
        "WiLabV2Xsim.m was not found under: %s", ...
        simulatorDirectory);
end
requiredConfigurations = [ ...
    fullfile(fixtureDirectory, "figure3.cfg"), ...
    fullfile(fixtureDirectory, "figures4and5.cfg")];
for requiredConfiguration = requiredConfigurations
    if ~isfile(requiredConfiguration)
        error( ...
            "v2xsimregression:zhuofei2023repetition:MissingConfiguration", ...
            "A regression configuration was not found: %s", ...
            requiredConfiguration);
    end
end
if ~isfolder(packetErrorRateDirectory)
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingPerCurves", ...
        "The paper's PER curves were not found under: %s", ...
        packetErrorRateDirectory);
end
if ~isfolder(fullfile(simulatorRoot, "src", "+v2xsim"))
    error( ...
        "v2xsimregression:zhuofei2023repetition:MissingRefactoredSource", ...
        "The simulator root requires src/+v2xsim under: %s", ...
        simulatorRoot);
end
end

function prepareOutputDirectory(outputDirectory)
if isfolder(outputDirectory)
    directoryEntries = dir(outputDirectory);
    isContent = ~ismember({directoryEntries.name}, {".", ".."});
    if any(isContent)
        error( ...
            "v2xsimregression:zhuofei2023repetition:OutputNotEmpty", ...
            "Refusing to append results in nonempty folder: %s", ...
            outputDirectory);
    end
else
    [wasCreated, message] = mkdir(outputDirectory);
    if ~wasCreated
        error( ...
            "v2xsimregression:zhuofei2023repetition:" + ...
            "OutputCreationFailed", ...
            "Could not create output folder %s: %s", ...
            outputDirectory, message);
    end
end
end

function simulationTimeSeconds = defaultSimulationTimeSeconds()
configuredValue = string(getenv( ...
    "V2XSIM_PAPER_SIMULATION_TIME_SECONDS"));
if configuredValue == ""
    simulationTimeSeconds = 5;
    return
end

simulationTimeSeconds = str2double(configuredValue);
if ~isscalar(simulationTimeSeconds) || ...
        ~isfinite(simulationTimeSeconds) || simulationTimeSeconds <= 0
    error( ...
        "v2xsimregression:zhuofei2023repetition:InvalidDuration", ...
        ["V2XSIM_PAPER_SIMULATION_TIME_SECONDS must contain a ", ...
        "positive finite number."]);
end
end

function restoreEnvironment( ...
        originalPath, randomStream, originalRandomState)
path(originalPath);
randomStream.State = originalRandomState;
end
