classdef Zhuofei2023CoChannelTest < matlab.unittest.TestCase
    %ZHUOFEI2023COCHANNELTEST Conclusion-level paper regressions.
    %   Reasserts the conclusions behind Figures 10-12 and 15 from
    %   Wu et al. (2023), rather than matching individual plot samples.

    properties (Constant, Access = private)
        MinimumAucImprovement = 0.005
        PrrPreservationTolerance = 0.01
        RangeBinWidthMeters = 50
        MinimumDelayIncreaseSeconds = 0.002
        ComparableDelayToleranceSeconds = 0.002
        NrDelayToleranceSeconds = 0.010
        NrDataAgeToleranceSeconds = 0.010
    end

    properties (SetAccess = private)
        SimulatorRoot (1, 1) string
        OutputDirectory (1, 1) string
    end

    methods (TestClassSetup)
        function configureCampaign(testCase)
            testCase.SimulatorRoot = getSimulatorRoot();
            temporaryFolder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            testCase.OutputDirectory = string(temporaryFolder.Folder);
        end
    end

    methods (Test, TestTags = {'ShortCampaign'})
        function testFigures10To12SupportMitigationTradeoffs(testCase)
            methods = [ ...
                "no_method", "enhanced_A", "method_B", ...
                "dynamic_C", "dynamic_C_preamble", "method_F"];
            results = ...
                v2xsimregression.paper.zhuofei2023cochannel. ...
                runPublishedCampaigns( ...
                    testCase.SimulatorRoot, ...
                    fullfile( ...
                        testCase.OutputDirectory, "figures-10-to-12"), ...
                    Methods=methods, ...
                    PacketIntervalVariationsSeconds=0, ...
                    RandomSeeds=10:15, ...
                    SimulationTimeSeconds=10);

            noMethod11p = selectRow( ...
                results, "no_method", "IEEE 802.11p", 0);
            noMethodNr = selectRow( ...
                results, "no_method", "NR-V2X", 0);
            enhancedA11p = selectRow( ...
                results, "enhanced_A", "IEEE 802.11p", 0);
            methodB11p = selectRow( ...
                results, "method_B", "IEEE 802.11p", 0);
            dynamicC11p = selectRow( ...
                results, "dynamic_C", "IEEE 802.11p", 0);
            preambleOnlyC11p = selectRow( ...
                results, "dynamic_C_preamble", "IEEE 802.11p", 0);
            methodF11p = selectRow( ...
                results, "method_F", "IEEE 802.11p", 0);

            testCase.verifyGreaterThan( ...
                enhancedA11p.NormalizedPrrScore - ...
                    noMethod11p.NormalizedPrrScore, ...
                testCase.MinimumAucImprovement, ...
                "Enhanced Method A must improve IEEE 802.11p PRR.");
            testCase.verifyGreaterThanOrEqual( ...
                dynamicC11p.NormalizedPrrScore - ...
                    noMethod11p.NormalizedPrrScore, ...
                testCase.MinimumAucImprovement, ...
                "Dynamic Method C must improve IEEE 802.11p PRR.");
            testCase.verifyGreaterThan( ...
                preambleOnlyC11p.NormalizedPrrScore - ...
                    noMethod11p.NormalizedPrrScore, ...
                testCase.MinimumAucImprovement, ...
                "Preamble-only Method C must improve IEEE 802.11p PRR.");

            positiveMethods = [ ...
                "enhanced_A", "dynamic_C", "dynamic_C_preamble"];
            for method = positiveMethods
                methodNr = selectRow(results, method, "NR-V2X", 0);
                testCase.verifyGreaterThanOrEqual( ...
                    methodNr.NormalizedPrrScore - ...
                        noMethodNr.NormalizedPrrScore, ...
                    -testCase.PrrPreservationTolerance, ...
                    compose( ...
                        "%s must not materially reduce NR-V2X PRR.", ...
                        method));
            end

            testCase.verifyGreaterThan( ...
                enhancedA11p.RangeAt90Meters, ...
                noMethod11p.RangeAt90Meters, ...
                "Enhanced Method A must extend reliable 802.11p range.");
            for method = ["dynamic_C", "dynamic_C_preamble"]
                method11p = selectRow( ...
                    results, method, "IEEE 802.11p", 0);
                testCase.verifyGreaterThanOrEqual( ...
                    method11p.RangeAt90Meters - ...
                        noMethod11p.RangeAt90Meters, ...
                    -testCase.RangeBinWidthMeters, ...
                    compose( ...
                        "%s must preserve reliable IEEE 802.11p range " + ...
                        "within one distance bin.", ...
                        method));
            end

            testCase.verifyLessThan( ...
                methodB11p.RangeAt90Meters, ...
                noMethod11p.RangeAt90Meters, ...
                "Method B must retain its IEEE 802.11p range tradeoff.");

            testCase.verifyGreaterThan( ...
                enhancedA11p.MeanEndToEndDelaySeconds - ...
                    noMethod11p.MeanEndToEndDelaySeconds, ...
                0.005, ...
                "Method A must expose its IEEE 802.11p delay cost.");
            testCase.verifyGreaterThan( ...
                methodB11p.MeanEndToEndDelaySeconds - ...
                    noMethod11p.MeanEndToEndDelaySeconds, ...
                testCase.MinimumDelayIncreaseSeconds, ...
                "Method B must expose its IEEE 802.11p delay cost.");
            testCase.verifyGreaterThan( ...
                methodF11p.MeanEndToEndDelaySeconds - ...
                    noMethod11p.MeanEndToEndDelaySeconds, ...
                testCase.MinimumDelayIncreaseSeconds, ...
                "Method F must expose its IEEE 802.11p delay cost.");
            testCase.verifyLessThanOrEqual( ...
                abs(dynamicC11p.MeanEndToEndDelaySeconds - ...
                    noMethod11p.MeanEndToEndDelaySeconds), ...
                testCase.ComparableDelayToleranceSeconds, ...
                "Dynamic Method C must preserve IEEE 802.11p delay.");
            testCase.verifyLessThanOrEqual( ...
                abs(preambleOnlyC11p.MeanEndToEndDelaySeconds - ...
                    noMethod11p.MeanEndToEndDelaySeconds), ...
                testCase.ComparableDelayToleranceSeconds, ...
                "Preamble-only Method C must preserve 802.11p delay.");

            for method = methods(methods ~= "no_method")
                methodNr = selectRow(results, method, "NR-V2X", 0);
                testCase.verifyLessThanOrEqual( ...
                    abs(methodNr.MeanEndToEndDelaySeconds - ...
                        noMethodNr.MeanEndToEndDelaySeconds), ...
                    testCase.NrDelayToleranceSeconds, ...
                    compose( ...
                        "%s must preserve average NR-V2X delay.", ...
                        method));
            end

            for method = ["dynamic_C", "dynamic_C_preamble"]
                method11p = selectRow( ...
                    results, method, "IEEE 802.11p", 0);
                methodNr = selectRow(results, method, "NR-V2X", 0);
                testCase.verifyLessThanOrEqual( ...
                    method11p.MeanDataAgeSeconds - ...
                        noMethod11p.MeanDataAgeSeconds, ...
                    testCase.ComparableDelayToleranceSeconds, ...
                    compose( ...
                        "%s must not materially increase IEEE 802.11p " + ...
                        "data age.", ...
                        method));
                testCase.verifyLessThanOrEqual( ...
                    methodNr.MeanDataAgeSeconds - ...
                        noMethodNr.MeanDataAgeSeconds, ...
                    testCase.NrDataAgeToleranceSeconds, ...
                    compose( ...
                        "%s must not materially increase NR-V2X " + ...
                        "data age.", ...
                        method));
            end
        end

        function testShortCamCampaignPreservesIeee80211pConclusions( ...
                testCase)
            methods = [ ...
                "no_method", "enhanced_A", ...
                "dynamic_C", "dynamic_C_preamble"];
            results = ...
                v2xsimregression.paper.zhuofei2023cochannel. ...
                runPublishedCampaigns( ...
                    testCase.SimulatorRoot, ...
                    fullfile(testCase.OutputDirectory, "figure-15"), ...
                    Methods=methods, ...
                    PacketIntervalVariationsSeconds=[0, -1], ...
                    RandomSeeds=10:15, ...
                    SimulationTimeSeconds=5);

            for intervalVariation = [0, -1]
                noMethod11p = selectRow( ...
                    results, "no_method", ...
                    "IEEE 802.11p", intervalVariation);
                enhancedA11p = selectRow( ...
                    results, "enhanced_A", ...
                    "IEEE 802.11p", intervalVariation);
                testCase.verifyGreaterThan( ...
                    enhancedA11p.NormalizedPrrScore, ...
                    noMethod11p.NormalizedPrrScore, ...
                    "Method A must improve both traffic patterns.");
                for method = ["dynamic_C", "dynamic_C_preamble"]
                    method11p = selectRow( ...
                        results, method, ...
                        "IEEE 802.11p", intervalVariation);
                    testCase.verifyGreaterThanOrEqual( ...
                        method11p.NormalizedPrrScore - ...
                            noMethod11p.NormalizedPrrScore, ...
                        -testCase.PrrPreservationTolerance, ...
                        compose( ...
                            "%s must preserve IEEE 802.11p PRR for " + ...
                            "both traffic patterns.", ...
                            method));
                end
            end
        end
    end

    methods (Test, TestTags = {'HighDensity'})
        function testHighDensityMethodFReducesIeee80211pRange(testCase)
            results = ...
                v2xsimregression.paper.zhuofei2023cochannel. ...
                runPublishedCampaigns( ...
                    testCase.SimulatorRoot, ...
                    fullfile( ...
                        testCase.OutputDirectory, ...
                        "high-density-method-f"), ...
                    Methods=["no_method", "method_F"], ...
                    DensitiesVehiclesPerKilometer=36, ...
                    PacketIntervalVariationsSeconds=0, ...
                    RandomSeeds=10:12, ...
                    SimulationTimeSeconds=5);

            noMethod11p = selectRow( ...
                results, "no_method", "IEEE 802.11p", 0);
            methodF11p = selectRow( ...
                results, "method_F", "IEEE 802.11p", 0);
            testCase.verifyLessThan( ...
                methodF11p.RangeAt90Meters, ...
                noMethod11p.RangeAt90Meters, ...
                "At high density, Method F must reduce reliable " + ...
                "IEEE 802.11p range.");
        end
    end
end

function simulatorRoot = getSimulatorRoot()
simulatorRoot = string(getenv("V2XSIM_PAPER_SIMULATOR_ROOT"));
if simulatorRoot == ""
    simulatorRoot = string(fileparts(fileparts(fileparts(fileparts( ...
        fileparts(mfilename("fullpath")))))));
end
end

function selectedRow = selectRow( ...
        results, method, technology, intervalVariation)
isSelected = ...
    results.Method == method & ...
    results.Technology == technology & ...
    results.PacketIntervalVariationSeconds == intervalVariation;
selectedRow = results(isSelected, :);
if height(selectedRow) ~= 1
    error( ...
        "v2xsimregression:zhuofei2023cochannel:NonuniqueSelection", ...
        "Expected one campaign row but selected %d.", ...
        height(selectedRow));
end
end
