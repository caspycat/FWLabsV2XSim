        function deepPatchReplacesArraysAndArraysOfTablesAtomically(testCase)
            originalError = {struct( ...
                Type="Gaussian", StandardDeviationMeters=3), ...
                struct(Type="Delay", DelaySeconds=0.1)};
            template = v2xsim.config.ConfigurationTemplate(struct( ...
                SchemaVersion=1, ...
                Awareness=struct(RangesMeters=[100, 200]), ...
                Positioning=struct(Errors={originalError})));
            replacementError = {struct(Type="Delay", DelaySeconds=0.25)};
            overlay = v2xsim.config.patch(struct( ...
                Awareness=struct(RangesMeters=300), ...
                Positioning=struct(Errors={replacementError})));

            merged = template.withPatch(overlay);

            testCase.verifyEqual(merged.Data.Awareness.RangesMeters, 300);
            testCase.verifyNumElements(merged.Data.Positioning.Errors, 1);
            testCase.verifyEqual( ...
                merged.Data.Positioning.Errors{1}.DelaySeconds, 0.25);
        end

