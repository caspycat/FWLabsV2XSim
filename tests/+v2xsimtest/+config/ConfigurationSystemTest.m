        function preservesSharedSidelinkAndRemovesInactiveCoexistence(testCase)
            inactiveCoexistence = ...
                v2xsim.config.ConfigurationTemplate(struct( ...
                    SchemaVersion=1, ...
                    Coexistence=struct(Method="MethodA")));
            testCase.verifyError( ...
                @() inactiveCoexistence.resolve(), ...
                "v2xsim:config:InactiveKey");

            template = v2xsim.config.ConfigurationTemplate(struct( ...
                SchemaVersion=1, ...
                Radio=struct( ...
                    Type="Coexistence", ...
                    Sidelink=struct(ResourcePool=struct( ...
                        SubchannelSizeResourceBlocks=20))), ...
                Coexistence=struct(Method="MethodA")));
            overlay = v2xsim.config.patch(struct( ...
                Radio=struct(Type="NrV2X")));

            merged = template.withPatch(overlay);
            configuration = merged.resolve();

            testCase.verifyFalse(isfield(merged.Data, "Coexistence"));
            testCase.verifyEqual( ...
                configuration.Data.Radio.Sidelink.ResourcePool. ...
                    SubchannelSizeResourceBlocks, ...
                20);
            testCase.verifyEqual( ...
                configuration.sourceFor( ...
                    "Radio.Sidelink.ResourcePool." + ...
                    "SubchannelSizeResourceBlocks"), ...
                "Template");

            cochannel = v2xsim.config.ConfigurationTemplate(struct( ...
                SchemaVersion=1, ...
                Radio=struct( ...
                    Type="Coexistence", ...
                    Coexistence=struct( ...
                        InterferenceModel="Cochannel")), ...
                Coexistence=struct( ...
                    Method="MethodA", ...
                    VehiclePattern=struct(SidelinkVehicleCount=3), ...
                    MethodA=struct(EnhancementVariant=1))));
            independentPatch = v2xsim.config.patch(struct( ...
                Radio=struct(Coexistence=struct( ...
                    InterferenceModel="Independent"))));

            independent = cochannel.withPatch(independentPatch);
            independentConfiguration = independent.resolve();

            testCase.verifyEqual( ...
                string(fieldnames(independent.Data.Coexistence)), ...
                "VehiclePattern");
            testCase.verifyEqual( ...
                independentConfiguration.Data.Coexistence. ...
                    VehiclePattern.SidelinkVehicleCount, ...
                3);
        end
