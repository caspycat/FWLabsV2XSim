        function loadsAndResolvesAllMigratedFixtures(testCase)
            repositoryRoot = testCase.repositoryRoot();
            searchRoots = [ ...
                fullfile(repositoryRoot, "examples"), ...
                fullfile(repositoryRoot, "regression-tests"), ...
                fullfile(repositoryRoot, "tests", ...
                    "+v2xsimtest", "+fixtures")];
            entriesByRoot = cell(size(searchRoots));
            fileCount = 0;
            for rootIndex = 1:numel(searchRoots)
                entriesByRoot{rootIndex} = dir(fullfile( ...
                    searchRoots(rootIndex), "**", "*.toml"));
                fileCount = fileCount + numel(entriesByRoot{rootIndex});
            end
            files = strings(fileCount, 1);
            fileIndex = 0;
            for rootIndex = 1:numel(searchRoots)
                entries = entriesByRoot{rootIndex};
                for index = 1:numel(entries)
                    fileIndex = fileIndex + 1;
                    files(fileIndex) = string(fullfile( ...
                        entries(index).folder, entries(index).name));
                end
            end

            % Lesson 17 owns a copy of the output-artifact input so every
            % tutorial directory remains self-contained.
            testCase.verifyNumElements(files, 28);
            for file = reshape(files, 1, [])
                configuration = v2xsim.config.load(file).resolve();
                testCase.verifyEqual(configuration.Data.SchemaVersion, 1);
                testCase.verifyGreaterThan( ...
                    configuration.Data.Simulation.RandomSeed, 0);
                scenarioType = configuration.Data.Scenario.Type;
                testCase.verifyGreaterThan( ...
                    configuration.Data.Scenario.(scenarioType).RandomSeed, 0);
                testCase.verifyGreaterThan( ...
                    configuration.Data.ResourceAllocation.RandomSeed, 0);
            end
        end

