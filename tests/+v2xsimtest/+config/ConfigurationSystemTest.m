    methods (Static, Access = private)
        function writeUtf8(file, text)
            fileIdentifier = fopen(file, "wt", "n", "UTF-8");
            if fileIdentifier < 0
                error( ...
                    "v2xsimtest:config:FixtureWriteFailed", ...
                    "Could not create TOML fixture ""%s"".", file);
            end
            cleanup = onCleanup(@() fclose(fileIdentifier));
            fwrite(fileIdentifier, char(text), "char");
        end

