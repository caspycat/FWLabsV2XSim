        function resolvesTomlResourcePathsAtTheFileBoundary(testCase)
            folder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture).Folder;
            configurationFolder = fullfile(folder, "configuration");
            curveFolder = fullfile(configurationFolder, "curves");
            workerFolder = fullfile(folder, "worker");
            mkdir(configurationFolder);
            mkdir(curveFolder);
            mkdir(workerFolder);
            file = fullfile(configurationFolder, "resource-paths.toml");
            testCase.writeUtf8(file, ...
                "SchemaVersion = 1" + newline + ...
                "[Channel.PacketError]" + newline + ...
                "Model = ""Curves""" + newline + ...
                "CurveDirectory = ""curves""");

            originalFolder = string(pwd);
            folderCleanup = onCleanup(@() cd(originalFolder));
            cd(workerFolder);
            configuration = v2xsim.config.load(file).resolve();

            testCase.verifyEqual( ...
                configuration.Data.Channel.PacketError.CurveDirectory, ...
                string(curveFolder));
            testCase.verifyEqual( ...
                configuration.sourceFor( ...
                    "Channel.PacketError.CurveDirectory"), ...
                "File:" + string(file));
            folderCleanup; %#ok<VUNUS>

            relativePath = v2xsim.config.ConfigurationTemplate(struct( ...
                SchemaVersion=1, ...
                Channel=struct(PacketError=struct( ...
                    Model="Curves", CurveDirectory="curves"))));
            testCase.verifyError( ...
                @() relativePath.resolve(), ...
                "v2xsim:config:RelativeResourcePath");
        end

