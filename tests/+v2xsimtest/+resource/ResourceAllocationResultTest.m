classdef ResourceAllocationResultTest < matlab.unittest.TestCase
    %RESOURCEALLOCATIONRESULTTEST Tests allocator-output invariants.

    methods (Test)
        function testAcceptsAssignmentsOutcomesAndReservations(testCase)
            sliceId = testCase.createSliceId();
            assignments = testCase.createAssignments([1; NaN]);
            reservations = table( ...
                "ue-1", 2, VariableNames=["UeId", "ResourceId"]);

            result = v2xsim.resource.ResourceAllocationResult( ...
                sliceId, assignments, ["ue-1"; "ue-2"], ...
                "ue-1", "ue-2", reservations);

            testCase.verifyEqual(result.Assignments, assignments);
            testCase.verifyEqual(result.Reservations, reservations);
        end

        function testEmptyFactoriesHaveStableSchemas(testCase)
            assignments = ...
                v2xsim.resource.ResourceAllocationResult ...
                .emptyAssignments(2);
            reservations = ...
                v2xsim.resource.ResourceAllocationResult ...
                .emptyReservations();

            testCase.verifyEqual( ...
                string(assignments.Properties.VariableNames), ...
                ["UeId", "ResourceIds"]);
            testCase.verifySize(assignments.ResourceIds, [0, 2]);
            testCase.verifyEqual( ...
                string(reservations.Properties.VariableNames), ...
                ["UeId", "ResourceId"]);
        end

        function testRejectsInvalidAssignedResourceIds(testCase)
            sliceId = testCase.createSliceId();
            invalidValues = {0, -1, 1.5, Inf};

            for index = 1:numel(invalidValues)
                assignments = testCase.createAssignments( ...
                    [invalidValues{index}; NaN]);
                testCase.verifyError( ...
                    @() v2xsim.resource.ResourceAllocationResult( ...
                        sliceId, assignments, strings(0, 1), ...
                        strings(0, 1), strings(0, 1), ...
                        v2xsim.resource.ResourceAllocationResult ...
                        .emptyReservations()), ...
                    "v2xsim:resource:InvalidResourceId");
            end
        end

        function testRejectsSecondaryWithoutPrimary(testCase)
            assignments = table( ...
                "ue-1",[NaN 2], ...
                VariableNames=["UeId","ResourceIds"]);

            testCase.verifyError( ...
                @() v2xsim.resource.ResourceAllocationResult( ...
                    testCase.createSliceId(),assignments, ...
                    strings(0,1),strings(0,1),strings(0,1), ...
                    v2xsim.resource.ResourceAllocationResult ...
                    .emptyReservations()), ...
                "v2xsim:resource:" + ...
                "NoncontiguousTransmissionAssignments");
        end

        function testRejectsInconsistentOutcomeIdentities(testCase)
            sliceId = testCase.createSliceId();
            assignments = testCase.createAssignments([1; 2]);

            testCase.verifyError( ...
                @() v2xsim.resource.ResourceAllocationResult( ...
                    sliceId, assignments, "ue-1", "ue-2", ...
                    strings(0, 1), ...
                    v2xsim.resource.ResourceAllocationResult ...
                    .emptyReservations()), ...
                "v2xsim:resource:InvalidAllocationResultIdentity");
        end

        function testRejectsDuplicateReservationPairs(testCase)
            sliceId = testCase.createSliceId();
            assignments = testCase.createAssignments([1; 2]);
            reservations = table( ...
                ["ue-1"; "ue-1"], [2; 2], ...
                VariableNames=["UeId", "ResourceId"]);

            testCase.verifyError( ...
                @() v2xsim.resource.ResourceAllocationResult( ...
                    sliceId, assignments, strings(0, 1), ...
                    strings(0, 1), strings(0, 1), reservations), ...
                "v2xsim:resource:DuplicateUeId");
        end
    end

    methods (Access = private)
        function sliceId = createSliceId(~)
            sliceId = v2xsim.network.NetworkSliceId("global");
        end

        function assignments = createAssignments(~, resourceIds)
            assignments = table( ...
                ["ue-1"; "ue-2"], resourceIds, ...
                VariableNames=["UeId", "ResourceIds"]);
        end
    end
end
