        function testMaximumReuseUsesEstimateAndShadowDoesNotMutate( ...
                testCase)
            grid = v2xsim.resource.BRResourceGrid( ...
                v2xsim.network.NetworkSliceId("global"),2,1,0.001);
            ueIds = ["a";"b";"c"];
            apparent = [0 1 2;1 0 3;2 3 0];
            truth = [0 3 2;3 0 1;2 1 0];
            liveAllocator = ...
                v2xsim.resource.MaximumReuseDistanceAllocator( ...
                    grid,5,1,DiagnosticsEnabled=true). ...
                    synchronizeUes(ueIds);
            estimateControl = ...
                v2xsim.resource.MaximumReuseDistanceAllocator( ...
                    grid,5,1,DiagnosticsEnabled=true). ...
                    synchronizeUes(ueIds);
            initialLive = testCase.createThreeUeCentralizedContext( ...
                grid,ueIds,0,apparent,truth);
            initialControl = testCase.createThreeUeCentralizedContext( ...
                grid,ueIds,0,apparent,apparent);
            [liveAllocator,~] = liveAllocator.initialize(initialLive);
            [estimateControl,~] = ...
                estimateControl.initialize(initialControl);

            liveContext = testCase.createThreeUeCentralizedContext( ...
                grid,ueIds,1,apparent,truth);
            controlContext = testCase.createThreeUeCentralizedContext( ...
                grid,ueIds,1,apparent,apparent);
            [liveAllocator,liveResult] = ...
                liveAllocator.step(liveContext);
            [estimateControl,controlResult] = ...
                estimateControl.step(controlContext);

            testCase.verifyEqual( ...
                liveResult.Assignments,controlResult.Assignments);
            testCase.verifyNotEqual( ...
                liveResult.Assignments.ResourceIds, ...
                liveResult.Diagnostics. ...
                    OracleAssignments.ResourceIds);

            nextLive = testCase.createThreeUeCentralizedContext( ...
                grid,ueIds,3,apparent,truth);
            nextControl = testCase.createThreeUeCentralizedContext( ...
                grid,ueIds,3,apparent,apparent);
            [liveAllocator,nextLiveResult] = ...
                liveAllocator.step(nextLive);
            [estimateControl,nextControlResult] = ...
                estimateControl.step(nextControl);
            testCase.verifyEqual( ...
                nextLiveResult.Assignments, ...
                nextControlResult.Assignments);
            testCase.verifyEqual( ...
                liveAllocator.Assignments, ...
                estimateControl.Assignments);
        end

        function testRandomBenchmarkAllocatesOnlyForNewPackets(testCase)
            grid = testCase.createGrid();
            allocator = v2xsim.resource.RandomBenchmarkAllocator(grid,9,2);
            allocator = allocator.synchronizeUes(["ue-1";"ue-2"]);
            noPacketContext = v2xsim.resource.ResourceAllocationContext( ...
                grid.NetworkSliceId,["ue-1";"ue-2"],0, ...
                false(2,1),true(2,grid.ResourceCount));
            [allocator,~] = allocator.initialize(noPacketContext);
            eligibility = logical([0 1 0 0;1 1 1 1]);
            packetContext = v2xsim.resource.ResourceAllocationContext( ...
                grid.NetworkSliceId,["ue-1";"ue-2"],1, ...
                [true;false],eligibility);

            [allocator,result] = allocator.step(packetContext);

            testCase.verifyEqual( ...
                allocator.Assignments.ResourceIds(1,1),2);
            testCase.verifyTrue( ...
                isnan(allocator.Assignments.ResourceIds(1,2)));
            testCase.verifyTrue(all(isnan( ...
                allocator.Assignments.ResourceIds(2,:))));
            testCase.verifyEqual(result.DecisionUeIds,"ue-1");
        end

