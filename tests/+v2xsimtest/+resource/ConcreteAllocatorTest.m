        function testRandomBenchmarkHarqOccurrencesStrictlyIncrease( ...
                testCase)
            grid = testCase.createGrid();
            allocator = ...
                v2xsim.resource.RandomBenchmarkAllocator(grid,17,2);
            allocator = allocator.synchronizeUes("ue-1");
            initialContext = v2xsim.resource.ResourceAllocationContext( ...
                grid.NetworkSliceId,"ue-1",0,false, ...
                true(1,grid.ResourceCount),0);
            [allocator,~] = allocator.initialize(initialContext);
            packetContext = v2xsim.resource.ResourceAllocationContext( ...
                grid.NetworkSliceId,"ue-1",0,true, ...
                true(1,grid.ResourceCount),0);

            [allocator,~] = allocator.step(packetContext);

            resources = allocator.Assignments.ResourceIds;
            resourceSlots = ceil( ...
                resources / grid.NumberFrequencyResources);
            futureSlots = resourceSlots;
            futureSlots(resourceSlots <= grid.periodicSlot(0)) = ...
                futureSlots(resourceSlots <= grid.periodicSlot(0)) + ...
                grid.NumberTimeSlots;
            testCase.verifyGreaterThan(diff(futureSlots),0);
        end

