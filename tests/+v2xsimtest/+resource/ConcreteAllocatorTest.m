    methods (Static, Access = private)
        function grid = createGrid()
            grid = v2xsim.resource.BRResourceGrid( ...
                v2xsim.network.NetworkSliceId("global"),2,2,0.001);
        end

        function context = createCentralizedContext(grid,currentSlot,x)
            ueIds = ["ue-1";"ue-2"];
            distance = [0 10;10 0];
            power = [0 1;1 0];
            context = v2xsim.resource.CentralizedAllocationContext( ...
                grid.NetworkSliceId,ueIds,currentSlot,false(2,1), ...
                true(2,grid.ResourceCount),x,distance,distance, ...
                power,zeros(2));
        end

        function context = createThreeUeCentralizedContext( ...
                grid,ueIds,currentSlot,estimatedDistance,trueDistance)
            power = ones(3);
            power(1:4:end) = 0;
            context = v2xsim.resource.CentralizedAllocationContext( ...
                grid.NetworkSliceId,ueIds,currentSlot,false(3,1), ...
                true(3,grid.ResourceCount),(1:3).', ...
                estimatedDistance,trueDistance,power,zeros(3));
        end

        function allocator = createThreeGppAllocator( ...
                grid,maximumTransmissionCount)
            arguments (Input)
                grid (1,1) v2xsim.resource.BRResourceGrid
