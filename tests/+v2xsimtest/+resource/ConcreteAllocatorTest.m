classdef ConcreteAllocatorTest < matlab.unittest.TestCase
    %CONCRETEALLOCATORTEST Tests concrete allocator lifecycle behavior.

    methods (Test)
        function testScheduledCentralizedAllocatorsWaitForBoundary(testCase)
            allocators = { ...
                v2xsim.resource.ReuseDistanceAllocator( ...
                    testCase.createGrid(),1,1,5), ...
                v2xsim.resource.MaximumReuseDistanceAllocator( ...
                    testCase.createGrid(),2,1), ...
                v2xsim.resource.MinimumReusePowerAllocator( ...
                    testCase.createGrid(),3,1,false)};

            for index = 1:numel(allocators)
                allocator = allocators{index}.synchronizeUes( ...
                    ["ue-1";"ue-2"]);
                context = testCase.createCentralizedContext( ...
                    allocator.Grid,0,[10;20]);
                [allocator,~] = allocator.initialize(context);
                [allocator,result] = allocator.step(context);
                testCase.verifyEmpty(result.DecisionUeIds);
                testCase.verifyTrue( ...
                    all(isnan(allocator.Assignments.ResourceIds),"all"));

                boundaryContext = testCase.createCentralizedContext( ...
                    allocator.Grid,1,[10;20]);
                [allocator,result] = allocator.step(boundaryContext);
                testCase.verifyEqual( ...
                    sort(result.DecisionUeIds),["ue-1";"ue-2"]);
                testCase.verifyTrue(all(isfinite( ...
                    allocator.Assignments.ResourceIds),"all"));
            end
        end

