        function testPositionErrorsProduceOrderedTrace(testCase)
            [results,outputDirectory] = testCase.executeExample( ...
                fullfile("04_apply_position_errors","apply_position_errors.m"));

            testCase.verifyEqual(results.Modules.ModuleIndex,[1;2;3;4;5]);
            testCase.verifyGreaterThan( ...
                results.Modules.ActiveRowCount(1),0);
            testCase.verifyGreaterThan( ...
                results.Modules.ActiveRowCount(2),0);
            testCase.verifyTrue(any( ...
                endsWith(results.Modules.StatusEffectType, ...
                    "FalseMergePositionErrorStatusEffect")));
            packetLossRow = results.Modules.ModuleType == ...
                "v2xsim.positioning.PositionPacketLossError";
            testCase.verifyEqual(sum(packetLossRow),1);
            testCase.verifyGreaterThan( ...
                results.Modules.NetworkUpdateRowCount(packetLossRow),0);
            testCase.verifyGreaterThan( ...
                results.Modules.DroppedUpdateRowCount(packetLossRow),0);
            testCase.verifyNotEmpty(results.RouteActivity);
            testCase.verifyNotEmpty(results.Trajectory);
            testCase.verifyNotEmpty(dir(fullfile( ...
                outputDirectory,"position_error_trace_*.csv")));
        end

