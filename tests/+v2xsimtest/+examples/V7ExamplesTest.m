    methods (Access = private)
        function [results,outputDirectory] = executeExample( ...
                testCase,scriptName)
            scriptFile = fullfile( ...
                testCase.ExampleDirectory,scriptName);
            run(scriptFile);
            results = exampleResults;
            outputDirectory = string(exampleOutputDirectory);
            testCase.addTeardown(@() removeOutput(outputDirectory));
        end
