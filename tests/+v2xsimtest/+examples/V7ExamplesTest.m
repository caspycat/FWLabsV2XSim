end

function restoreProcessState( ...
        originalPath,originalDirectory, ...
        originalStream,originalStreamState, ...
        originalWarningState,originalFigureVisibility)
close all force
path(originalPath);
cd(originalDirectory);
RandStream.setGlobalStream(originalStream);
originalStream.State = originalStreamState;
warning(originalWarningState);
set(groot,"DefaultFigureVisible",originalFigureVisibility);
end

function removeOutput(outputDirectory)
if isfolder(outputDirectory)
    rmdir(outputDirectory,"s");
end
end
