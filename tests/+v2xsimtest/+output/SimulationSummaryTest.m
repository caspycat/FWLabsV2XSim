        function testBuildsSemanticCoexistenceSummary(testCase)
            [station, sim, app, phy, sinr, out, values] = ...
                testCase.makeInputs();

            summary = v2xsim.output.buildSimulationSummary( ...
                station, sim, app, phy, sinr, out, values);

            testCase.verifyEqual(summary.SchemaVersion, 2);
            testCase.verifyFalse(isfield(summary.Run, "Identifier"));
            testCase.verifyEqual(summary.Run.SimulatorVersion, "V7");
            testCase.verifyEqual( ...
                summary.Configuration.Infrastructure. ...
                RoadSideUnitCount, 2);
            testCase.verifyEqual( ...
                summary.Configuration.ResourceAllocation. ...
                Metadata.Type, "ThreeGppAutonomous");
            testCase.verifyEqual( ...
