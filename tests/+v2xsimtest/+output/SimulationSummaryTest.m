        function testNeverOverwritesExistingSummary(testCase)
            outputDirectory = testCase.makeTemporaryDirectory();
            outputFile = fullfile( ...
                outputDirectory, "simulation_summary.json");
            testCase.writeText(outputFile, "existing result");

            testCase.verifyError( ...
                @() v2xsim.output.writeSimulationSummary( ...
                    outputDirectory, struct("SchemaVersion", 2)), ...
                "v2xsim:output:SummaryAlreadyExists");
            testCase.verifyEqual( ...
                string(fileread(outputFile)), "existing result");
        end

        function testRemovesTemporaryFileWhenSerializationFails(testCase)
            outputDirectory = testCase.makeTemporaryDirectory();
            invalidSummary = struct("Unsupported", @sin);

            testCase.verifyError( ...
                @() v2xsim.output.writeSimulationSummary( ...
                    outputDirectory, invalidSummary), ...
                "MATLAB:io:xml:writestruct:UnsupportedDatatypeInStruct");
            testCase.verifyFalse(isfile(fullfile( ...
                outputDirectory, "simulation_summary.json")));
            testCase.verifyEmpty(dir(fullfile(outputDirectory, "*.json")));
        end
