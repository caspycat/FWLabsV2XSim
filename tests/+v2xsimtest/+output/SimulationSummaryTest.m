            testCase.verifyEqual( ...
                cellular.ResidualSelfInterferenceDb, -110);
            testCase.verifyEqual( ...
                cellular.ResidualSelfInterferenceMode, "Finite");
            testCase.verifyEqual( ...
                cellular.SelfInterferenceThresholdMultiplierMode, ...
