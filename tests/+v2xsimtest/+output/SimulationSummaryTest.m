        function testWritesStrictJsonAndRoundTripsNestedArrays(testCase)
            [station, sim, app, phy, sinr, out, values] = ...
                testCase.makeInputs();
            summary = v2xsim.output.buildSimulationSummary( ...
                station, sim, app, phy, sinr, out, values);
            outputDirectory = testCase.makeTemporaryDirectory();

            outputFile = v2xsim.output.writeSimulationSummary( ...
                outputDirectory, summary);

            testCase.verifyEqual( ...
                outputFile, fullfile( ...
                    outputDirectory, "simulation_summary.json"));
            jsonText = string(fileread(outputFile));
            testCase.verifyNotEmpty(regexp( ...
                jsonText, ...
                """AwarenessRangeMetrics""\s*:\s*\[", "once"));
            testCase.verifyNotEmpty(regexp( ...
                jsonText, """Channels""\s*:\s*\[", "once"));
            testCase.verifyNotEmpty(regexp( ...
                jsonText, """RangesMeters""\s*:\s*\[", "once"));
            testCase.verifyTrue(contains(jsonText, "null"));
            testCase.verifyFalse(contains(jsonText, "NaN"));
            testCase.verifyFalse(contains(jsonText, "Infinity"));

            decoded = jsondecode(jsonText);
            testCase.verifyEqual(decoded.SchemaVersion, 2);
            testCase.verifyEqual( ...
                decoded.Configuration.Infrastructure. ...
                RoadSideUnitCount, 2);
            testCase.verifyEqual( ...
                string(decoded.Configuration.ResourceAllocation. ...
                Metadata.Type), "ThreeGppAutonomous");
            testCase.verifyNumElements( ...
                decoded.Results.CellularSidelink. ...
                AwarenessRangeMetrics, 2);

            jsonFiles = dir(fullfile(outputDirectory, "*.json"));
            testCase.verifyEqual( ...
                string({jsonFiles.name}), "simulation_summary.json");
        end

