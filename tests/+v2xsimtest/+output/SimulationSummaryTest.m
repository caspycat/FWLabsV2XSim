                testCase.makeInputs();
            phy.duplexCV2X = "FD";
            phy.Ksi_dB = -110;
            phy.PDelta = Inf;

            summary = v2xsim.output.buildSimulationSummary( ...
                station, sim, app, phy, sinr, out, values);
