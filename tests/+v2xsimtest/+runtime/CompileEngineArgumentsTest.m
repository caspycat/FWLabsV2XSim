classdef CompileEngineArgumentsTest < matlab.unittest.TestCase
    %COMPILEENGINEARGUMENTSTEST Tests the declarative-to-engine compiler.
    %   These tests deliberately stop at the one-way compiler boundary. The
    %   numerical engine must never participate in configuration mapping.

    methods (Test)
        function mapsEveryScenarioType(testCase)
            cases = { ...
                struct( ...
                    Type="BrownianMotion", ...
                    EngineType="BrownianMotionScenario", ...
                    BranchArgument="scenarioOptions.VehicleCount"), ...
                struct( ...
                    Type="BidirectionalHighway", ...
                    EngineType="BidirectionalHighwayScenario", ...
                    BranchArgument="scenarioOptions.NLanes"), ...
                struct( ...
                    Type="EtsiHighway", ...
                    EngineType="EtsiHighwayScenario", ...
                    BranchArgument="scenarioOptions.TrafficModel"), ...
                struct( ...
                    Type="ExitRampHighway", ...
                    EngineType="ExitRampHighwayScenario", ...
                    BranchArgument="scenarioOptions.ExitProbability"), ...
                struct( ...
                    Type="Roundabout", ...
                    EngineType="RoundaboutScenario", ...
                    BranchArgument="scenarioOptions.RoadWidth")};

            for index = 1:numel(cases)
                testCaseData = cases{index};
                engineArguments = testCase.compilePatch(struct( ...
                    Scenario=struct(Type=testCaseData.Type)));

                testCase.verifyEqual( ...
                    testCase.argumentValue(engineArguments, "scenario.Type"), ...
                    testCaseData.EngineType, ...
                    "Scenario mapping failed for " + testCaseData.Type);
                testCase.verifyTrue( ...
                    testCase.hasArgument( ...
                        engineArguments, testCaseData.BranchArgument), ...
                    "The selected scenario branch was not compiled for " + ...
                        testCaseData.Type);
            end
        end

        function scenarioCompilerOmitsInactiveBranchOptions(testCase)
            engineArguments = testCase.compilePatch(struct( ...
                Scenario=struct(Type="EtsiHighway")));

            testCase.verifyTrue(testCase.hasArgument( ...
                engineArguments, "scenarioOptions.TrafficModel"));
            testCase.verifyFalse(testCase.hasArgument( ...
                engineArguments, "scenarioOptions.VehicleCount"));
            testCase.verifyFalse(testCase.hasArgument( ...
                engineArguments, "scenarioOptions.NLanes"));
            testCase.verifyFalse(testCase.hasArgument( ...
                engineArguments, "scenarioOptions.ExitProbability"));
            testCase.verifyFalse(testCase.hasArgument( ...
                engineArguments, "scenarioOptions.RoadWidth"));
        end

        function mapsEveryRoundaboutOption(testCase)
            exitLengths = [110, 120, 130, 140];
            scenario = struct( ...
                RandomSeed=733, ...
                VehicleCount=12, ...
                ExitLengths=exitLengths, ...
                RoadWidth=5, ...
                InnerCircleDiameter=40, ...
                MeanVehicleSpeed=18, ...
                VehicleSpeedStandardDeviation=1.5, ...
                RerollSpeedOnWrapAround=false);
            engineArguments = testCase.compilePatch(struct( ...
                Scenario=struct( ...
                    Type="Roundabout", Roundabout=scenario)));

            testCase.verifyEqual(testCase.argumentValue( ...
                engineArguments, "scenario.Type"), ...
                "RoundaboutScenario");
            for field = string(fieldnames(scenario)).'
                testCase.verifyEqual(testCase.argumentValue( ...
                    engineArguments, "scenarioOptions." + field), ...
                    scenario.(field));
            end
        end

        function mapsOrderedPositioningErrorPipeline(testCase)
            errors = { ...
                struct( ...
                    Type="Gaussian", ...
                    MeanMagnitudeMeters=2, ...
                    StandardDeviationMeters=3, ...
                    ActiveRoutes=["Ramp", "Adjacent"]), ...
                struct(Type="Delay", DelaySeconds=0.25), ...
                struct( ...
                    Type="FalseExit", ...
                    AffectedVehicleProbability=0.4)};
            engineArguments = testCase.compilePatch(struct( ...
                Scenario=struct(Type="ExitRampHighway"), ...
                Positioning=struct(Errors={errors})));

            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, ...
                    "positioning.Gaussian.MeanMagnitudeMeters"), ...
                2);
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, "positioning.ErrorModules"), ...
                'Gaussian,Delay,FalseExit');
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, ...
                    "positioning.Gaussian.StandardDeviationMeters"), ...
                3);
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, "positioning.Gaussian.ActiveRoutes"), ...
                'Ramp,Adjacent');
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, "positioning.Delay.DelaySeconds"), ...
                0.25);
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, ...
                    "positioning.FalseExit.AffectedVehicleProbability"), ...
                0.4);
            testCase.verifyFalse(testCase.hasArgumentPrefix( ...
                engineArguments, "positioning.FalseMerge."));
        end

        function mapsEverySupportedRadioMode(testCase)
            cases = { ...
                struct( ...
                    Patch=struct(Type="Ieee80211p"), ...
                    EngineMode="80211p", ...
                    RequiredPrefix="ieee80211p.", ...
                    ForbiddenPrefixes=[ ...
                        "lteV2x.", "nrV2x.", "sidelink."]), ...
                struct( ...
                    Patch=struct(Type="LteV2X"), ...
                    EngineMode="LTE-V2X", ...
                    RequiredPrefix="lteV2x.", ...
                    ForbiddenPrefixes=["ieee80211p.", "nrV2x."]), ...
                struct( ...
                    Patch=struct(Type="NrV2X"), ...
                    EngineMode="NR-V2X", ...
                    RequiredPrefix="nrV2x.", ...
                    ForbiddenPrefixes=["ieee80211p.", "lteV2x."]), ...
                struct( ...
                    Patch=struct( ...
                        Type="Coexistence", ...
                        Coexistence=struct( ...
                            SidelinkType="LteV2X", ...
                            InterferenceModel="Independent")), ...
                    EngineMode="COEX-NO-INTERF", ...
                    RequiredPrefix="lteV2x.", ...
                    ForbiddenPrefixes="nrV2x."), ...
                struct( ...
                    Patch=struct( ...
                        Type="Coexistence", ...
                        Coexistence=struct( ...
                            SidelinkType="LteV2X", ...
                            InterferenceModel="Cochannel")), ...
                    EngineMode="COEX-STD-INTERF", ...
                    RequiredPrefix="lteV2x.", ...
                    ForbiddenPrefixes="nrV2x."), ...
                struct( ...
                    Patch=struct( ...
                        Type="Coexistence", ...
                        Coexistence=struct( ...
                            SidelinkType="NrV2X", ...
                            InterferenceModel="Cochannel")), ...
                    EngineMode="COEX-STD-INTERF-5G", ...
                    RequiredPrefix="nrV2x.", ...
                    ForbiddenPrefixes="lteV2x.")};

            for index = 1:numel(cases)
                testCaseData = cases{index};
                engineArguments = testCase.compilePatch(struct( ...
                    Radio=testCaseData.Patch));

                testCase.verifyEqual( ...
                    testCase.argumentValue( ...
                        engineArguments, "simulation.RadioAccessMode"), ...
                    testCaseData.EngineMode);
                testCase.verifyTrue(testCase.hasArgumentPrefix( ...
                    engineArguments, testCaseData.RequiredPrefix));
                for forbiddenPrefix = testCaseData.ForbiddenPrefixes
                    testCase.verifyFalse(testCase.hasArgumentPrefix( ...
                        engineArguments, forbiddenPrefix));
                end

                if testCaseData.Patch.Type == "Coexistence"
                    testCase.verifyTrue(testCase.hasArgumentPrefix( ...
                        engineArguments, "ieee80211p."));
                    testCase.verifyTrue(testCase.hasArgumentPrefix( ...
                        engineArguments, "sidelink."));
                    testCase.verifyTrue(testCase.hasArgumentPrefix( ...
                        engineArguments, "coexistence."));
                end
            end
        end

        function mapsOnlyTheSelectedIeeePhysicalLayerMcs(testCase)
            nativeArguments = testCase.compilePatch(struct( ...
                Radio=struct( ...
                    Type="Ieee80211p", ...
                    Ieee80211p=struct( ...
                        PhysicalLayer="Native", ...
                        Mcs=4, ...
                        LteSurrogateMcs=9))));
            testCase.verifyEqual(testCase.argumentValue( ...
                nativeArguments,"ieee80211p.Mcs"),4);
            testCase.verifyFalse(testCase.hasArgument( ...
                nativeArguments,"ieee80211p.LtePhysicalLayerMcs"));

            surrogateArguments = testCase.compilePatch(struct( ...
                Radio=struct( ...
                    Type="Ieee80211p", ...
                    Ieee80211p=struct( ...
                        PhysicalLayer="LteSurrogate", ...
                        Mcs=4, ...
                        LteSurrogateMcs=9))));
            testCase.verifyEqual(testCase.argumentValue( ...
                surrogateArguments,"ieee80211p.LtePhysicalLayerMcs"),9);
            testCase.verifyFalse(testCase.hasArgument( ...
                surrogateArguments,"ieee80211p.Mcs"));
        end

        function mapsAllSixAllocatorTypes(testCase)
            configurationTypes = [ ...
                "ReuseDistance", "MaximumReuseDistance", ...
                "MinimumReusePower", "SensingBased", "Random", "Ordered"];
            engineTypes = [ ...
                "ReuseDistance", "MaximumReuseDistance", ...
                "MinimumReusePower", "ThreeGppAutonomous", ...
                "RandomBenchmark", "OrderedBenchmark"];
            requiredArguments = [ ...
                "resourceAllocation.Controlled.ReuseMarginMeters", ...
                "resourceAllocation.Controlled.ReassignmentIntervalSeconds", ...
                "resourceAllocation.Controlled.KnownShadowingEnabled", ...
                "resourceAllocation.Autonomous.SensingThresholdDbm", ...
                "resourceAllocation.Autonomous.SelectionWindowEndMilliseconds", ...
                ""];

            for index = 1:numel(configurationTypes)
                configurationType = configurationTypes(index);
                allocationPatch = struct(Type=configurationType);
                allocationPatch.(configurationType) = struct();
                engineArguments = testCase.compilePatch(struct( ...
                    ResourceAllocation=allocationPatch));

                testCase.verifyEqual( ...
                    testCase.argumentValue( ...
                        engineArguments, "resourceAllocation.Type"), ...
                    engineTypes(index), ...
                    "Allocator mapping failed for " + configurationType);
                testCase.verifyTrue(testCase.hasArgument( ...
                    engineArguments, "resourceAllocation.RandomSeed"));
                if strlength(requiredArguments(index)) > 0
                    testCase.verifyTrue(testCase.hasArgument( ...
                        engineArguments, requiredArguments(index)));
                end
                if configurationType == "Ordered"
                    testCase.verifyFalse(testCase.hasArgumentPrefix( ...
                        engineArguments, "resourceAllocation.Controlled."));
                    testCase.verifyFalse(testCase.hasArgumentPrefix( ...
                        engineArguments, "resourceAllocation.Autonomous."));
                end
            end
        end

        function omitsOptionsOwnedByInactiveFeatures(testCase)
            engineArguments = testCase.compilePatch(struct());

            absentNames = [ ...
                "channelLoad.MeasurementWindowSeconds", ...
                "channelLoad.UpdateStepsPerWindow", ...
                "congestionControl.Enabled", ...
                "sidelink.CongestionControl.ChannelOccupancyLimitScale", ...
                "sidelink.FullDuplex.ResidualSelfInterferenceDb", ...
                "resourceAllocation.FullDuplex." + ...
                    "SelfInterferenceThresholdMultiplier", ...
                "output.WirelessBlindSpot.MaximumDelaySeconds", ...
                "output.WirelessBlindSpot.BinWidthSeconds", ...
                "output.DelayMetrics.BinWidthSeconds", ...
                "output.CoexistenceTechnologyShare.Enabled", ...
                "channel.PacketErrorRateCurveDirectory", ...
                "channel.NlosPacketErrorRateCurveDirectory", ...
                "resourcePool.SubchannelSizeResourceBlocks", ...
                "resourcePool.MaximumFrequencyDomainBeaconResources"];
            for name = absentNames
                testCase.verifyFalse( ...
                    testCase.hasArgument(engineArguments, name), ...
                    "Inactive engine option was emitted: " + name);
            end

            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, "channelLoad.Enabled"), ...
                false);
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, ...
                    "output.WirelessBlindSpot.Enabled"), ...
                false);
        end

        function emitsOptionsWhenTheirFeaturesAreActive(testCase)
            temporaryFolder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            curveDirectory = string(fullfile( ...
                temporaryFolder.Folder, "curves", "los"));
            mkdir(curveDirectory);
            patchData = struct( ...
                Application=struct( ...
                    ChannelLoad=struct(Enabled=true), ...
                    CongestionControl=struct( ...
                        Enabled=true, ...
                        ChannelOccupancyLimitScale=0.75)), ...
                Radio=struct( ...
                    Sidelink=struct(DuplexMode="Full")), ...
                Channel=struct( ...
                    PacketError=struct( ...
                        Model="Curves", ...
                        CurveDirectory=curveDirectory)), ...
                Outputs=struct( ...
                    WirelessBlindSpot=struct(Enabled=true), ...
                    UpdateDelay=struct(Enabled=true)));

            engineArguments = testCase.compilePatch(patchData);

            presentNames = [ ...
                "channelLoad.MeasurementWindowSeconds", ...
                "channelLoad.UpdateStepsPerWindow", ...
                "congestionControl.Enabled", ...
                "sidelink.CongestionControl.ChannelOccupancyLimitScale", ...
                "sidelink.FullDuplex.ResidualSelfInterferenceDb", ...
                "resourceAllocation.FullDuplex." + ...
                    "SelfInterferenceThresholdMultiplier", ...
                "output.WirelessBlindSpot.MaximumDelaySeconds", ...
                "output.WirelessBlindSpot.BinWidthSeconds", ...
                "output.DelayMetrics.BinWidthSeconds", ...
                "channel.PacketErrorRateCurveDirectory"];
            for name = presentNames
                testCase.verifyTrue( ...
                    testCase.hasArgument(engineArguments, name), ...
                    "Active engine option was omitted: " + name);
            end
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, ...
                    "channel.PacketErrorRateCurveDirectory"), ...
                curveDirectory);
        end

        function keepsRunOptionsOutsideScientificConfiguration(testCase)
            temporaryFolder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            outputDirectory = string(fullfile( ...
                temporaryFolder.Folder, "compiler-boundary"));
            runLabel = "paired-seed-17";
            patchData = struct(Outputs=struct( ...
                VehicleKinematics=struct(Enabled=true)));

            [engineArguments, ~, configuration] = testCase.compilePatch( ...
                patchData, outputDirectory, runLabel);

            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, "output.Directory"), ...
                outputDirectory);
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, "simulation.RunLabel"), ...
                runLabel);
            testCase.verifyEqual( ...
                testCase.argumentValue( ...
                    engineArguments, ...
                    "output.VehicleKinematics.Enabled"), ...
                true);
            testCase.verifyFalse( ...
                isfield(configuration.Data, "OutputDirectory"));
            testCase.verifyFalse(isfield(configuration.Data, "RunLabel"));
            testCase.verifyFalse(isfolder(outputDirectory));
        end

        function handsOffRoadsideUnitArrayWithoutReordering(testCase)
            units = { ...
                struct( ...
                    Id="rsu-west", ...
                    Technology="LteV2X", ...
                    PacketType="Cam", ...
                    PositionMeters=[-25, 3]), ...
                struct( ...
                    Id="rsu-east", ...
                    Technology="LteV2X", ...
                    PacketType="Cam", ...
                    PositionMeters=[125, -3])};
            patchData = struct(Infrastructure=struct( ...
                RoadsideUnits={units}));

            [~, compiledUnits, configuration] = ...
                testCase.compilePatch(patchData);

            testCase.verifyEqual( ...
                compiledUnits, ...
                configuration.Data.Infrastructure.RoadsideUnits);
            testCase.verifyEqual( ...
                string(cellfun( ...
                    @(unit) unit.Id, compiledUnits, ...
                    UniformOutput=false)), ...
                ["rsu-west", "rsu-east"]);
            testCase.verifyEqual( ...
                compiledUnits{1}.PositionMeters, [-25, 3]);
            testCase.verifyEqual( ...
                compiledUnits{2}.PositionMeters, [125, -3]);
        end
    end

    methods (Static, Access = private)
        function [engineArguments, roadsideUnits, configuration] = ...
                compilePatch(patchData, outputDirectory, runLabel)
            arguments
                patchData (1, 1) struct
                outputDirectory (1, 1) string = ...
                    "results/not-created-by-compiler"
                runLabel (1, 1) string = ""
            end

            template = v2xsim.config.ConfigurationTemplate(struct( ...
                SchemaVersion=1));
            configuration = template.resolve( ...
                Patch=v2xsim.config.patch(patchData));
            plan = v2xsim.runtime.compile(configuration);
            runOptions = v2xsim.runtime.RunOptions( ...
                OutputDirectory=outputDirectory, ...
                RunLabel=runLabel);
            [engineArguments, roadsideUnits] = ...
                v2xsim.runtime.internal.compileEngineArguments( ...
                    plan, runOptions);
        end

        function result = hasArgument(engineArguments, name)
            result = any(string(engineArguments(1:2:end)) == name);
        end

        function result = hasArgumentPrefix(engineArguments, prefix)
            result = any(startsWith( ...
                string(engineArguments(1:2:end)), prefix));
        end

        function value = argumentValue(engineArguments, name)
            names = string(engineArguments(1:2:end));
            index = find(names == name, 1);
            assert(~isempty(index), ...
                "Expected engine argument was not compiled: " + name);
            value = engineArguments{2 * index};
        end
    end
