                ~,technology,vehicleUeId,perspective, ...
                summaries,distanceGridMeters)
            rowCount = numel(summaries);
            metrics = table( ...
                technology,vehicleUeId,perspective, ...
                repmat(distanceGridMeters(end),rowCount,1), ...
                repmat(numel(distanceGridMeters),rowCount,1), ...
                [summaries.NonemptyDeliveryBinCount].', ...
                [summaries.NonemptyRadioBinCount].', ...
                [summaries.CorrectCount].', ...
                [summaries.ErrorCount].', ...
                [summaries.BlockedCount].', ...
                [summaries.TotalCount].', ...
                [summaries.RadioAttemptCount].', ...
                [summaries.DeliveryPrr].', ...
                [summaries.RadioPrr].', ...
                [summaries.BlockingRate].', ...
                [summaries.DeliveryPrrAuc].', ...
                [summaries.RadioPrrAuc].', ...
                [summaries.DeliveryPrrAucStatus].', ...
                [summaries.RadioPrrAucStatus].', ...
                VariableNames=[ ...
                    "Technology","VehicleUeId","Perspective", ...
                    "MaximumDistanceMeters","DistanceBinCount", ...
                    "NonemptyDeliveryBinCount", ...
                    "NonemptyRadioBinCount","CorrectCount", ...
                    "ErrorCount","BlockedCount","TotalCount", ...
                    "RadioAttemptCount","DeliveryPrr","RadioPrr", ...
                    "BlockingRate","DeliveryPrrAuc","RadioPrrAuc", ...
                    "DeliveryPrrAucStatus", ...
                    "RadioPrrAucStatus"]);
        end
