    end

    methods (Access = private)
        function [simParams, remainingArguments] = ...
                initializeWithArguments(~, inputArguments, configPath)
            if nargin < 3
                configPath = "";
            end

            [simParams, remainingArguments] = ...
                initiateMainSimulationParameters( ...
                    configPath, inputArguments);
        end
    end
