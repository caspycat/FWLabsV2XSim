        function testConfigFileAndCommandLinePrecedence(testCase)
            configPath = string(tempname) + ".cfg";
            writelines([ ...
                "[simulation.RandomSeed] 1", ...
                "[scenario.Type] BrownianMotionScenario", ...
                "[scenarioOptions.RandomSeed] 41", ...
                "[scenarioOptions.VehicleCount] 20", ...
                "[scenarioOptions.SimulationAreaSize] 750", ...
                "[scenarioOptions.MeanVehicleSpeed] 30"], configPath);
            testCase.addTeardown(@() delete(configPath));

            inputArguments = { ...
                "scenarioOptions.RandomSeed", 42, ...
                "scenarioOptions.VehicleCount", 35, ...
                "scenarioOptions.VehicleSpeedStandardDeviation", 2};
            [simParams, remainingArguments] = ...
                testCase.initializeWithArguments( ...
                    inputArguments, configPath);

            testCase.verifyEqual(simParams.scenarioOptions.VehicleCount, 35);
            testCase.verifyEqual(simParams.scenarioOptions.RandomSeed, 42);
            testCase.verifyEqual( ...
                simParams.scenarioOptions.SimulationAreaSize, 750);
            testCase.verifyEqual( ...
                simParams.scenarioOptions.MeanVehicleSpeed, 30);
            testCase.verifyEqual( ...
                simParams.scenarioOptions.VehicleSpeedStandardDeviation, 2);
            testCase.verifyEmpty(remainingArguments{1});
        end

        function testRemovedLegacyScenarioNameIsRejected(testCase)
            testCase.verifyError( ...
                @() testCase.initializeWithArguments( ...
                    {"simulation.RandomSeed", 1, "scenario.Type", "PPP"}), ...
                "v2xsim:legacy:UnknownScenario");
        end

        function testParsesOrderedPositionErrorChain(testCase)
            inputArguments = { ...
                "simulation.RandomSeed", 1, ...
                "scenario.Type", "ExitRampHighwayScenario", ...
                "positioning.ErrorModules", ...
                    "Gaussian,FalseExit,Delay,FalseMerge", ...
                "positioning.Gaussian.StandardDeviationMeters", ...
                    3, ...
                "positioning.Gaussian.DisplacementRandomSeed", 101, ...
                "positioning.Gaussian.AffectedVehicleProbability", ...
                    0.4, ...
                "positioning.Gaussian.SelectionRandomSeed", 102, ...
                "positioning.Gaussian.ResetAfterSeconds", 7, ...
                "positioning.Gaussian.ActiveRoutes", ...
                    "Ramp,Merge,Adjacent", ...
                "positioning.FalseExit.AffectedVehicleProbability", ...
                    0.1, ...
                "positioning.FalseExit.ResetAfterSeconds", ...
                    5, ...
                "positioning.FalseExit.DisplacementScale", 0.25, ...
                "positioning.FalseExit.SelectionRandomSeed", 103, ...
                "positioning.Delay.DelaySeconds", 0.5, ...
                "positioning.FalseMerge.AffectedVehicleProbability", ...
                    0.2, ...
                "positioning.FalseMerge.DisplacementScale", 0.5, ...
                "positioning.FalseMerge.SelectionRandomSeed", 104};

            [simParams, remainingArguments] = ...
                testCase.initializeWithArguments(inputArguments);

            modules = simParams.positionErrorChain.Modules;
            testCase.verifyEqual( ...
                simParams.positionErrorModuleNames, ...
                ["Gaussian", "FalseExit", "Delay", "FalseMerge"]);
            testCase.verifyClass( ...
                modules{1}, ...
                "v2xsim.positioning." + ...
                "PositionErrorStatusEffectInflictor");
            testCase.verifyClass( ...
                modules{1}.Effect, ...
                "v2xsim.positioning." + ...
                "IsotropicGaussianPositionErrorStatusEffect");
            testCase.verifyEqual( ...
                modules{1}.Effect.StandardDeviationMeters, 3);
            testCase.verifyEqual( ...
                modules{1}.Effect.DisplacementRandomSeed, 101);
            testCase.verifyEqual( ...
                modules{1}.Effect.SelectionProbability, 0.4);
            testCase.verifyEqual( ...
                modules{1}.Effect.SelectionRandomSeed, 102);
            testCase.verifyEqual( ...
                modules{1}.Effect.ResetAfterSeconds, 7);
            testCase.verifyEqual( ...
                modules{1}.Effect.ActiveRoutes, ...
                ["Ramp", "Merge", "Adjacent"]);
            testCase.verifyClass( ...
                modules{2}, ...
                "v2xsim.positioning." + ...
                "PositionErrorStatusEffectInflictor");
            testCase.verifyClass( ...
                modules{2}.Effect, ...
                "v2xsim.positioning." + ...
                "FalseExitPositionErrorStatusEffect");
            testCase.verifyEqual( ...
                modules{2}.Effect.SelectionProbability, 0.1);
            testCase.verifyEqual( ...
                modules{2}.Effect.ResetAfterSeconds, 5);
            testCase.verifyEqual( ...
                modules{2}.Effect.DisplacementScale, 0.25);
            testCase.verifyEqual( ...
                modules{2}.Effect.SelectionRandomSeed, 103);
            testCase.verifyClass( ...
                modules{3}, ...
                "v2xsim.positioning.PositionDelayError");
            testCase.verifyEqual(modules{3}.DelaySeconds, 0.5);
            testCase.verifyClass( ...
                modules{4}, ...
                "v2xsim.positioning." + ...
                "PositionErrorStatusEffectInflictor");
            testCase.verifyClass( ...
                modules{4}.Effect, ...
                "v2xsim.positioning." + ...
                "FalseMergePositionErrorStatusEffect");
            testCase.verifyEqual( ...
                modules{4}.Effect.SelectionProbability, 0.2);
            testCase.verifyEqual( ...
                modules{4}.Effect.ResetAfterSeconds, Inf);
            testCase.verifyEqual( ...
                modules{4}.Effect.DisplacementScale, 0.5);
            testCase.verifyEqual( ...
                modules{4}.Effect.SelectionRandomSeed, 104);
            testCase.verifyEmpty(remainingArguments{1});
        end

        function testPositionErrorSeedsDefaultToIndependentStreams( ...
                testCase)
            [simParams, remainingArguments] = ...
                testCase.initializeWithArguments({ ...
                    "simulation.RandomSeed", 7, ...
                    "scenario.Type", "ExitRampHighwayScenario", ...
                    "positioning.ErrorModules", ...
                        "Gaussian,FalseExit,FalseMerge"});

            modules = simParams.positionErrorChain.Modules;
            testCase.verifyNotEqual( ...
                modules{1}.Effect.DisplacementRandomSeed, ...
                modules{1}.Effect.SelectionRandomSeed);
            testCase.verifyNotEqual( ...
                modules{1}.Effect.DisplacementRandomSeed, ...
                modules{2}.Effect.SelectionRandomSeed);
            testCase.verifyNotEqual( ...
                modules{2}.Effect.SelectionRandomSeed, ...
                modules{3}.Effect.SelectionRandomSeed);
            testCase.verifyEmpty(remainingArguments{1});
        end

        function testRemovedPositionErrorSeedNamesAreNotAliases( ...
                testCase)
            removedArguments = { ...
                "positioning.Gaussian.RandomSeed", 101, ...
                "positioning.Gaussian.ExposureRandomSeed", 102, ...
                "positioning.FalseExit.RandomSeed", 103};
            [~, remainingArguments] = ...
                testCase.initializeWithArguments([{ ...
                    "simulation.RandomSeed", 7, ...
                    "scenario.Type", "ExitRampHighwayScenario", ...
                    "positioning.ErrorModules", ...
                        "Gaussian,FalseExit"}, removedArguments]);

            testCase.verifyEqual( ...
                remainingArguments{1}, removedArguments);
        end

        function testPositionErrorConfigAllowsCommandLineOverride( ...
                testCase)
            configPath = string(tempname) + ".cfg";
            writelines([ ...
                "[simulation.RandomSeed] 1", ...
                "[positioning.ErrorModules] Gaussian,Delay", ...
                "[positioning.Gaussian." + ...
                    "StandardDeviationMeters] 2", ...
                "[positioning.Delay.DelaySeconds] 0.5"], ...
                configPath);
            testCase.addTeardown(@() delete(configPath));

            [simParams, remainingArguments] = ...
                testCase.initializeWithArguments( ...
                    { ...
                    "positioning.Gaussian." + ...
                        "StandardDeviationMeters", 4}, ...
                    configPath);

            modules = simParams.positionErrorChain.Modules;
            testCase.verifyEqual( ...
                modules{1}.Effect.StandardDeviationMeters, 4);
            testCase.verifyEqual(modules{2}.DelaySeconds, 0.5);
            testCase.verifyEmpty(remainingArguments{1});
        end

