classdef VehicleKinematicsDispatchTest < matlab.unittest.TestCase
    %VEHICLEKINEMATICSDISPATCHTEST Tests legacy dispatch adapters.

    methods (TestClassSetup)
        function addCompatibilityPaths(testCase)
            projectRoot = fileparts(fileparts(fileparts(fileparts( ...
                mfilename("fullpath")))));
            pathsToAdd = [ ...
                fullfile(projectRoot,"old_src","MatFilesInit"), ...
                fullfile(projectRoot,"old_src","MatFilesPosition")];
            originalPath = path;
            testCase.addTeardown(@() path(originalPath));
            for pathToAdd = pathsToAdd
                addpath(pathToAdd);
            end
        end
    end

    methods (Test)
        function recordsInitialAndUpdatedWorldKinematics(testCase)
            outputDirectory = testCase.makeOutputDirectory();
            [registry,dispatcher] = ...
                testCase.createRecorder(outputDirectory);
            testCase.addTeardown(@() registry.cleanup());
            [simParams,remainingArguments] = ...
                initiateMainSimulationParameters("",{ ...
                    "simulation.RandomSeed",1, ...
                    "scenario.Type","BidirectionalHighwayScenario", ...
                    "scenarioOptions.VehicleCount",3, ...
                    "scenarioOptions.MeanVehicleSpeed",20, ...
                    "scenarioOptions.VehicleSpeedStandardDeviation",0, ...
                    "scenarioOptions.RerollSpeedOnWrapAround",false});
            testCase.assertEmpty(remainingArguments{1});
            simParams.technology = constants.TECH_ONLY_11P;
            appParams = struct( ...
                nRSUs=1, ...
                RSU_xLocation=100, ...
                RSU_yLocation=20);

            [~,simValues,positionManagement] = ...
                initVehiclePositions( ...
                    simParams,appParams,dispatcher);
            initialKinematics = ...
                simValues.world.TrafficScenario.VehicleKinematics( ...
                    cellstr(simValues.world.VehicleIds),:);

            [~,~,~,~,~,simValues] = ...
                updatePosition( ...
                    0.1,simValues.IDvehicle,0.1, ...
                    positionManagement,simValues,struct(),simParams);
            updatedKinematics = ...
                simValues.world.TrafficScenario.VehicleKinematics( ...
                    cellstr(simValues.world.VehicleIds),:);

            filename = fullfile( ...
                outputDirectory,"vehicle_kinematics.csv");
            actual = testCase.readOutput(filename);
            expected = [ ...
                testCase.outputRows(0,initialKinematics); ...
                testCase.outputRows(0.1,updatedKinematics)];

            testCase.verifyEqual(height(actual),6);
            testCase.verifyFalse(any(actual.VehicleId == "RSU1"));
            testCase.verifyEqual( ...
                actual.SimulationTimeSeconds, ...
                expected.SimulationTimeSeconds);
            testCase.verifyEqual(actual.VehicleId,expected.VehicleId);
            actualKinematics = actual{:,3:end};
            expectedKinematics = expected{:,3:end};
            testCase.verifyEqual( ...
                isnan(actualKinematics), ...
                isnan(expectedKinematics));
            availableValues = ~isnan(expectedKinematics);
            testCase.verifyEqual( ...
                actualKinematics(availableValues), ...
                expectedKinematics(availableValues), ...
                AbsTol=1e-12,RelTol=1e-14);
            testCase.verifyEqual(sum( ...
                startsWith( ...
                    readlines(filename), ...
                    "SimulationTimeSeconds,")),1);
        end

        function traceAdapterUsesNaNForUnavailableVectors(testCase)
            outputDirectory = testCase.makeOutputDirectory();
            [registry,dispatcher] = ...
                testCase.createRecorder(outputDirectory);
            testCase.addTeardown(@() registry.cleanup());
            dataTrace = [ ...
                0, 1, 0, 0, 10; ...
                0, 2, 5, 0, 20; ...
                1, 2, 6, 1, 21; ...
                1, 3, 8, 2, 30];
            simValues = struct("hookDispatcher",dispatcher);

            updatePositionFile( ...
                1,dataTrace,[1;2],[0;5],[0;0],0, ...
                simValues,struct());

            filename = fullfile( ...
                outputDirectory,"vehicle_kinematics.csv");
            actual = testCase.readOutput(filename);
            testCase.verifyEqual( ...
                string(actual.Properties.VariableNames), ...
                [ ...
                    "SimulationTimeSeconds", ...
                    "VehicleId", ...
                    "X", ...
                    "Y", ...
                    "vX", ...
                    "vY", ...
                    "aX", ...
                    "aY"]);
            testCase.verifyEqual( ...
                actual.SimulationTimeSeconds,[1;1]);
            testCase.verifyEqual(actual.VehicleId,["2";"3"]);
            testCase.verifyEqual(actual.X,[6;8]);
            testCase.verifyEqual(actual.Y,[1;2]);
            testCase.verifyTrue(all( ...
                isnan(actual{:,["vX","vY","aX","aY"]}), ...
                "all"));
        end
    end

    methods (Access = private)
        function outputDirectory = makeOutputDirectory(testCase)
            fixture = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            outputDirectory = string(fixture.Folder);
        end

        function [registry,dispatcher] = createRecorder( ...
                ~,outputDirectory)
            container = v2xsim.hook.dependency.ServiceContainer();
            container.provideConstant( ...
                ?v2xsim.hook.dependencies.OutputDirectory, ...
                v2xsim.hook.dependencies.OutputDirectory( ...
                    outputDirectory));
            registry = v2xsim.hook.HookRegistry(container);
            registry.register( ...
                v2xsim.hooks.common.VehicleKinematicsRecorder(), ...
                v2xsim.hook.points.AfterVehicleKinematicsUpdated);
            dispatcher = registry.createDispatcher();
        end

        function output = readOutput(~,filename)
            output = readtable(filename,TextType="string");
            output.VehicleId = string(output.VehicleId);
        end

        function rows = outputRows( ...
                ~,simulationTimeSeconds,vehicleKinematics)
            vehicleCount = height(vehicleKinematics);
            rows = table( ...
                repmat(simulationTimeSeconds,vehicleCount,1), ...
                string(vehicleKinematics.Properties.RowNames), ...
                vehicleKinematics.X, ...
                vehicleKinematics.Y, ...
                vehicleKinematics.vX, ...
                vehicleKinematics.vY, ...
                vehicleKinematics.aX, ...
                vehicleKinematics.aY, ...
                VariableNames=[ ...
                    "SimulationTimeSeconds", ...
                    "VehicleId", ...
                    "X", ...
                    "Y", ...
                    "vX", ...
                    "vY", ...
                    "aX", ...
                    "aY"]);
        end
    end
end
