classdef Cv2xSensedPowerTest < matlab.unittest.TestCase
    %CV2XSENSEDPOWERTEST Frequency coupling in legacy C-V2X sensing.

    methods (TestClassSetup)
        function addLegacySensingPath(testCase)
            projectRoot = string(fileparts(fileparts(fileparts( ...
                fileparts(mfilename("fullpath"))))));
            originalPath = path;
            testCase.addTeardown(@() path(originalPath));
            addpath(fullfile( ...
                projectRoot,"old_src","MainFilesCV2X"));
        end
    end

    methods (Test)
        function testNoIbeHalfDuplexPreservesUncoupledResources( ...
                testCase)
            [stationManagement,sinrManagement,appParams,phyParams] = ...
                testCase.twoTransmitterState();
            phyParams.Ksi = Inf;
            phyParams.IBEmatrixData = eye(2);

            sensedPower = sensedPowerCV2X( ...
                stationManagement,sinrManagement, ...
                appParams,phyParams);

            testCase.verifyEqual( ...
                sensedPower,[Inf 7;5 Inf], ...
                "A structural zero coupling must not evaluate as " + ...
                "zero times infinite half-duplex self-power.");
            testCase.verifyFalse(any(isnan(sensedPower),"all"));
        end

        function testNonzeroIbeCouplingRetainsWeightedPower(testCase)
            [stationManagement,sinrManagement,appParams,phyParams] = ...
                testCase.twoTransmitterState();
            phyParams.Ksi = 0.01;
            phyParams.P_ERP_MHz_CV2X = [100;200];
            phyParams.IBEmatrixData = [1 0.1;0.25 1];

            sensedPower = sensedPowerCV2X( ...
                stationManagement,sinrManagement, ...
                appParams,phyParams);

            testCase.verifyEqual( ...
                sensedPower,[1.5 7.2;5.25 3.75], ...
                AbsTol=1e-12);
        end

        function testNonzeroIbePropagatesHalfDuplexSelfPower(testCase)
            [stationManagement,sinrManagement,appParams,phyParams] = ...
                testCase.twoTransmitterState();
            phyParams.Ksi = Inf;
            phyParams.IBEmatrixData = [1 0.1;0.25 1];

            sensedPower = sensedPowerCV2X( ...
                stationManagement,sinrManagement, ...
                appParams,phyParams);

            testCase.verifyEqual(sensedPower,Inf(2));
            testCase.verifyFalse(any(isnan(sensedPower),"all"));
        end
    end

    methods (Static, Access = private)
        function [stationManagement,sinrManagement, ...
                appParams,phyParams] = twoTransmitterState()
            stationManagement = struct( ...
                "activeIDsCV2X",[1;2], ...
                "indexInActiveIDs_ofLTEnodes",[1;2], ...
                "transmittingIDsCV2X",[1;2], ...
                "indexInActiveIDsOnlyLTE_OfTxLTE",[1;2], ...
                "transmittingFusedLTE",[1;2]);
            sinrManagement = struct( ...
                "P_RX_MHz",[0 5;7 0]);
            appParams = struct("NbeaconsF",2);
            phyParams = struct( ...
                "Ksi",Inf, ...
                "P_ERP_MHz_CV2X",ones(2,1), ...
                "IBEmatrixData",eye(2));
        end
    end
end
