classdef WirelessBlindSpotThresholdCountsTest < matlab.unittest.TestCase
    %WIRELESSBLINDSPOTTHRESHOLDCOUNTSTEST Histogram WBS count contracts.

    methods (Test)
        function preservesEveryThresholdBoundary(testCase)
            thresholds = [0.1, 0.2, 0.5, 1, 2];
            belowThresholds = thresholds - eps(thresholds);
            aboveThresholds = thresholds + eps(thresholds);
            receivedAges = [ ...
                -0.0; 0; belowThresholds(:); thresholds(:); ...
                aboveThresholds(:); 3];
            neverReceivedEntryAges = [ ...
                0; belowThresholds(:); thresholds(:); ...
                aboveThresholds(:); 3];

            testCase.verifyMatchesThresholdLoop( ...
                receivedAges, neverReceivedEntryAges, thresholds);
        end

        function acceptsEmptyAgeSets(testCase)
            thresholds = 0.1 .* (1:10);

            [greaterOrEqualCounts, shorterCounts] = ...
                v2xsim.hooks.common.internal. ...
                countWirelessBlindSpotThresholds( ...
                    zeros(0, 1), zeros(0, 1), thresholds);

            testCase.verifyEqual( ...
                greaterOrEqualCounts, zeros(size(thresholds)));
            testCase.verifyEqual( ...
                shorterCounts, zeros(size(thresholds)));
        end

        function matchesThresholdLoopForRandomizedAges(testCase)
            stream = RandStream("mrg32k3a", Seed=20260730);
            thresholds = 0.1 .* (1:150);

            for trialIndex = 1:100
                receivedCount = randi(stream, 250) - 1;
                entryCount = randi(stream, 250) - 1;
                boundaryIndices = randi( ...
                    stream, numel(thresholds), 12, 1);
                boundaryValues = thresholds(boundaryIndices).';
                receivedAges = [ ...
                    16 .* rand(stream, receivedCount, 1); ...
                    0; boundaryValues; ...
                    boundaryValues - eps(boundaryValues); ...
                    boundaryValues + eps(boundaryValues)];
                neverReceivedEntryAges = [ ...
                    16 .* rand(stream, entryCount, 1); ...
                    0; boundaryValues; ...
                    boundaryValues - eps(boundaryValues); ...
                    boundaryValues + eps(boundaryValues)];

                testCase.verifyMatchesThresholdLoop( ...
                    receivedAges, neverReceivedEntryAges, thresholds, ...
                    sprintf("Randomized trial %d failed.", trialIndex));
            end
        end
    end

    methods (Access = private)
        function verifyMatchesThresholdLoop( ...
                testCase, receivedAges, neverReceivedEntryAges, ...
                thresholds, diagnostic)
            arguments (Input)
                testCase (1, 1)
                receivedAges (:, 1) double
                neverReceivedEntryAges (:, 1) double
                thresholds (1, :) double
                diagnostic (1, 1) string = ...
                    "Histogram counts differ from the threshold loop."
            end

            [expectedGreaterOrEqual, expectedShorter] = ...
                thresholdLoopOracle( ...
                    receivedAges, neverReceivedEntryAges, thresholds);
            [actualGreaterOrEqual, actualShorter] = ...
                v2xsim.hooks.common.internal. ...
                countWirelessBlindSpotThresholds( ...
                    receivedAges, neverReceivedEntryAges, thresholds);

            testCase.verifyEqual( ...
                actualGreaterOrEqual, expectedGreaterOrEqual, ...
                diagnostic);
            testCase.verifyEqual( ...
                actualShorter, expectedShorter, diagnostic);
        end
    end
end

function [greaterOrEqualCounts, shorterCounts] = ...
        thresholdLoopOracle( ...
            receivedAges, neverReceivedEntryAges, thresholds)
greaterOrEqualCounts = zeros(size(thresholds));
shorterCounts = zeros(size(thresholds));
for thresholdIndex = 1:numel(thresholds)
    threshold = thresholds(thresholdIndex);
    greaterOrEqualCounts(thresholdIndex) = ...
        nnz(receivedAges >= threshold) + ...
        nnz(neverReceivedEntryAges > threshold);
    shorterCounts(thresholdIndex) = ...
        nnz(receivedAges > 0 & receivedAges < threshold);
end
end
