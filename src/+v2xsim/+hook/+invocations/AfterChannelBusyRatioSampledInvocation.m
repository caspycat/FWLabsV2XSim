classdef AfterChannelBusyRatioSampledInvocation < ...
        v2xsim.hook.invocation.Invocation
    %AFTERCHANNELBUSYRATIOSAMPLEDINVOCATION Per-UE CBR observations.

    properties (SetAccess = immutable)
        SimulationTimeSeconds (1, 1) double ...
            {mustBeReal, mustBeFinite, mustBeNonnegative}
        Technology (1, 1) string
        UeIds (:, 1) double ...
            {mustBeReal, mustBeFinite, mustBeInteger, mustBePositive}
        Channels (:, 1) double ...
            {mustBeReal, mustBeFinite, mustBeInteger, mustBePositive}
        Values (:, 1) double {mustBeReal}
        TechnologyOnlyValues (:, 1) double {mustBeReal}
    end

    methods
        function obj = AfterChannelBusyRatioSampledInvocation( ...
                simulationTimeSeconds, technology, ueIds, channels, ...
                values, technologyOnlyValues)
            arguments (Input)
                simulationTimeSeconds (1, 1) double ...
                    {mustBeReal, mustBeFinite, mustBeNonnegative}
                technology (1, 1) string
                ueIds (:, 1) double ...
                    {mustBeReal, mustBeFinite, ...
                    mustBeInteger, mustBePositive}
                channels (:, 1) double ...
                    {mustBeReal, mustBeFinite, ...
                    mustBeInteger, mustBePositive}
                values (:, 1) double {mustBeReal}
                technologyOnlyValues (:, 1) double ...
                    {mustBeReal} = zeros(0, 1)
            end

            technology = validatestring( ...
                technology, ["11p", "LTE", "5G"]);
            rowCount = numel(ueIds);
            if numel(channels) ~= rowCount || ...
                    numel(values) ~= rowCount || ...
                    (~isempty(technologyOnlyValues) && ...
                    numel(technologyOnlyValues) ~= rowCount)
                error( ...
                    "v2xsim:hook:invocations:CbrSizeMismatch", ...
                    "UE IDs, channels, and CBR values must have " + ...
                    "matching sizes.");
            end
            if any(values < -1 | values > 1 | isnan(values)) || ...
                    any(technologyOnlyValues < -1 | ...
                    technologyOnlyValues > 1 | ...
                    isnan(technologyOnlyValues))
                error( ...
                    "v2xsim:hook:invocations:InvalidCbrValue", ...
                    "CBR values must be -1 or between zero and one.");
            end

            obj.SimulationTimeSeconds = simulationTimeSeconds;
            obj.Technology = technology;
            obj.UeIds = ueIds;
            obj.Channels = channels;
            obj.Values = values;
            obj.TechnologyOnlyValues = technologyOnlyValues;
        end
    end
end
