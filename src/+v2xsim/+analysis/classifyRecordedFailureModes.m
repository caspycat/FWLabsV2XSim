function [classified,evidence,coverage,exposedStatus] = ...
        classifyRecordedFailureModes( ...
            terminalFates,attemptTrace,counterfactualTrace, ...
            reuseCandidates)
%CLASSIFYRECORDEDFAILUREMODES Join raw PHY and allocator evidence.
%   PacketSequence is projected from TERMINALFATES after joining by stable
%   UE identity, GenerationTimeSeconds, and AttemptNumber. This avoids
%   treating a recorder-local sequence as authoritative.
%
%   Harmful interference overlap is joined by AllocationEpoch and the
%   canonical desired-transmitter/interferer UE pair. The allocator's live
%   resource relation must match the PHY counterfactual relation, including
%   the controller's other_same_time to PHY other mapping. The strict
%   classifyFailureModes algorithm is then applied once per fate so
%   EvidenceIsExhaustive is interpreted per terminal error rather than
%   globally.
%
%   This helper does not classify exposed terminals. That conclusion
%   requires a complete explicit shadow decode-probability set.

arguments (Input)
    terminalFates table
    attemptTrace table
    counterfactualTrace table
    reuseCandidates table
end
arguments (Output)
    classified table
    evidence table
    coverage table
    exposedStatus (1,1) string
end

terminalFates = ...
    v2xsim.analysis.aggregateTerminalPacketFates(terminalFates);
validateTraceSchema( ...
    attemptTrace, ...
    v2xsim.analysis.emptyInterferenceAttemptTrace(), ...
    "attempt");
validateTraceSchema( ...
    counterfactualTrace, ...
    v2xsim.analysis.emptyInterferenceCounterfactualTrace(), ...
    "counterfactual");
validateReuseCandidates(reuseCandidates);

evidence = emptyClassifierEvidence();
fateCount = height(terminalFates);
hasAttemptEvidence = false(fateCount,1);
evidenceIsExhaustive = false(fateCount,1);
counterfactualCount = zeros(fateCount,1);

fateKeys = directedGenerationKeys(terminalFates);
if numel(unique(fateKeys)) ~= numel(fateKeys)
    error( ...
        "v2xsim:analysis:AmbiguousTerminalGenerationIdentity", ...
        "Terminal fate generation identities must be unique.");
end
attemptKeys = directedGenerationKeys(attemptTrace);
[knownAttempts,attemptFateRows] = ismember( ...
    attemptKeys,fateKeys);
if ~all(knownAttempts)
    error( ...
        "v2xsim:analysis:InterferenceAttemptJoinFailure", ...
        "%d interference attempts did not match a terminal fate.", ...
        nnz(~knownAttempts));
end
if numel(unique(attemptFateRows)) ~= ...
        numel(attemptFateRows)
    error( ...
        "v2xsim:analysis:DuplicateInterferenceAttemptTrace", ...
        "A terminal error has multiple attempt-evidence rows.");
end
if any( ...
        terminalFates.Outcome(attemptFateRows) ~= "error") || ...
        any(attemptTrace.Outcome ~= "error")
    error( ...
        "v2xsim:analysis:InvalidInterferenceAttemptOutcome", ...
        "Runtime interference evidence is valid only for " + ...
        "terminal error links.");
end
knownFateAttempts = ...
    ~isnan(terminalFates.AttemptNumber(attemptFateRows));
if any( ...
        terminalFates.AttemptNumber( ...
            attemptFateRows(knownFateAttempts)) ~= ...
        attemptTrace.AttemptNumber(knownFateAttempts))
    error( ...
        "v2xsim:analysis:InterferenceAttemptJoinFailure", ...
        "Interference and packet-fate attempt numbers disagree.");
end
hasAttemptEvidence(attemptFateRows) = true;
evidenceIsExhaustive(attemptFateRows) = ...
    attemptTrace.EvidenceIsExhaustive;

attemptIdentityKeys = directedAttemptKeys(attemptTrace);
if numel(unique(attemptIdentityKeys)) ~= ...
        numel(attemptIdentityKeys)
    error( ...
        "v2xsim:analysis:DuplicateInterferenceAttemptTrace", ...
        "Interference attempt identities must be unique.");
end
counterfactualKeys = ...
    directedAttemptKeys(counterfactualTrace);
[knownCounterfactuals,counterAttemptRows] = ismember( ...
    counterfactualKeys,attemptIdentityKeys);
if ~all(knownCounterfactuals)
    error( ...
        "v2xsim:analysis:" + ...
        "InterferenceCounterfactualJoinFailure", ...
        "%d counterfactuals did not match an attempt row.", ...
        nnz(~knownCounterfactuals));
end
counterFateRows = attemptFateRows(counterAttemptRows);
if ~isempty(counterFateRows)
    counterfactualCount = accumarray( ...
        counterFateRows,1,[fateCount,1]);
end

isHarmfulReuse = harmfulReuseFlags( ...
    counterfactualTrace,reuseCandidates);
counterfactualRowCount = height(counterfactualTrace);
if counterfactualRowCount > 0
    evidence = table( ...
        terminalFates.Technology(counterFateRows), ...
        terminalFates.TransmitterUeId(counterFateRows), ...
        terminalFates.ReceiverUeId(counterFateRows), ...
        terminalFates.PacketSequence(counterFateRows), ...
        counterfactualTrace.AttemptNumber, ...
        counterfactualTrace.InterfererUeId, ...
        counterfactualTrace.ResourceRelation, ...
        counterfactualTrace.ObservedSinrDb, ...
        counterfactualTrace.DecodeThresholdDb, ...
        counterfactualTrace.SinrWithoutInterfererDb, ...
        isHarmfulReuse, ...
        counterfactualTrace.SinrWithoutAllInterferersDb, ...
        VariableNames=string( ...
            emptyClassifierEvidence().Properties.VariableNames));
end

if any( ...
        counterfactualCount(attemptFateRows) ~= ...
        attemptTrace.InterfererCount)
    error( ...
        "v2xsim:analysis:RecordedInterferenceCountMismatch", ...
        "Attempt interferer counts must match joined " + ...
        "counterfactual rows.");
end

coverage = terminalFates(:,[ ...
    "Technology","TransmitterUeId","ReceiverUeId", ...
    "PacketSequence","AttemptNumber","Outcome"]);
coverage.HasAttemptEvidence = hasAttemptEvidence;
coverage.EvidenceIsExhaustive = evidenceIsExhaustive;
coverage.CounterfactualCount = counterfactualCount;
coverage.ExposedTerminalStatus = repmat( ...
    "shadow_predictions_required",fateCount,1);

classified = classifyByEvidenceCompleteness( ...
    terminalFates,evidence,counterFateRows, ...
    evidenceIsExhaustive);
exposedStatus = "shadow_predictions_required";
end

function keys = directedGenerationKeys(rows)
generationKeys = string(compose( ...
    "%.17g",rows.GenerationTimeSeconds));
keys = rows.Technology + "|" + ...
    rows.TransmitterUeId + "|" + ...
    rows.ReceiverUeId + "|" + generationKeys;
end

function keys = directedAttemptKeys(rows)
keys = directedGenerationKeys(rows) + "|" + ...
    string(compose("%.0f",rows.AttemptNumber));
end

function flags = harmfulReuseFlags( ...
        counterfactuals,reuseCandidates)
flags = false(height(counterfactuals),1);
if isempty(counterfactuals) || isempty(reuseCandidates)
    return
end
candidateKeys = reuseCandidateKeys(reuseCandidates);
if numel(unique(candidateKeys)) ~= numel(candidateKeys)
    error( ...
        "v2xsim:analysis:DuplicateReuseCandidateEvidence", ...
        "An allocation epoch may classify a UE pair once.");
end
counterfactualKeys = reuseCandidateKeys(counterfactuals);
[isKnown,candidateRows] = ismember( ...
    counterfactualKeys,candidateKeys);
flags(isKnown) = ...
    reuseCandidates.IsHarmfulInterferenceOverlap( ...
        candidateRows(isKnown)) & ...
    controllerToPhyRelation( ...
        reuseCandidates.LiveResourceRelation( ...
            candidateRows(isKnown))) == ...
    counterfactuals.ResourceRelation(isKnown);
end

function relation = controllerToPhyRelation(relation)
relation = string(relation);
relation(relation == "other_same_time") = "other";
end

function keys = reuseCandidateKeys(rows)
if ismember( ...
        "FirstUeId", ...
        string(rows.Properties.VariableNames))
    keys = string(compose("%.0f",rows.AllocationEpoch)) + "|" + ...
        rows.FirstUeId + "|" + rows.SecondUeId;
else
    keys = string(compose("%.0f",rows.AllocationEpoch)) + "|" + ...
        rows.ReusePairFirstUeId + "|" + ...
        rows.ReusePairSecondUeId;
end
end

function classified = classifyByEvidenceCompleteness( ...
        fates,evidence,evidenceFateRows,isExhaustive)
classified = v2xsim.analysis.classifyFailureModes( ...
    fates([],:),evidence([],:),EvidenceIsExhaustive=false);
if isempty(fates)
    return
end

parts = cell(0,1);
for exhaustiveValue = [false,true]
    fateRows = find(isExhaustive == exhaustiveValue);
    if isempty(fateRows)
        continue
    end
    evidenceRows = ismember(evidenceFateRows,fateRows);
    part = v2xsim.analysis.classifyFailureModes( ...
        fates(fateRows,:),evidence(evidenceRows,:), ...
        EvidenceIsExhaustive=exhaustiveValue);
    part.OriginalFateRow = fateRows;
    parts{end + 1,1} = part; %#ok<AGROW>
end
classified = vertcat(parts{:});
classified = sortrows(classified,"OriginalFateRow");
classified.OriginalFateRow = [];
end

function validateTraceSchema(actual,expected,label)
if ~isequal( ...
        string(actual.Properties.VariableNames), ...
        string(expected.Properties.VariableNames))
    error( ...
        "v2xsim:analysis:InvalidRecordedInterferenceTrace", ...
        "Recorded %s evidence has an invalid schema.",label);
end
end

function validateReuseCandidates(candidates)
requiredNames = [ ...
    "AllocationEpoch","NetworkSliceId", ...
    "FirstUeId","SecondUeId","CandidateType", ...
    "LiveResourceRelation","OracleResourceRelation", ...
    "IsHarmfulInterferenceOverlap", ...
    "IsMissedInterferenceOverlap"];
if isempty(candidates) && width(candidates) == 0
    return
end
if ~all(ismember( ...
        requiredNames, ...
        string(candidates.Properties.VariableNames)))
    error( ...
        "v2xsim:analysis:InvalidReuseCandidateEvidence", ...
        "Reuse-candidate evidence must contain epoch, canonical " + ...
        "UE pair, exact-resource type, live/oracle relation, and " + ...
        "interference-overlap direction.");
end
if isempty(candidates)
    % Header-only artifacts cannot preserve column storage types in CSV.
    % Required names are sufficient because there are no values to join.
    return
end
if ~isnumeric(candidates.AllocationEpoch) || ...
        ~iscolumn(candidates.AllocationEpoch) || ...
        any(~isfinite(candidates.AllocationEpoch)) || ...
        any(candidates.AllocationEpoch < 0) || ...
        any(fix(candidates.AllocationEpoch) ~= ...
            candidates.AllocationEpoch) || ...
        ~isstring(candidates.NetworkSliceId) || ...
        ~iscolumn(candidates.NetworkSliceId) || ...
        ~isstring(candidates.FirstUeId) || ...
        ~iscolumn(candidates.FirstUeId) || ...
        ~isstring(candidates.SecondUeId) || ...
        ~iscolumn(candidates.SecondUeId) || ...
        ~isstring(candidates.CandidateType) || ...
        ~iscolumn(candidates.CandidateType) || ...
        any(~ismember( ...
            candidates.CandidateType, ...
            ["harmful_reuse","missed_reuse", ...
            "unchanged_overlap","unchanged_separation"]))
    error( ...
        "v2xsim:analysis:InvalidReuseCandidateEvidence", ...
        "Reuse-candidate evidence must contain epoch, canonical " + ...
        "UE pair, and candidate type.");
end
stringNames = [ ...
    "NetworkSliceId","FirstUeId","SecondUeId", ...
    "CandidateType","LiveResourceRelation", ...
    "OracleResourceRelation"];
for variableName = stringNames
    values = candidates.(variableName);
    if ~isstring(values) || ~iscolumn(values) || ...
            any(ismissing(values)) || ...
            any(strlength(strip(values)) == 0) || ...
            any(values ~= strip(values))
        error( ...
            "v2xsim:analysis:InvalidReuseCandidateEvidence", ...
            "%s must contain nonblank string values.", ...
            variableName);
    end
end
if any(candidates.NetworkSliceId ~= "global")
    error( ...
        "v2xsim:analysis:UnsupportedReuseCandidateNetworkSlice", ...
        "Recorded PHY evidence is not slice-qualified; controller " + ...
        "candidate evidence must use the simulator's single global " + ...
        "network slice.");
end
if any(candidates.FirstUeId >= candidates.SecondUeId)
    error( ...
        "v2xsim:analysis:InvalidReuseCandidateEvidence", ...
        "Reuse-candidate UE pairs must be canonicalized.");
end
validRelations = [ ...
    "unassigned","separate_time","cochannel", ...
    "adjacent_channel","other_same_time"];
if any(~ismember( ...
        candidates.LiveResourceRelation,validRelations)) || ...
        any(~ismember( ...
            candidates.OracleResourceRelation,validRelations))
    error( ...
        "v2xsim:analysis:InvalidReuseCandidateEvidence", ...
        "LiveResourceRelation and OracleResourceRelation contain " + ...
        "an unsupported value.");
end
if ~isLogicalEncoding( ...
        candidates.IsHarmfulInterferenceOverlap) || ...
        ~isLogicalEncoding( ...
            candidates.IsMissedInterferenceOverlap)
    error( ...
        "v2xsim:analysis:InvalidReuseCandidateEvidence", ...
        "Interference-overlap direction flags must be logical or " + ...
        "binary numeric columns.");
end
liveSameResource = ...
    candidates.LiveResourceRelation == "cochannel";
oracleSameResource = ...
    candidates.OracleResourceRelation == "cochannel";
expectedCandidateType = repmat( ...
    "unchanged_separation",height(candidates),1);
expectedCandidateType( ...
    liveSameResource & oracleSameResource) = ...
    "unchanged_overlap";
expectedCandidateType( ...
    liveSameResource & ~oracleSameResource) = ...
    "harmful_reuse";
expectedCandidateType( ...
    ~liveSameResource & oracleSameResource) = ...
    "missed_reuse";
isHarmful = logical( ...
    candidates.IsHarmfulInterferenceOverlap);
isMissed = logical( ...
    candidates.IsMissedInterferenceOverlap);
isDirectionalExactCandidate = ismember( ...
    candidates.CandidateType, ...
    ["harmful_reuse","missed_reuse"]);
if any(candidates.CandidateType ~= expectedCandidateType) || ...
        any(isHarmful & isMissed) || ...
        any( ...
            ~(isDirectionalExactCandidate | ...
            isHarmful | isMissed))
    error( ...
        "v2xsim:analysis:InconsistentReuseCandidateEvidence", ...
        "Candidate type, resource relations, and overlap-direction " + ...
        "flags must describe one sparse allocation-pair transition.");
end
end

function valid = isLogicalEncoding(values)
valid = iscolumn(values) && ...
    (islogical(values) || ...
    (isnumeric(values) && ...
    all(isfinite(values)) && ...
    all(ismember(values,[0 1]))));
end

function evidence = emptyClassifierEvidence()
evidence = table( ...
    strings(0,1),strings(0,1),strings(0,1), ...
    zeros(0,1),zeros(0,1),strings(0,1),strings(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1), ...
    false(0,1),zeros(0,1), ...
    VariableNames=[ ...
        "Technology","TransmitterUeId","ReceiverUeId", ...
        "PacketSequence","AttemptNumber","InterfererUeId", ...
        "ResourceRelation","ObservedSinrDb","DecodeThresholdDb", ...
        "SinrWithoutInterfererDb","IsHarmfulReuseCandidate", ...
        "SinrWithoutAllInterferersDb"]);
end
