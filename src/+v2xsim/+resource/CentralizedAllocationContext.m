classdef CentralizedAllocationContext < ...
        v2xsim.resource.ResourceAllocationContext
    %CENTRALIZEDALLOCATIONCONTEXT Slice-wide observations for a controller.
    %   Pairwise matrices use the row and column order declared by UeIds.

    properties (SetAccess = immutable)
        X (:, 1) double = zeros(0, 1)
        EstimatedDistanceMeters (:, :) double = zeros(0, 0)
        TrueDistanceMeters (:, :) double = zeros(0, 0)
        ReceivedPowerWattsPerMHz (:, :) double = zeros(0, 0)
        ShadowingDecibels (:, :) double = zeros(0, 0)
    end

    methods
        function obj = CentralizedAllocationContext( ...
                networkSliceId, ueIds, currentSlot, ...
                newPacketMask, eligibilityMask, x, ...
                estimatedDistanceMeters, trueDistanceMeters, ...
                receivedPowerWattsPerMHz, shadowingDecibels, ...
                selectionOriginSlot)
            arguments (Input)
                networkSliceId (1, 1) v2xsim.network.NetworkSliceId
                ueIds string
                currentSlot (1, 1) double ...
                    {mustBeReal, mustBeFinite, mustBeInteger, ...
                    mustBeNonnegative}
                newPacketMask logical
                eligibilityMask (:, :) logical
                x double {mustBeReal, mustBeFinite}
                estimatedDistanceMeters (:, :) double {mustBeReal}
                trueDistanceMeters (:, :) double {mustBeReal}
                receivedPowerWattsPerMHz (:, :) double {mustBeReal}
                shadowingDecibels (:, :) double ...
                    {mustBeReal, mustBeFinite}
                selectionOriginSlot double = []
            end

            obj = obj@v2xsim.resource.ResourceAllocationContext( ...
                networkSliceId, ueIds, currentSlot, ...
                newPacketMask, eligibilityMask,selectionOriginSlot);

            if ~isvector(x) && ~isempty(x)
                error( ...
                    "v2xsim:resource:CentralizedContextSizeMismatch", ...
                    "X must be a vector with one value per UE.");
            end
            x = x(:);
            numberUes = numel(obj.UeIds);
            expectedMatrixSize = [numberUes, numberUes];
            if numel(x) ~= numberUes || ...
                    ~isequal(size(estimatedDistanceMeters), ...
                        expectedMatrixSize) || ...
                    ~isequal(size(trueDistanceMeters), ...
                        expectedMatrixSize) || ...
                    ~isequal(size(receivedPowerWattsPerMHz), ...
                        expectedMatrixSize) || ...
                    ~isequal(size(shadowingDecibels), expectedMatrixSize)
                error( ...
                    "v2xsim:resource:CentralizedContextSizeMismatch", ...
                    "Centralized observations must align with UeIds.");
            end

            nonnegativeMatrices = { ...
                estimatedDistanceMeters, ...
                trueDistanceMeters, ...
                receivedPowerWattsPerMHz};
            for index = 1:numel(nonnegativeMatrices)
                matrix = nonnegativeMatrices{index};
                if any(isnan(matrix), "all") || ...
                        any(matrix < 0, "all")
                    error( ...
                        "v2xsim:resource:InvalidCentralizedObservation", ...
                        "Distances and received powers must be " + ...
                        "nonnegative and cannot contain NaN.");
                end
            end

            obj.X = x;
            obj.EstimatedDistanceMeters = estimatedDistanceMeters;
            obj.TrueDistanceMeters = trueDistanceMeters;
            obj.ReceivedPowerWattsPerMHz = receivedPowerWattsPerMHz;
            obj.ShadowingDecibels = shadowingDecibels;
        end
    end
end
