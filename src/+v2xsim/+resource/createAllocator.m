function allocator = createAllocator(plan, grid, options)
%CREATEALLOCATOR Compose one allocator from a compiled V7 simulation plan.
%   CREATEALLOCATOR(PLAN, GRID) is the only allocator-selection branch in
%   the runtime. It consumes resolved V7 domains and has no dependency on
%   legacy simParams, phyParams, or appParams structures.

arguments (Input)
    plan (1, 1) v2xsim.runtime.CompiledSimulationPlan
    grid (1, 1) v2xsim.resource.BRResourceGrid
    options.ReuseDistanceMeters = []
end

allocationPlan = plan.ResourceAllocation;
allocationType = allocationPlan.Type;
randomSeed = allocationPlan.RandomSeed;
reservationIntervalSeconds = ...
    plan.Application.ResourceReservationIntervalSeconds;

switch allocationType
    case "ReuseDistance"
        branch = allocationPlan.ReuseDistance;
        reassignmentCycleCount = cycleCount( ...
            branch.ReassignmentIntervalSeconds, ...
            reservationIntervalSeconds);
        if isempty(options.ReuseDistanceMeters)
            reuseDistanceMeters = ...
                v2xsim.resource.deriveReuseDistanceMeters( ...
                    plan.Radio, plan.Channel, plan.Awareness, ...
                    branch.ReuseMarginMeters);
        else
            reuseDistanceMeters = ...
                validateReuseDistance(options.ReuseDistanceMeters);
        end
        allocator = v2xsim.resource.ReuseDistanceAllocator( ...
            grid, randomSeed, reassignmentCycleCount, ...
            reuseDistanceMeters);
    case "MaximumReuseDistance"
        branch = allocationPlan.MaximumReuseDistance;
        reassignmentCycleCount = cycleCount( ...
            branch.ReassignmentIntervalSeconds, ...
            reservationIntervalSeconds);
        allocator = ...
            v2xsim.resource.MaximumReuseDistanceAllocator( ...
                grid, randomSeed, reassignmentCycleCount, ...
                DiagnosticsEnabled= ...
                    plan.Outputs.ControllerDiagnostics.Enabled);
    case "MinimumReusePower"
        branch = allocationPlan.MinimumReusePower;
        reassignmentCycleCount = cycleCount( ...
            branch.ReassignmentIntervalSeconds, ...
            reservationIntervalSeconds);
        allocator = v2xsim.resource.MinimumReusePowerAllocator( ...
            grid, randomSeed, reassignmentCycleCount, ...
            branch.KnownShadowingEnabled);
    case "SensingBased"
        branch = allocationPlan.SensingBased;
        [minimumCounter, maximumCounter] = ...
            reselectionCounterRange( ...
                reservationIntervalSeconds, branch);
        sensingThresholdWatts = sensingThreshold( ...
            branch.SensingThresholdDbm);
        if branch.KeepResourceProbability > 0.8
            warning( ...
                "v2xsim:resource:NonstandardKeepProbability", ...
                "3GPP specifies a keep probability no greater than 0.8.");
        end
        allocator = v2xsim.resource.ThreeGppAutonomousAllocator( ...
            grid, randomSeed, ...
            plan.Radio.Sidelink.MaximumTransmissionCount, ...
            MinimumReselectionCounter=minimumCounter, ...
            MaximumReselectionCounter=maximumCounter, ...
            KeepResourceProbability= ...
                branch.KeepResourceProbability, ...
            MaximumConsecutiveReservationIntervals= ...
                branch.MaximumConsecutiveReservationIntervals, ...
            MinimumCandidateFraction= ...
                branch.MinimumCandidateFraction, ...
            L2CandidateFraction=branch.L2CandidateFraction, ...
            L2RankingEnabled=branch.L2RankingEnabled, ...
            DynamicSchedulingEnabled= ...
                branch.ReselectEveryPacketEnabled, ...
            ResourceReevaluationEnabled= ...
                branch.ReevaluationEnabled, ...
            ReevaluateAfterSkippedTransmissionEnabled= ...
                branch.ReevaluateAfterSkippedTransmissionEnabled, ...
            SensingThresholdWatts=sensingThresholdWatts, ...
            IsNr=isNrSidelink(plan.Radio));
    case "Random"
        allocator = v2xsim.resource.RandomBenchmarkAllocator( ...
            grid, randomSeed, ...
            plan.Radio.Sidelink.MaximumTransmissionCount);
    case "Ordered"
        allocator = v2xsim.resource.OrderedBenchmarkAllocator( ...
            grid, randomSeed);
    otherwise
        error( ...
            "v2xsim:resource:UnknownAllocatorType", ...
            "Unknown resource allocator type ""%s"".", ...
            allocationType);
end
end

function result = validateReuseDistance(value)
if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
        ~isfinite(value) || value <= 0
    error( ...
        "v2xsim:resource:InvalidReuseDistance", ...
        "ReuseDistanceMeters must be one finite positive number.");
end
result = double(value);
end

function result = cycleCount( ...
        reassignmentIntervalSeconds, reservationIntervalSeconds)
ratio = reassignmentIntervalSeconds / reservationIntervalSeconds;
result = round(ratio);
tolerance = 16 * eps(max(1, abs(ratio)));
if reassignmentIntervalSeconds <= 0 || ...
        abs(ratio - result) > tolerance
    error( ...
        "v2xsim:resource:NonIntegralInterval", ...
        "ReassignmentIntervalSeconds must be a positive exact " + ...
        "multiple of %.15g seconds.", reservationIntervalSeconds);
end
end

function [minimumCounter, maximumCounter] = ...
        reselectionCounterRange(reservationIntervalSeconds, branch)
if reservationIntervalSeconds >= 0.1
    minimumCounter = 5;
    maximumCounter = 15;
elseif reservationIntervalSeconds >= 0.05
    minimumCounter = 10;
    maximumCounter = 30;
else
    minimumCounter = 25;
    maximumCounter = 75;
end

if isfield(branch, "ReselectionCounterMinimum")
    minimumCounter = branch.ReselectionCounterMinimum;
end
if isfield(branch, "ReselectionCounterMaximum")
    maximumCounter = branch.ReselectionCounterMaximum;
end
if maximumCounter <= minimumCounter
    error( ...
        "v2xsim:resource:InvalidReselectionCounter", ...
        "The maximum reselection counter must exceed the minimum.");
end
end

function result = sensingThreshold(thresholdDbm)
if thresholdDbm < -128 || thresholdDbm > -2 || ...
        mod(thresholdDbm, 2) ~= 0
    error( ...
        "v2xsim:resource:InvalidSensingThreshold", ...
        "SensingThresholdDbm must be from -128 to -2 in 2 dB steps.");
end
result = db2pow(thresholdDbm - 30);
end

function result = isNrSidelink(radioPlan)
result = radioPlan.Type == "NrV2X" || ...
    (radioPlan.Type == "Coexistence" && ...
    radioPlan.Coexistence.SidelinkType == "NrV2X");
end
