function coexistence = buildCoexistence( ...
        simParams, phyParams, sinrManagement)
technology = requiredField(simParams, "technology");
active = ismember(technology, [3, 4]);
sharedChannel = technology == 4;
methodCode = conditionalField( ...
    simParams, "coexMethod", sharedChannel);
slotCode = conditionalField( ...
    simParams, "coex_slotManagement", ...
    sharedChannel && methodCode ~= 0);
staticSlotManagement = sharedChannel && slotCode == 1;

effectiveStaticCellularDuration = fieldOr( ...
    simParams, "coex_endOfLTE", NaN);
if staticSlotManagement && methodCode == 3 && ...
        isfield(sinrManagement, "coex_NtotSubframeLTE")
    subframeCounts = sinrManagement.coex_NtotSubframeLTE;
    if ~isempty(subframeCounts)
        effectiveStaticCellularDuration = ...
            subframeCounts(1) * fieldOr(phyParams, "Tsf", NaN);
    end
end

perceivedEnd = NaN;
perceivedEndMode = "NotApplicable";
if sharedChannel && methodCode == 1
    configuredPerceivedEnd = fieldOr( ...
        simParams, "coexA_endOfLteKnownBy11p", -1);
    if configuredPerceivedEnd == -1
        perceivedEnd = effectiveStaticCellularDuration;
        perceivedEndMode = "EffectiveCellularSidelinkBoundary";
    else
        perceivedEnd = configuredPerceivedEnd;
        perceivedEndMode = "Explicit";
    end
end

methodA = struct( ...
    "Enabled", sharedChannel && methodCode == 1, ...
    "GuardTimeSeconds", conditionalField( ...
        simParams, "coexA_guardTime", methodCode == 1), ...
    "EnhancementVariant", conditionalField( ...
        simParams, "coexA_improvements", methodCode == 1), ...
    "DesynchronizationErrorSeconds", conditionalField( ...
        simParams, "coexA_desynchError", methodCode == 1), ...
    "Ieee80211pPerceivedCellularSidelinkEndSeconds", perceivedEnd, ...
    "Ieee80211pPerceivedCellularSidelinkEndMode", ...
        perceivedEndMode, ...
    "LegacyIeee80211pNodesEnabled", conditionalField( ...
        simParams, "coexA_withLegacyITSG5", methodCode == 1));
methodB = struct( ...
    "Enabled", sharedChannel && methodCode == 2, ...
    "EnergySignalLeadTimeSeconds", conditionalField( ...
        simParams, "coexB_timeBeforeLTEstarts", methodCode == 2), ...
    "AllVehiclesTransmitInEmptySubframes", conditionalField( ...
        simParams, "coexB_allToTransmitInEmptySF", methodCode == 2));
methodC = struct( ...
    "Enabled", sharedChannel && methodCode == 3, ...
    "TimeGapVariant", conditionalField( ...
        simParams, "coexC_timegapVariant", methodCode == 3), ...
    "Ieee80211pDetectionEnabled", conditionalField( ...
        simParams, "coexC_11pDetection", methodCode == 3), ...
    "ModifiedContentionWindowEnabled", conditionalField( ...
        simParams, "coexCmodifiedCW", methodCode == 3), ...
    "MultipleSubframeIndicationEnabled", conditionalField( ...
        simParams, "coexC_moreThanOneSubframe", methodCode == 3));
methodF = struct( ...
    "Enabled", sharedChannel && methodCode == 6, ...
    "GuardTimeEnabled", conditionalField( ...
        simParams, "coexF_guardTime", methodCode == 6));

coexistence = struct( ...
    "Active", active, ...
    "InterferenceMode", coexistenceInterferenceMode(technology), ...
    "CellularSidelinkVehicleGroupSize", conditionalField( ...
        simParams, "numVehiclesLTE", active), ...
    "Ieee80211pVehicleGroupSize", conditionalField( ...
        simParams, "numVehicles11p", active), ...
    "MethodCode", methodCode, ...
    "Method", coexistenceMethodName(methodCode, sharedChannel), ...
    "SlotManagementCode", slotCode, ...
    "SlotManagement", slotManagementName(slotCode), ...
    "SuperframeDurationSeconds", conditionalField( ...
        simParams, "coex_superFlength", sharedChannel), ...
    "EffectiveStaticCellularSidelinkDurationSeconds", ...
        conditionalValue( ...
            effectiveStaticCellularDuration, ...
            staticSlotManagement), ...
    "CellularSidelinkCbrVariant", conditionalField( ...
        simParams, "coex_cbrLteVariant", sharedChannel), ...
    "CombinedCbrVariant", conditionalField( ...
        simParams, "coex_cbrTotVariant", sharedChannel), ...
    "MethodA", methodA, ...
    "MethodB", methodB, ...
    "MethodC", methodC, ...
    "MethodF", methodF);
end

