obstacleMapEnabled = logical(fieldOr( ...
    simParams, "fileObstaclesMap", false));

limits = struct( ...
    "MinimumXMeters", fieldOr(simParams, "XminTrace", NaN), ...
    "MaximumXMeters", fieldOr(simParams, "XmaxTrace", NaN), ...
    "MinimumYMeters", fieldOr(simParams, "YminTrace", NaN), ...
    "MaximumYMeters", fieldOr(simParams, "YmaxTrace", NaN));
obstacleMap = struct( ...
    "Enabled", obstacleMapEnabled, ...
    "File", textField(simParams, "filenameObstaclesMap", ""));

scenario = struct;
scenario.Type = textField(simParams, "typeOfScenario", "");
scenario.PositionLimitsMeters = limits;
scenario.ObstacleMap = obstacleMap;
scenario.Options = buildScenarioOptions(simParams);
end

function positioning = buildPositioning(simParams, cellularConfigured)
allocatorType = string(fieldOr( ...
    simParams, "resourceAllocationType", ""));
positionUpdateAvailable = cellularConfigured && ...
    allocatorType == "ReuseDistance";
positioning = struct( ...
    "SnapshotIntervalSeconds", ...
        requiredField(simParams, "positionTimeResolution"), ...
    "ControlledPositioningEnabled", positionUpdateAvailable, ...
    "PositionError95PercentileMeters", conditionalField( ...
        simParams, "posError95", positionUpdateAvailable), ...
    "UpdateIntervalSeconds", conditionalField( ...
        simParams, "Tupdate", positionUpdateAvailable), ...
    "UpdateIntervalExceedsSimulationDuration", ...
        positionUpdateAvailable && ...
        simParams.Tupdate > simParams.simulationTime);
positioning.ErrorChain = buildPositionErrorChain(simParams);
end

function options = buildScenarioOptions(simParams)
options = struct;
if ~isfield(simParams, "scenarioOptions") || ...
        ~isstruct(simParams.scenarioOptions)
    return
end

configuredOptions = simParams.scenarioOptions;
optionNames = [ ...
    "RandomSeed", "VehicleCount", "SimulationAreaSize", ...
    "MeanVehicleSpeed", "VehicleSpeedStandardDeviation", ...
    "NLanes", "LaneWidth", "RoadLength", ...
    "CentralDividerWidth", "RerollSpeedOnWrapAround", ...
    "TrafficModel", "Placement", "MinimumRoadLength", ...
    "ExitProbability", "MergeDistance"];
for optionName = optionNames
    if ~isfield(configuredOptions, optionName)
        continue
    end
    value = configuredOptions.(optionName);
    if isenum(value)
        value = string(value);
    end
    options.(optionName) = value;
end
end

function errorChain = buildPositionErrorChain(simParams)
moduleNames = string(fieldOr( ...
    simParams, "positionErrorModuleNames", strings(1, 0)));
moduleNames = reshape(moduleNames, 1, []);
configuredOptions = fieldOr( ...
    simParams, "positionErrorOptions", struct);
modules = cell(1, numel(moduleNames));
for moduleIndex = 1:numel(moduleNames)
    moduleName = moduleNames(moduleIndex);
    moduleOptions = struct;
    if isfield(configuredOptions, moduleName)
        moduleOptions = configuredOptions.(moduleName);
    end
    if moduleName == "Delay"
        modules{moduleIndex} = struct( ...
            "Index", moduleIndex, ...
            "Type", "PositionDelayError", ...
            "Options", moduleOptions);
        continue
    end

    statusEffectTypes = struct( ...
        "Gaussian", ...
            "IsotropicGaussianPositionErrorStatusEffect", ...
        "FalseExit", ...
            "FalseExitPositionErrorStatusEffect", ...
        "FalseMerge", ...
            "FalseMergePositionErrorStatusEffect");
    if ~isfield(statusEffectTypes, moduleName)
        error( ...
            "v2xsim:output:UnknownPositionErrorModule", ...
            "Cannot summarize position error module type ""%s"".", ...
            moduleName);
    end
    statusEffect = struct( ...
        "Type", statusEffectTypes.(moduleName), ...
        "Options", moduleOptions);
    modules{moduleIndex} = struct( ...
        "Index", moduleIndex, ...
        "Type", "PositionErrorStatusEffectInflictor", ...
        "StatusEffect", statusEffect);
end
errorChain = struct( ...
    "Enabled", ~isempty(moduleNames), ...
    "Modules", {modules});
end

function packetGeneration = buildPacketGeneration( ...
        appParams, cellularConfigured)
variability = requiredField( ...
    appParams, "variabilityGenerationInterval");
if variability == -1
    mode = "EtsiCam";
elseif variability == 0
    mode = "Periodic";
else
    mode = "PerVehicleUniformJitter";
end

camDiscretizationActive = variability == -1 && ...
    isfield(appParams, "camDiscretizationType") && ...
    ~strcmpi(string(appParams.camDiscretizationType), "null");
camDiscretization = struct( ...
    "Enabled", camDiscretizationActive, ...
    "Type", conditionalTextField( ...
        appParams, "camDiscretizationType", ...
        camDiscretizationActive), ...
    "MaximumIntervalIncreasePercent", conditionalField( ...
        appParams, "camDiscretizationIncrease", ...
        camDiscretizationActive));

packetGeneration = struct;
packetGeneration.Mode = mode;
packetGeneration.AllocationPeriodSeconds = ...
    requiredField(appParams, "allocationPeriod");
packetGeneration.PacketSizeBytes = ...
    requiredField(appParams, "beaconSizeBytes");
packetGeneration.CellularSidelinkResourcePercentage = ...
    conditionalField(appParams, "resourcesV2V", cellularConfigured);
packetGeneration.DeterministicIntervalSeconds = ...
    requiredField(appParams, "generationInterval");
packetGeneration.MeanRandomAdditionalIntervalSeconds = ...
    requiredField(appParams, "generationIntervalAverageRandomPart");
packetGeneration.UniformJitterSpanSeconds = conditionalValue( ...
    variability, variability > 0);
packetGeneration.UniformJitterHalfWidthSeconds = conditionalValue( ...
    variability / 2, variability > 0);
packetGeneration.CamDiscretization = camDiscretization;
end

function resourcePool = buildResourcePool( ...
        simParams, appParams, phyParams, cellularConfigured)
