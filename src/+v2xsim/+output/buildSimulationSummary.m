function summary = buildSimulationSummary( ...
        stationManagement, simParams, appParams, phyParams, ...
        sinrManagement, outParams, outputValues)
%BUILDSIMULATIONSUMMARY Build the versioned semantic simulation summary.
%   This function is pure apart from recording the current UTC completion
%   time. It preserves the simulator's existing KPI calculations while
%   representing configuration and results as typed, nested data.

arguments (Input)
    stationManagement (1, 1) struct
    simParams (1, 1) struct
    appParams (1, 1) struct
    phyParams (1, 1) struct
    sinrManagement (1, 1) struct
    outParams (1, 1) struct
    outputValues (1, 1) struct
end

summary = struct;
summary.SchemaVersion = 2;
summary.Run = buildRun(simParams, outParams, outputValues);
summary.Configuration = buildConfiguration( ...
    simParams, appParams, phyParams, sinrManagement);
summary.Results = buildResults( ...
    stationManagement, simParams, phyParams, outputValues);
end

function run = buildRun(simParams, outParams, outputValues)
completedAt = datetime( ...
    "now", TimeZone="UTC", ...
    Format="uuuu-MM-dd'T'HH:mm:ss.SSS'Z'");

run = struct( ...
    "SimulatorVersion", simulatorVersion(simParams), ...
    "CompletedAtUtc", string(completedAt), ...
    "RunLabel", textField(outParams, "message", ""), ...
    "RandomSeed", requiredField(simParams, "seed"), ...
    "SimulatedDurationSeconds", ...
        requiredField(simParams, "simulationTime"), ...
    "ComputationDurationSeconds", ...
        requiredField(outputValues, "computationTime"), ...
    "ConfigurationFile", textField(simParams, "fileCfg", ""));
end

function configuration = buildConfiguration( ...
        simParams, appParams, phyParams, sinrManagement)
technology = requiredField(simParams, "technology");
cellularConfigured = technology ~= 2;
ieee80211pConfigured = technology ~= 1;

configuration = struct;
configuration.RadioAccessMode = radioAccessMode(simParams);
configuration.Scenario = buildScenario(simParams);
configuration.Infrastructure = struct( ...
    "RoadSideUnitCount", fieldOr(appParams, "nRSUs", 0));
configuration.Positioning = buildPositioning( ...
    simParams, cellularConfigured);
configuration.Application = struct( ...
    "PacketGeneration", buildPacketGeneration( ...
        appParams, cellularConfigured));
configuration.ResourcePool = buildResourcePool( ...
    simParams, appParams, phyParams, cellularConfigured);
configuration.Radio = buildRadio(phyParams);
configuration.CellularSidelink = buildCellularConfiguration( ...
    simParams, phyParams, cellularConfigured);
configuration.Ieee80211p = buildIeee80211pConfiguration( ...
    phyParams, ieee80211pConfigured);
configuration.Channel = buildChannel( ...
    simParams, phyParams, cellularConfigured, ieee80211pConfigured);
configuration.Coexistence = buildCoexistence( ...
    simParams, phyParams, sinrManagement);
configuration.ResourceAllocation = buildResourceAllocation( ...
    simParams, cellularConfigured);
configuration.Awareness = struct;
configuration.Awareness.RangesMeters = num2cell( ...
    rowVector(requiredField(phyParams, "Raw")));
end

