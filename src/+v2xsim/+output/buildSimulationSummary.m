    value = string(simParams.SimulatorVersion);
elseif isfield(simParams, "CheckVersion")
    value = string(simParams.CheckVersion);
elseif exist("constants", "class") == 8
    value = string(constants.SIM_VERSION);
else
    % Keep the pure builder usable with only src on the path. Simulator
    % integration takes the constants branch above.
    value = "V7";
end
end

