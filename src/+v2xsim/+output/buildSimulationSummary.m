    appParams, "RBsBeacon", cellularConfigured);
if isLte
    physicalResourceBlockCount = resourceBlockUnits / 2;
else
    physicalResourceBlockCount = resourceBlockUnits;
end

resourcePool = struct( ...
    "Active", cellularConfigured, ...
    "BeaconResourceCount", conditionalField( ...
        appParams, "Nbeacons", cellularConfigured), ...
    "BeaconResourceBlockUnits", resourceBlockUnits, ...
    "PhysicalResourceBlockCount", physicalResourceBlockCount, ...
    "SubchannelCount", conditionalField( ...
        phyParams, "NsubchannelsBeacon", cellularConfigured), ...
    "PhysicalResourceBlocksPerSubchannel", conditionalField( ...
        phyParams, "sizeSubchannel", cellularConfigured), ...
    "AdjacentPscchAndPsschEnabled", conditionalField( ...
        phyParams, "ifAdjacent", isLte));
end

function radio = buildRadio(phyParams)
channelCount = fieldOr(phyParams, "nChannels", 1);
proportions = fieldOr( ...
    phyParams, "propVehiclesChannels", defaultChannelProportions( ...
        channelCount));
powerDeltas = fieldOr( ...
    phyParams, "mcoPowerDeltaChannels", zeros(1, channelCount));
channels = cell(1, channelCount);
for channelIndex = 1:channelCount
    channels{channelIndex} = struct( ...
        "ChannelIndex", channelIndex, ...
        "ConfiguredVehicleFraction", ...
            indexedValue(proportions, channelIndex), ...
        "TransmitPowerDeltaDb", ...
            indexedValue(powerDeltas, channelIndex));
end

radio = struct;
radio.BandwidthMegahertz = requiredField(phyParams, "BwMHz");
radio.TransmitPowerDbm = requiredField(phyParams, "Ptx_dBm");
radio.FixedPowerDensity = logical(fieldOr( ...
    phyParams, "FixedPdensity", false));
radio.NoisePowerDensityDbmPerMegahertz = ...
    requiredField(phyParams, "Pnoise_MHz_dBm");
radio.ReceiverNoiseFigureDb = requiredField(phyParams, "F_dB");
radio.TransmitterAntennaGainDb = requiredField(phyParams, "Gt_dB");
radio.ReceiverAntennaGainDb = requiredField(phyParams, "Gr_dB");
radio.Channels = channels;
end

function configuration = buildCellularConfiguration( ...
        simParams, phyParams, active)
mode = fieldOr(simParams, "mode5G", NaN);
isLte = active && mode == 0;
isNr = active && mode == 1;
if isLte
    technology = "LTE-V2X";
    subcarrierSpacing = 15;
    mcs = fieldOr(phyParams, "MCS_LTE", NaN);
elseif isNr
    technology = "NR-V2X";
    subcarrierSpacing = fieldOr(phyParams, "SCS_NR", NaN);
    mcs = fieldOr(phyParams, "MCS_NR", NaN);
else
    technology = "";
    subcarrierSpacing = NaN;
    mcs = NaN;
end

duplex = conditionalTextField(phyParams, "duplexCV2X", active);
isFullDuplex = active && duplex == "FD";
residualSelfInterferenceDb = fieldOr( ...
    phyParams, "Ksi_dB", NaN);
selfInterferenceThresholdMultiplier = fieldOr( ...
    phyParams, "PDelta", NaN);
configuration = struct( ...
    "Active", active, ...
    "Technology", technology, ...
    "SubcarrierSpacingKilohertz", subcarrierSpacing, ...
    "ModulationAndCodingScheme", mcs, ...
    "PowerDensityDbmPerMegahertz", conditionalField( ...
        phyParams, "P_ERP_MHz_CV2X_dBm", active), ...
    "DuplexMode", duplex, ...
    "FullDuplexEnabled", isFullDuplex, ...
    "ResidualSelfInterferenceDb", conditionalValue( ...
        residualSelfInterferenceDb, isFullDuplex), ...
    "ResidualSelfInterferenceMode", ...
        residualSelfInterferenceMode( ...
            residualSelfInterferenceDb, isFullDuplex), ...
    "SelfInterferenceThresholdMultiplier", conditionalValue( ...
        selfInterferenceThresholdMultiplier, isFullDuplex), ...
    "SelfInterferenceThresholdMultiplierMode", ...
        selfInterferenceThresholdMultiplierMode( ...
            selfInterferenceThresholdMultiplier, isFullDuplex), ...
    "SelfInterferenceThresholdAdjustmentEnabled", ...
        isFullDuplex && ...
        residualSelfInterferenceDb < Inf && ...
        selfInterferenceThresholdMultiplier < Inf);
end

