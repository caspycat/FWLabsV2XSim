function results = buildResults( ...
        stationManagement, simParams, phyParams, outputValues)
ranges = rowVector(requiredField(phyParams, "Raw"));
cellularActive = requiredField(outputValues, "AvgNUEsCV2X") > 0;
ieee80211pActive = requiredField(outputValues, "AvgNUEs11p") > 0;
combinedActive = requiredField(outputValues, "AvgNUEsTOT") > 0;

cellular = struct;
cellular.Active = cellularActive;
cellular.AverageUeCount = requiredField( ...
    outputValues, "AvgNUEsCV2X");
if cellularActive
    cellular.AwarenessRangeMetrics = buildAwarenessMetrics( ...
        ranges, ...
        requiredField(outputValues, "NneighborsCV2X"), ...
        requiredField(outputValues, "StDevNeighboursCV2X"), ...
        requiredField(outputValues, "NtxBeaconsCV2X"), ...
        requiredField(outputValues, "blockingRateCV2X"), ...
        requiredField(outputValues, "errorRateCV2X"), ...
        requiredField(outputValues, "packetReceptionRatioCV2X"), ...
        "MeanSnapshotNeighborCountStandardDeviation");
else
    cellular.AwarenessRangeMetrics = cell(1, 0);
end
cellular.AverageSuccessfulReassignmentsPerUePerSecond = ...
    conditionalValue( ...
        requiredField(outputValues, "NreassignCV2X"), cellularActive);
cellular.AverageInitialTransmissionsPerUePerSecond = ...
    conditionalValue( ...
        requiredField(outputValues, "cv2xTransmissionsFirst") / ...
        (requiredField(outputValues, "AvgNUEsCV2X") * ...
        requiredField(simParams, "simulationTime")), ...
        cellularActive);
cellular.AverageTransmissionsPerPacketIncludingHarq = ...
    conditionalValue( ...
        requiredField(outputValues, "cv2xTransmissionsIncHarq") / ...
        requiredField(outputValues, "cv2xTransmissionsFirst"), ...
        cellularActive);
cellular.ChannelBusyRatio = buildChannelBusyRatio( ...
    stationManagement, simParams, phyParams, ...
    "CellularSidelink", cellularActive);

ieee80211p = struct;
ieee80211p.Active = ieee80211pActive;
ieee80211p.AverageUeCount = requiredField( ...
    outputValues, "AvgNUEs11p");
if ieee80211pActive
    ieee80211p.AwarenessRangeMetrics = buildAwarenessMetrics( ...
        ranges, ...
        requiredField(outputValues, "Nneighbors11p"), ...
        requiredField(outputValues, "StDevNeighbours11p"), ...
        requiredField(outputValues, "NtxBeacons11p"), ...
        requiredField(outputValues, "blockingRate11p"), ...
        requiredField(outputValues, "errorRate11p"), ...
        requiredField(outputValues, "packetReceptionRatio11p"), ...
        "MeanSnapshotNeighborCountStandardDeviation");
else
    ieee80211p.AwarenessRangeMetrics = cell(1, 0);
end
firstRange = ranges(1);
ieee80211pOpportunities = requiredField( ...
    outputValues, "NtxBeacons11p");
averageOpportunityRate = conditionalValue( ...
    sum(ieee80211pOpportunities(:, :, 1), "all") / ...
    (requiredField(outputValues, "AvgNUEs11p") * ...
    indexedValue(requiredField(outputValues, "Nneighbors11p"), 1) * ...
    requiredField(simParams, "simulationTime")), ...
    ieee80211pActive);
ieee80211p.AverageTransmissionOpportunityRate = struct( ...
    "AwarenessRangeLowerBoundMeters", 0, ...
    "AwarenessRangeUpperBoundMeters", firstRange, ...
    "PerUePerNeighborPerSecond", averageOpportunityRate);
ieee80211p.ChannelBusyRatio = buildChannelBusyRatio( ...
    stationManagement, simParams, phyParams, ...
    "Ieee80211p", ieee80211pActive);

combined = struct;
combined.Active = combinedActive;
combined.AverageUeCount = requiredField( ...
    outputValues, "AvgNUEsTOT");
if combinedActive
    combined.AwarenessRangeMetrics = buildAwarenessMetrics( ...
        ranges, ...
        requiredField(outputValues, "NneighborsTOT"), ...
        requiredField(outputValues, "StDevNeighboursTOT"), ...
        requiredField(outputValues, "NtxBeaconsTOT"), ...
        requiredField(outputValues, "blockingRateTOT"), ...
        requiredField(outputValues, "errorRateTOT"), ...
        requiredField(outputValues, "packetReceptionRatioTOT"), ...
        "MeanSnapshotSumOfTechnologyNeighborCountStandardDeviations");
else
    combined.AwarenessRangeMetrics = cell(1, 0);
end
combined.ChannelBusyRatio = emptyChannelBusyRatio("NotApplicable");

results = struct( ...
    "CellularSidelink", cellular, ...
    "Ieee80211p", ieee80211p, ...
    "Combined", combined);
end

function metrics = buildAwarenessMetrics( ...
        ranges, neighborCounts, dispersions, opportunities, ...
        blockingRates, errorRates, receptionRatios, dispersionField)
metrics = cell(1, numel(ranges));
lowerBound = 0;
for index = 1:numel(ranges)
    metric = struct( ...
        "AwarenessRangeLowerBoundMeters", lowerBound, ...
        "AwarenessRangeUpperBoundMeters", ranges(index), ...
        "AverageNeighborCount", indexedValue( ...
            neighborCounts, index), ...
        "NonblockedTransmitterReceiverOpportunityCount", ...
            sum(opportunities(:, :, index), "all"), ...
        "BlockingRate", indexedValue(blockingRates, index), ...
        "ErrorRate", indexedValue(errorRates, index), ...
        "PacketReceptionRatio", indexedValue( ...
            receptionRatios, index));
    metric.(dispersionField) = indexedValue(dispersions, index);
    metrics{index} = metric;
    lowerBound = ranges(index);
end
end

function result = buildChannelBusyRatio( ...
        stationManagement, simParams, phyParams, technology, active)
discardedSampleCount = 10;
if ~active
    result = emptyChannelBusyRatio("NotApplicable");
    return
end
if ~logical(fieldOr(simParams, "cbrActive", false))
    result = emptyChannelBusyRatio("Disabled");
    return
end

channelCount = fieldOr(phyParams, "nChannels", 1);
vehicleStates = fieldOr(stationManagement, "vehicleState", []);
vehicleChannels = fieldOr(stationManagement, "vehicleChannel", []);
if technology == "CellularSidelink"
    eligibleVehicles = vehicleStates == 100;
    values = fieldOr(stationManagement, "cbrCV2Xvalues", []);
    dccFlags = fieldOr( ...
        stationManagement, "dccLteTriggered", ...
        false(1, channelCount));
    harqFlags = fieldOr( ...
        stationManagement, "dccLteTriggeredHarq", ...
        false(1, channelCount));
else
    eligibleVehicles = vehicleStates ~= 100;
    values = fieldOr(stationManagement, "cbr11pValues", []);
    dccFlags = fieldOr( ...
        stationManagement, "dcc11pTriggered", ...
        false(1, channelCount));
    harqFlags = nan(1, channelCount);
end

if ~any(eligibleVehicles)
    channels = emptyCbrChannels( ...
        channelCount, dccFlags, harqFlags, "NoEligibleUes");
    result = channelBusyRatio( ...
        "NoEligibleUes", discardedSampleCount, channels);
    return
end
if size(values, 2) <= discardedSampleCount
    channels = emptyCbrChannels( ...
        channelCount, dccFlags, harqFlags, ...
        "InsufficientSamples");
    result = channelBusyRatio( ...
        "InsufficientSamples", discardedSampleCount, channels);
    return
end

channels = emptyCbrChannels( ...
    channelCount, dccFlags, harqFlags, "NoValidSamples");
hasAnyValidSample = false;
for channelIndex = 1:channelCount
    rows = eligibleVehicles & vehicleChannels == channelIndex;
    channelValues = values(rows, discardedSampleCount + 1:end);
    channelValues = channelValues(:);
    channelValues = channelValues(channelValues >= 0);
    if isempty(channelValues)
        medianRatio = NaN;
    else
        medianRatio = median(channelValues);
        channels{channelIndex}.Status = "Available";
        hasAnyValidSample = true;
    end
    channels{channelIndex}.MedianRatio = medianRatio;
end
if hasAnyValidSample
    status = "Available";
else
    status = "NoValidSamples";
end
result = channelBusyRatio( ...
    status, discardedSampleCount, channels);
end

function result = emptyChannelBusyRatio(status)
result = channelBusyRatio(status, 0, cell(1, 0));
end

function result = channelBusyRatio(status, warmupSampleCount, channels)
result = struct;
result.Status = status;
result.WarmupSampleCountRequired = warmupSampleCount;
result.Channels = channels;
end

function channels = emptyCbrChannels( ...
        channelCount, dccFlags, harqFlags, status)
channels = cell(1, channelCount);
for channelIndex = 1:channelCount
    channels{channelIndex} = struct( ...
        "ChannelIndex", channelIndex, ...
        "Status", status, ...
        "MedianRatio", NaN, ...
        "CongestionControlTriggered", ...
            logical(indexedValue(dccFlags, channelIndex)), ...
        "HarqCongestionControlTriggered", ...
            indexedValue(harqFlags, channelIndex));
end
end

function value = requiredField(source, name)
if ~isfield(source, name)
    error( ...
        "v2xsim:output:MissingSummaryInput", ...
        "Summary input is missing required field ""%s"".",name);
end
value = source.(name);
end

function value = fieldOr(source, name, defaultValue)
if isfield(source, name)
    value = source.(name);
else
    value = defaultValue;
end
end

function value = conditionalField(source, name, applicable)
if applicable && isfield(source, name)
    value = source.(name);
else
    value = NaN;
end
end

function value = conditionalTextField(source, name, applicable)
if applicable && isfield(source, name)
    value = string(source.(name));
else
    value = "";
end
end

function value = conditionalValue(candidate, applicable)
if applicable
    value = candidate;
else
    value = NaN;
end
end

function value = textField(source, name, defaultValue)
value = string(fieldOr(source, name, defaultValue));
end

function value = indexedValue(values, index)
if numel(values) >= index
    value = values(index);
else
    value = NaN;
end
end

function values = rowVector(values)
values = reshape(values, 1, []);
end

function values = defaultChannelProportions(channelCount)
if channelCount == 1
    values = 1;
else
    values = nan(1, channelCount);
end
end

function value = radioAccessMode(simParams)
technology = requiredField(simParams, "technology");
mode5G = fieldOr(simParams, "mode5G", 0);
switch technology
    case 1
        if mode5G == 1
            value = "NR-V2X";
        else
            value = "LTE-V2X";
        end
    case 2
        value = "80211p";
    case 3
        value = "COEX-NO-INTERF";
    case 4
        if mode5G == 1
            value = "COEX-STD-INTERF-5G";
        else
            value = "COEX-STD-INTERF";
        end
    otherwise
        value = "Unknown";
end
end

function value = simulatorVersion(simParams)
